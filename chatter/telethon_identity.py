"""Отпечаток устройства для Telethon — прибит константами.

Зачем. Telethon 1.44 собирает `InitConnectionRequest` из `platform.uname()` и
собственной версии:

    device_model   = 'PC 64bit' | 'PC 32bit' | <machine>     # по архитектуре
    system_version = re.sub(r'-.+', '', system.release)      # по ОС
    app_version    = telethon.__version__                    # по версии либы

Отпечаток менялся сам, по трём независимым причинам:
  * смена ОС — `system_version` с '11' на версию ядра Linux;
  * смена архитектуры — x86_64 → aarch64 меняет `device_model`;
  * `pip upgrade telethon` — меняет `app_version` вообще без смены хоста.

Telegram показывает эти поля владельцу аккаунта в «Активных сессиях». Дрейф
делает историю сессий нечитаемой, а при переносе хоста аккаунт видит «новое
устройство» на том же auth_key.

⚠️ Честная граница. Это поля-ЯРЛЫКИ, а не фактор аутентификации: сама по себе
их смена сессию не разлогинивает и повторную авторизацию не запускает —
auth_key остаётся валидным. Пин убирает шум и делает поведение
детерминированным на любом хосте; он не «защита от разлогина».

Значения — СНИМОК того, что эти сессии уже рекламируют сегодня
(`platform.uname()` на прод-хосте даёт machine='AMD64' → 'PC 64bit',
release='11'). Выбраны так намеренно: пин не меняет НИЧЕГО на живых сессиях
сейчас и замораживает состояние на будущее. Содержательного смысла в них нет
и не должно быть — ценна только неизменность. Менять их — значит менять
ярлык живых сессий, поэтому без нужды не трогать.
"""
from __future__ import annotations

DEVICE_MODEL = "PC 64bit"
SYSTEM_VERSION = "11"
APP_VERSION = "1.44.0"


def identity_kwargs() -> dict[str, str]:
    """kwargs отпечатка для конструктора TelegramClient.

    Возвращает СВЕЖИЙ словарь: вызывающие домешивают своё через
    `**identity_kwargs()`, а общий мутируемый объект протёк бы между клиентами."""
    return {
        "device_model": DEVICE_MODEL,
        "system_version": SYSTEM_VERSION,
        "app_version": APP_VERSION,
    }
