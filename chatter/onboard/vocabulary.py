    # knowledge в другом смысле — «орієнтир по вартості». Решение владельца:
    # это ОМОНИМ, сущности разные, и разводить их надо словами, а не проверкой.
    # «Як нас знайти» несёт ровно тот смысл, который нужен лиду, и ни с чем не
