"""ОДИН источник правды для обязательных фактов и разделов.

Зачем отдельный модуль, а не константы по месту. Один и тот же список нужен
ТРЁМ слоям сразу: `render` пишет заглушку по недостающему факту (R7) и
обязательные разделы (R8), `report` кладёт по тому же факту строку в раздел 3,
`checks` сверяет парность «заглушка ⇔ строка отчёта» (C10) и наличие разделов
(C11).

Три копии одного списка — это «два числа на одну вещь». Меньшее гасит большее
молча: список в `checks` разойдётся со списком в `render`, и проверка станет
зелёной не потому, что всё на месте, а потому, что она спрашивает не про то.
Сторож обязан стоять НА РАЗМЕТКЕ, а разметка обязана быть одна.

Заголовки взяты ИЗ ЖИВОГО ЭТАЛОНА `chatter/clients/yarina/knowledge.md`, а не
придуманы: приёмка арки (§6) сравнивает генератор именно с ним, и выдуманная
формулировка дала бы расхождение на ровном месте.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class RequiredFact:
    """Факт, без которого бот врёт или молчит.

    `source` — id поля брифа ИЛИ None. None здесь не «забыли заполнить», а
    факт из спеки: **список обязательных фактов НЕ совпадает со списком
    вопросов формы**. Адреса, телефона и канала записи в форме нет вообще, а
    нужны они всегда. Именно поэтому нельзя вывести обязательные факты из
    схемы формы — их приходится объявлять.
    """

    id: str
    title_uk: str
    source: str | None
    question_for_client_uk: str


# Порядок значим: в этом же порядке факты идут в раздел 3 отчёта, и два
# прогона одного брифа обязаны давать построчно сравнимые отчёты.
