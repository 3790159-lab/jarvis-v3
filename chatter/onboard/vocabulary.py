# Формула заглушки. ОДНА на все факты и на языке клиента: `checks` ищет в
# knowledge именно её, и вторая формулировка сделала бы C10 слепой.
#
# 🔴 `{owner}` — ИМЕНИТЕЛЬНЫЙ падеж, то есть `owner_id` («Старший майстер»), а
# НЕ `owner_ref`. Это не придирка к стилю: в конфиге клиента живут ДВА разных
# значения на одну роль, и путать их нельзя.
#   owner_id  — именительный, стоит подлежащим: «називає старший майстер»;
#   owner_ref — ОРУДНЫЙ, годится только после предлога: «зв'яжу вас з нашим
