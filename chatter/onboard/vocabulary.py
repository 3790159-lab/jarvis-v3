# генератор выводит ref из id и получает именительный — то есть дефект ждал
# ровно того момента, когда владелец поправит ref на правильный орудный, как
# того требует живой конфиг Ярины. Склонять программно мы не будем (спека §5),
# значит выбирать нужную форму обязан ВЫЗЫВАЮЩИЙ, и имя плейсхолдера обязано
# ему об этом сказать.
