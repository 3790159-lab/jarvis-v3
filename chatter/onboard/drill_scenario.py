# -*- coding: utf-8 -*-
"""T6: ЗАГОТОВКА дрил-сценария из брифа, сгенерированного конфига и отчёта.

Решение владельца 17.08 (вопрос 1 спеки): заготовку ГЕНЕРИРУЕМ, человек правит.
Пять ходов: цена → выбор услуги → готовность записаться → **контрольный вопрос
из раздела 3 отчёта** → просьба скидки.

Вся ценность модуля в четвёртом ходе. Первые три и пятый — типовая воронка ниши,
их можно было бы держать литералом. Контрольный ход держать литералом НЕЛЬЗЯ: он
обязан спрашивать бота ровно про то, чего в его базе НЕТ, а «чего нет» знает
только этот прогон — раздел 3 отчёта и заглушки в knowledge «Чого ми НЕ знаємо».
Литерал устарел бы в тот день, когда клиент дал адрес, и дрил начал бы проверять
факт, который бот теперь законно знает.

ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не судит бота. Судит `chatter.core.drill`, и его
словарь `EXPECT_KEYS` ЗАКРЫТ: «ответ не содержит выдуманного адреса» проверкой
не является и являться не может. Поэтому заготовка расставляет ровно те
ожидания, которые харнесс умеет считать (ход состоялся, дубля нет, классификатор
не сбоил, карточка пришла), а главный вопрос дрила — не выдумал ли бот то, чего
не знает, — снимается ГЛАЗАМИ по тексту, реально ушедшему лиду. Об этом сказано
в шапке сгенерированного yaml, потому что читать её будет человек, а не код.

Спека: `docs/superpowers/specs/2026-08-14-chatter-onboarding-pipeline.md`, §4 C7
(что автоприёмка проверяет в сценарии) и §5 (тон и правдоподобие — только
человек, живой дрил и деплой — не наша граница).
"""
