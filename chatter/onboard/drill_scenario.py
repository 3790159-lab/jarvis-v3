def _wrap(text: str, width: int) -> list[str]:
    words, out, cur = text.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            out.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}" if cur else w
    if cur:
        out.append(cur)
    return out or [""]


# ─────────────────────────────────────────────────────────────────────────────
# Сторож собственных реплик
# ─────────────────────────────────────────────────────────────────────────────

def _assert_sane(scenario: dict) -> None:
    """Пять запретов из шапки модуля, проверенные на собственном выходе.

    Это НЕ замена независимому сторожу арки: тот пишется от спеки и другим
    человеком, потому что тест и код одного автора наследуют одно неверное
    допущение. Здесь — предохранитель против опечатки в шаблоне, которая иначе
    уехала бы в файл, дошла до живого прогона и покрасила работающего бота.
    """
    steps = scenario.get("steps") or []
    if not steps:
        raise DrillScenarioError("[onboard] drill: сценарий без шагов")
    for i, step in enumerate(steps, 1):
        say = step.get("say") or ""
        if not say.strip():
            raise DrillScenarioError(f"[onboard] drill: шаг {i}: пустая реплика")
        if "\n" in say or "\r" in say:
            raise DrillScenarioError(
                f"[onboard] drill: шаг {i}: реплика многострочная — лид шлёт "
                "построчно, стенд её не отправит")
        if not any(ch.isalpha() for ch in _normalize_say(say)):
            raise DrillScenarioError(
                f"[onboard] drill: шаг {i}: после нормализации не остаётся букв "
                "— `match_step` такой шаг не опознает, и он будет красным при "
                "работающем боте (DEV-32)")
        if any(ch.isdigit() for ch in say):
            raise DrillScenarioError(
                f"[onboard] drill: шаг {i}: цифра в реплике лида — цены в "
                "репликах только из прайса, а проще всего это держать полным "
                "запретом на числа")
        expect = step.get("expect") or {}
        unknown = sorted(set(expect) - EXPECT_KEYS)
        if unknown:
            raise DrillScenarioError(
                f"[onboard] drill: шаг {i}: проверок {unknown} нет в закрытом "
                "словаре — `parse_scenario` такой сценарий не примет")
        if not expect:
            raise DrillScenarioError(
                f"[onboard] drill: шаг {i}: ни одной проверки")
        if "obligations" in expect or "obligations_unchanged" in expect:
            raise DrillScenarioError(
                f"[onboard] drill: шаг {i}: ожидание про слот обязательств "
                "генератор поставить не может — оно самоподтверждается на "
                "живом контакте")


# ─────────────────────────────────────────────────────────────────────────────
# YAML
# ─────────────────────────────────────────────────────────────────────────────
#
# Печатаем сами, а не `yaml.safe_dump`. Причина одна и она важнее аккуратности:
# заготовку правит ЧЕЛОВЕК, а `safe_dump` не умеет комментариев — то есть
# выбросил бы и шапку («что вычитать»), и построчные пояснения к ходам, ради
# которых живые сценарии вообще читаемы. Значения при этом кодируются
# `json.dumps`: JSON-строка — законный YAML-скаляр в двойных кавычках, и
# апострофы с кириллицей она экранирует правильно.

def render_yaml(scenario: dict) -> str:
    if not isinstance(scenario, dict):
        raise DrillScenarioError(
            f"[onboard] drill: render_yaml ждёт сценарий-объект, получено "
            f"{type(scenario).__name__}")
    out: list[str] = [f"# {line}".rstrip() for line in scenario.get("header") or []]
    if out:
        out.append("#")
    out.append(f"name: {_scalar(scenario.get('name'))}")
    out.append(f"client: {_scalar(scenario.get('client'))}")
    out.append(f"contact: {_scalar(scenario.get('contact'))}")
    out.append("steps:")
    for step in scenario.get("steps") or []:
        out.append("")
        for note in step.get("note") or []:
            out.append(f"  # {note}".rstrip())
        out.append(f"  - say: {_scalar(step.get('say'))}")
        expect = step.get("expect") or {}
        if expect:
            out.append("    expect:")
            for key in sorted(expect, key=lambda k: sorted(EXPECT_KEYS).index(k)):
                out.append(f"      {key}: {_value(expect[key])}")
    return "\n".join(out) + "\n"


def _scalar(value) -> str:
    return json.dumps("" if value is None else str(value), ensure_ascii=False)


def _value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_scalar(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k}: {_value(v)}" for k, v in value.items()) + "}"
    return _scalar(value)
