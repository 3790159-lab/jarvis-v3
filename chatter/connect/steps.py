"""STEPS — карта подключения S0…S15 в ЕДИНСТВЕННОМ порядке исполнения (§3, §12.1).

Список ЛИТЕРАЛЬНЫЙ, и это главное решение этого файла. Собрать его интроспекцией
`probes` (найти всё, что зовётся `probe_s*`, отсортировать по номеру) было бы
короче на двадцать строк и бесполезно: выведенный список согласен с реализацией
ПО ОПРЕДЕЛЕНИЮ и промолчит ровно там, где о шаге забыли —
[[jarvis-literal-lists-not-introspection]]. Забытый шаг обязан выглядеть как
дыра в карте, а не как карта без дыры.

Порядок менять нельзя: каждая строка опирается на факт предыдущей, и цена
перестановки уже названа в §6. Опасное состояние ровно одно — «в реестре
`enabled: true`, а конфига или сессии нет»: гардиан читает реестр каждые ~30 с
и уходит в цикл подъёма. Поэтому запись в реестр (S10) и подъём (S11) стоят
ПОСЛЕ переноса конфига (S4) и логина (S6), а открытие трафика (S15) не стоит
нигде — оно вне команды навсегда (§5.5).

Что этот модуль проверяет ПРИ ИМПОРТЕ (и падает громко, DEV-18):

* состав и порядок id — ровно `S0…S15`, без пропусков, без повторов;
* множество автошагов из колонки `owner` совпадает с литеральным множеством
  §3 (`S4, S9, S10, S11, S12, S13` — ровно шесть);
* инвариант «AUTO <=> act is not None» — в `Step.__post_init__` (model.py);
* `TAIL_HUMAN_IDS` — действительно ХВОСТ карты и действительно человеческий;
* проба и действие пришиты К СВОЕМУ шагу: `probe_s9` не может оказаться на S10.

Последняя проверка сделана здесь, а не в `Step`, намеренно: она опирается на
имена функций из контракта §12.1 и не должна мешать чужому коду собирать свои
`Step` с лямбдами.
"""
