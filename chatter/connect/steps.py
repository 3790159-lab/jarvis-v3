def _check_contract(steps: tuple[Step, ...]) -> None:
    """Сверка литеральной карты с литеральными ожиданиями §3. Падает громко.

    Молчаливое расхождение здесь стоило бы дороже любой ошибки исполнения:
    кривой порядок не виден в выводе — он виден у клиента.
    """
    ids = tuple(s.id for s in steps)
    if ids != STEP_ORDER:
        raise ConnectContractError(
            "порядок шагов разошёлся с картой §3: "
            f"ожидалось {STEP_ORDER}, собрано {ids}. Порядок единственный, "
            "каждая строка опирается на факт предыдущей (§3, §6)"
        )

    auto_by_owner = frozenset(s.id for s in steps if s.owner == Owner.AUTO)
    if auto_by_owner != AUTO_STEP_IDS:
        # Именно эта сверка ловит то, чего не видит `Step.__post_init__`:
        # шаг, у которого owner и act согласованы между собой, но оба
        # разошлись со спекой — «дописали действие человеческому шагу».
        # Сортировка по НОМЕРУ, а не по строке: алфавит ставит S10 перед S4 и
        # превращает сообщение о порядке в загадку.
        def by_number(ids: frozenset[str]) -> list[str]:
            return sorted(ids, key=lambda sid: int(sid[1:]))

        raise ConnectContractError(
            "множество автошагов разошлось с §3: ожидалось "
            f"{by_number(AUTO_STEP_IDS)}, собрано {by_number(auto_by_owner)}. "
            "Автоматических шагов ровно шесть, остальные закрывает человек по "
            "конструкции (§5, список закрытый)"
        )

    # Хвост обязан быть именно хвостом: пропуск шага, который стоит В СЕРЕДИНЕ,
    # тихо снял бы ворота — а на эту константу опирается цикл §12.3.
    if ids[-len(TAIL_HUMAN_IDS):] != TAIL_HUMAN_IDS:
        raise ConnectContractError(
            f"TAIL_HUMAN_IDS={TAIL_HUMAN_IDS} — не последние шаги карты (хвост карты: {ids[-len(TAIL_HUMAN_IDS):]}). "
            "Цикл §12.3 пропускает эти id: стоящий в середине шаг был бы пропущен вместе с его воротами"
        )
    for tail_id in TAIL_HUMAN_IDS:
        tail = next(s for s in steps if s.id == tail_id)  # состав уже сверен с STEP_ORDER выше
        if tail.owner != Owner.HUMAN:
            raise ConnectContractError(
                f"{tail_id}: хвостовой шаг объявлен {tail.owner.value} — §12.10 п.1 выносит из цикла ровно то, "
                "что закрывается словом владельца, а не фактом; автошаг, вынесенный из цикла, не исполнится никогда"
            )

    for step in steps:
        # Инвариант AUTO <=> act держит `Step.__post_init__`; здесь — только
        # его следствие в терминах карты, чтобы сообщение называло спеку.
        if step.is_auto != (step.act is not None):  # pragma: no cover — недостижимо, пока жив Step.__post_init__
            raise ConnectContractError(
                f"{step.id}: нарушен инвариант «AUTO <=> act is not None» (§3, §12.2)"
            )

        suffix = step.id.lower()
        probe_name = getattr(step.probe, "__name__", "")
        if probe_name != f"probe_{suffix}":
            raise ConnectContractError(
                f"{step.id}: пришита проба {probe_name or step.probe!r}, ожидалась probe_{suffix} (§12.1). "
                "Проба от соседнего шага читает не тот факт и закрывает шаг чужим доказательством"
            )
        if step.act is not None:
            act_name = getattr(step.act, "__name__", "")
            if act_name != f"act_{suffix}":
                raise ConnectContractError(
                    f"{step.id}: пришито действие {act_name or step.act!r}, ожидалось act_{suffix} (§12.1). "
                    "Действие от соседнего шага меняет диск не там, где обещала карта"
                )


_check_contract(STEPS)


