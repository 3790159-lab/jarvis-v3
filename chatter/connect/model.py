# -*- coding: utf-8 -*-
"""Данные и типы подключения: Verdict, Owner, StepResult, Step, Ctx, CommandRunner.

Контракт §12.2 спеки `2026-08-20-t7-turnkey-connect.md`. Имена и формы взяты
оттуда дословно, потому что сторожа и плановый код пишут РАЗНЫЕ авторы
([[jarvis-guards-not-by-the-plan-author]]): разойдись здесь на одно поле — и
сторож проверит фантом, а код окажется правильным про другое.

Модуль не делает ввода-вывода и не импортирует ничего из `chatter`: только
stdlib. Требование не косметическое — `model` обязан импортироваться на голой
машине, без конфигов, без секретов и без ещё не написанных `probes`/`actions`.

Здесь же живут ДВА структурных инварианта, которые дешевле держать в типе, чем
в договорённости:

1. **AUTO <=> `act is not None`** (§3, §12.2). Шаг без действия — человеческий
   по определению; шаг с действием не имеет права называться человеческим.
2. **Непустое «что сделать» у любого не-CLOSED** (§12.4, сторож Д11).
   Остановка печатает ровно три строки, и третья из них — `todo`.

Оба нарушения — ошибка КОДА, а не состояние мира, поэтому падают громко
(DEV-18: не глотать, а говорить), а не превращаются в вердикт.
"""
from __future__ import annotations

import enum
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol, runtime_checkable


class ConnectContractError(ValueError):
    """Нарушение контракта §12 внутри собственного кода подключения.

    Отдельный класс, а не голый `ValueError`, чтобы такая поломка не сливалась
    с разбором чужих данных: «в конфиге клиента мусор» и «мы сами собрали шаг
    неправильно» требуют разной реакции. Наследование от `ValueError` оставлено
    намеренно: широкий `except ValueError` вокруг разбора не должен внезапно
    начать пропускать эту ошибку мимо себя незамеченной.
    """


class Verdict(str, enum.Enum):
    """Вердикт пробы: что показали ФАКТЫ НА ДИСКЕ, а не память процесса (§1).

    Наследование от `str` намеренно: вердикт попадает в вывод и в журнал, и
    сравнение с сырой строкой обязано работать — иначе автор, сравнивший с
    литералом, разошёлся бы с кодом на пустом месте.
    """

    CLOSED = "закрыт"
    OPEN = "не закрыт"
    CONFLICT = "противоречие"


class Owner(str, enum.Enum):
    """Кто ЗАКРЫВАЕТ шаг — не кто его проверяет (§3, пояснение под таблицей).

    S0 и S1 проверяются автоматом целиком, но закрывает их человек: секрет в
    `.env` кладёт владелец, конфиг собирает `chatter.onboard`. Автоматического
    действия у них нет, и выдумывать его нельзя: `connect`, умеющий сам
    пересобрать конфиг, однажды пересоберёт вычитанный.
    """

    AUTO = "автомат"
    HUMAN = "человек"


@dataclass(frozen=True)
class CommandResult:
    """Результат внешнего вызова: код возврата и оба потока, без интерпретации.

    Интерпретация — дело шага: реестр закрывается не «файл записан», а
    `runnable=true, error=null`; подъём — не «скрипт отработал», а прошедший
    замер радиуса (§2.2). Здесь только сырьё для этих утверждений.
    """

    rc: int
    stdout: str = ""
    stderr: str = ""


@runtime_checkable
class CommandRunner(Protocol):
    """ЕДИНСТВЕННЫЙ путь наружу: подпроцессы только через него (§12.2).

    Прямой `subprocess` в `probes.py`/`actions.py` запрещён, и запрет не про
    аккуратность: именно он делает сторожей возможными без живых процессов —
    без Telegram, без гардиана, без денег. Подменяемый раннер и есть граница
    между «проверили механику ворот» и «подняли живого клиента».

    `timeout` обязателен по той же причине, что и `cwd`: вызов без потолка
    времени однажды повиснет внутри шага, и подключение встанет молча — без
    строки в выводе и без кода возврата, то есть ровно тем способом, ради
    борьбы с которым арка и затевалась.
    """

    def run(self, argv: list[str], *, cwd: Path, timeout: float) -> CommandResult:
        ...


@dataclass(frozen=True)
class StepResult:
    """Итог пробы или действия одного шага.

    `why` — ОДНА строка: какой факт есть или отсутствует И чем это грозит.
    Вторая половина обязательна: «CONSENT.md нет» человек прочитает как
    бюрократию, «бот читает всю личку аккаунта, а факта согласия нет» — как
    причину.

    `todo` — что сделать; НЕПУСТО у любого не-CLOSED (§12.4, Д11). Проверяется
    тут же, в `__post_init__`.

    🔴 `facts` — машиночитаемые улики: пути, признаки, числа. **СЕКРЕТОВ ТУТ НЕ
    БЫВАЕТ НИКОГДА** (§12.5). Ни токена, ни пароля, ни содержимого `.env`, ни
    строки сессии — ни целиком, ни куском, ни «первыми четырьмя символами».
    Если шагу нужен признак секрета, признак — это ДЛИНА и НЕПУСТОТА:

        facts = {"token_env": "CHATTER_CONTROL_BOT_TOKEN_ACME",
                 "token_present": True, "token_len": 46}   # <- так
        facts = {"token": "123456:AA..."}                  # <- НИКОГДА

    Причина механическая, а не этическая: `facts` уходит в вывод, в журнал
    `state/connect/<slug>.md` и в вывод сторожей — три места, где секрет
    переживёт само подключение и где его никто не будет искать. Имя переменной
    секретом не является, значение — является; путь к `.session` не является,
    его содержимое — является.

    `facts` — единственное, на что сторожа опираются в тонких утверждениях;
    `why`/`todo` они проверяют на непустоту и адресность, но НЕ на дословный
    текст (§12.2): сторож на буквы сообщения превратил бы правку формулировки
    в красное.

    `waits_for_human` — АДРЕСАТ следующего действия, а не состояние факта
    (§12.7 п.1). Появилось из дыры в алгоритме §12.3: у автошага не было ветки
    «жду разрешения человека», и денежные ворота S13 (`act_s13` без
    `--drill-yes`) отдавали бы код 1 «ПРОТИВОРЕЧИЕ» на штатном пути — ровно то
    слипание «жду тебя» и «сломано», ради которого владелец и разводил коды
    решением q2. Флаг ставит и проба, и действие; порядок §12.3 читает оба и
    выходит с кодом 3.

    Почему булево, а не четвёртый `Verdict`: факт на диске от ожидания не
    меняется — дрил не прогнан и в обоих случаях `не закрыт`. Четвёртый
    вердикт заставил бы каждую пробу решать, какой из двух он теперь возвращает,
    и первая же забывчивость дала бы «ждёт человека» там, где всё сломано.

    Поле НЕ отменяет `todo`: именно в этой ветке человеку и нужно сказать
    «повтори с `--drill-yes`», поэтому `__post_init__` требует «что сделать» и
    при `waits_for_human=True` — даже если вердикт вдруг CLOSED.
    """

    step_id: str
    verdict: Verdict
    why: str
    todo: str
    facts: dict[str, Any] = field(default_factory=dict)
    # Поле дописано В КОНЕЦ намеренно: позиционный порядок полей §12.2 не
    # сдвигается, и чужой код, собиравший StepResult позиционно, не начинает
    # молча класть булево в `facts`.
    waits_for_human: bool = False

    def __post_init__(self) -> None:
        if not str(self.step_id).strip():
            raise ConnectContractError(
                "StepResult.step_id пуст: результат без шага нельзя ни напечатать, ни отнести к строке карты §3"
            )
        # Пустое «почему» превращает остановку в «сломано, разбирайся сам»:
        # человек читает три строки §12.4 и не узнаёт из них ничего.
        if not str(self.why).strip():
            raise ConnectContractError(
                f"{self.step_id}: StepResult.why пуст — остановка обязана называть факт и чем его отсутствие грозит"
            )
        # Д11 держится СТРУКТУРНО, по всем ветвям, а не на трёх примерах:
        # проверка стоит в типе, поэтому мимо неё не пройдёт ни одна ветка ни в
        # пробе, ни в действии — включая ту, о которой автор не вспомнил.
        # `or self.waits_for_human` — не перестраховка: ожидание человека без
        # «что сделать» это остановка «жду тебя», не говорящая, чего именно
        # ждут (§12.7 п.1 — там как раз «передай --drill-yes»).
        if (self.verdict != Verdict.CLOSED or self.waits_for_human) and not str(self.todo).strip():
            # `getattr(..., "value", ...)` — не украшательство: у str-Enum
            # `str()` печатает «Verdict.OPEN», то есть имя ветки кода вместо
            # слова, которым вердикт назван в спеке и в выводе.
            shown = getattr(self.verdict, "value", self.verdict)
            if self.waits_for_human:
                shown = f"{shown}, ждём человека"
            raise ConnectContractError(
                f"{self.step_id}: вердикт «{shown}» без «что сделать» — §12.4 требует третью строку у КАЖДОЙ остановки"
            )

    @property
    def is_closed(self) -> bool:
        """Закрыт ли шаг фактом. Сравнение через `Verdict`, а не через литерал."""
        return self.verdict == Verdict.CLOSED


@dataclass(frozen=True)
class Step:
    """Строка карты §3: id, заголовок, кто закрывает, проба и (у автошагов) действие.

    `probe` читает факты и НИЧЕГО не пишет на диск (§12.5) — ни файла, ни
    строки журнала. `act` — единственное, чему позволено менять диск, и после
    него проба гоняется ВТОРОЙ раз: «команда отработала» и «факт появился» —
    разные утверждения (§12.3).
    """

    id: str
    title: str
    owner: Owner
    probe: Callable[[Ctx], StepResult]
    act: Callable[[Ctx], StepResult] | None = None

    def __post_init__(self) -> None:
        if not str(self.id).strip():
            raise ConnectContractError(
                "Step.id пуст: без стабильного id шаг нельзя ни назвать в остановке, ни найти в карте"
            )
        if not str(self.title).strip():
            raise ConnectContractError(
                f"{self.id}: Step.title пуст — первая строка остановки §12.4 состоит из id и заголовка"
            )
        if not callable(self.probe):
            raise ConnectContractError(f"{self.id}: Step.probe не вызываем — шаг без пробы не проверяется ничем")
        if self.act is not None and not callable(self.act):
            raise ConnectContractError(f"{self.id}: Step.act задан, но не вызываем")
        # Инвариант §3/§12.2 стоит в единственном месте, которое нельзя обойти:
        # любой Step, откуда бы он ни собирался, обязан ему подчиняться.
        # HUMAN с действием — шаг, который закроет себя сам там, где спека
        # требует остановки перед человеком (§5, список закрытый).
        # AUTO без действия — вечный останов: порядок §12.3 видит «не закрыт»,
        # закрывать нечем, и подключение упирается в шаг, у которого нет даже
        # команды для человека.
        if self.owner == Owner.AUTO and self.act is None:
            raise ConnectContractError(
                f"{self.id}: owner=AUTO без act — нарушен инвариант «AUTO <=> act is not None» (§3, §12.2)"
            )
        if self.owner == Owner.HUMAN and self.act is not None:
            raise ConnectContractError(
                f"{self.id}: owner=HUMAN с act — нарушен инвариант «AUTO <=> act is not None» (§3, §12.2): "
                "человеческий шаг закрывает человек"
            )

    @property
    def is_auto(self) -> bool:
        """Автоматический ли шаг. Читается из `owner`, а НЕ выводится из `act`.

        Вывод «есть act => авто» согласился бы с реализацией по определению и
        промолчал бы ровно там, где `owner` проставлен неверно
        ([[jarvis-literal-lists-not-introspection]]). Два представления сводит
        `__post_init__`, а не подмена одного другим.
        """
        return self.owner == Owner.AUTO


@dataclass(frozen=True)
class Ctx:
    """Всё, что шаг знает о мире. Ни одного глобала, ни одного чтения окружения мимо.

    `root` — корень дерева, в котором идёт подключение. Он существует ради
    §9.1: репетиция гоняется в ОТДЕЛЬНОМ корне и не касается ни живого
    реестра, ни живых сессий. Шаг, взявший путь из константы вместо
    `ctx.root`, эту границу пробьёт молча — и узнаем мы об этом на живом
    клиенте.

    `slug` — клиент, которого подключаем. DEV-36 открыт: совпадение имени
    клиента уже зеленило чужой файл, поэтому шаги сверяют слаг ВНУТРИ фактов,
    а не только путь, в котором факт нашёлся.

    `env` — Mapping, а не `os.environ`: подключение читает env-материал, но не
    правит его (секреты вводит владелец, §5.4).

    `runner` — ОБЪЕКТ с методом `run`, отсюда и имя (§12.8 п.4). Форма вызова
    ровно одна: `ctx.runner.run(argv, cwd=..., timeout=...)`. Прежнее имя поля
    (`run`) допускало два законных прочтения — `ctx.run(argv, ...)` как вызов
    самого поля и `ctx.run.run(argv, ...)` как вызов метода, — и два автора
    разошлись по ним МОЛЧА: обе записи выглядят правильными, а падает та, что
    доедет до живого подпроцесса. Имя существительным закрывает вопрос до
    первой строки кода.

    Алиаса и свойства-совместимости здесь нет и не будет: два имени одного
    поля — ровно та болезнь, которую переименование лечит
    ([[jarvis-two-numbers-for-one-thing]]). Пусть старое имя падает
    `AttributeError` громко, а не работает у половины вызывающих.

    `now` — время СНАРУЖИ (unix seconds). Свежесть heartbeat (S12) и разбор
    даты согласия (S5) обязаны быть воспроизводимы: проба, зовущая `time.time()`
    внутри, меняет вердикт сама по себе, а сторож на ней — фон, а не проверка.

    `drill_yes` — разрешение на ОДИН платный прогон (§4, решение владельца q4).
    На диске не запоминается нигде: следующий запуск снова остановится перед
    тратой (Д17). Поэтому флаг и живёт в `Ctx`, а не в состоянии подключения.

    `drill_again` — повтор дрила при УЖЕ имеющемся результате (§2.3, Д3).
    Отдельный флаг, а не «ещё раз --drill-yes»: повтор «на всякий случай» —
    это деньги клиента и посторонний трафик в его БД.
    """

    root: Path
    slug: str
    now: float
    env: Mapping[str, str]
    runner: CommandRunner
    drill_yes: bool = False
    drill_again: bool = False
