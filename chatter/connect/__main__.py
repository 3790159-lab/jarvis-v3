def _journal_path(root: Path, slug: str) -> Path:
    return Path(root) / "state" / "connect" / f"{slug}.md"


def _verdict_word(result: StepResult) -> str:
    """Слово вердикта из спеки, а не имя ветки кода.

    У str-Enum `str()` печатает «Verdict.OPEN»; журнал читает человек, и «не
    закрыт» говорит ему больше, чем имя члена перечисления.
    """
    return str(getattr(result.verdict, "value", result.verdict))


def _fact_lines(facts: dict[str, Any]) -> str:
    parts = []
    for key in sorted(facts):
        value = _one_line(str(facts[key]))
        if len(value) > _FACT_VALUE_LIMIT:
            value = value[:_FACT_VALUE_LIMIT] + "…"
        parts.append(f"{key}={value}")
    return "; ".join(parts)


class Journal:
    """Дописывание в `state/connect/<slug>.md`. ЧЕЛОВЕКУ, а не коду.

    Метода `read` здесь нет и не будет: чтение журнала кодом сделало бы его
    вторым источником истины, и он молча погасил бы первый (§1, Д7). Если
    журнал удалить между запусками, подключение продолжится ровно там же.

    Одна запись на ИСПОЛНЕННЫЙ шаг (§12.10 п.3): действие и доказавшая его
    проба ложатся в ОДИН блок. Прогон, который не исполнил ничего —
    остановился на человеческом шаге, упал на чтении фактов, просто посмотрел
    состояние, — журнала не заводит и не трогает. Иначе повторный вопрос «где
    я» менял бы диск, а спека обещает обратное (Д12).

    Первая запись создаёт файл. До неё на диск не попадает ничего — в том
    числе пустого каталога.
    """

    def __init__(self, path: Path) -> None:
        self.path = path
        self.wrote = False

    def entry(self, title: str, lines: list[str]) -> None:
        stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        block = [f"## {stamp} — {title}"] + [f"- {l}" for l in lines] + [""]
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with open(self.path, "a", encoding="utf-8") as fh:
            fh.write("\n".join(block) + "\n")
        self.wrote = True

    def executed(self, step: Step, done: StepResult, proof: StepResult) -> None:
        """Исполненный шаг: что сделало действие и что увидела проба ПОСЛЕ него.

        Оба результата в одном блоке, потому что человек читает их вместе:
        «команда отработала» и «факт появился» — разные утверждения, и
        расхождение между ними это ровно то, ради чего повторная проба стоит
        в §12.3.
        """
        self.entry(f"{step.id} {step.title}", [
            f"действие: {_verdict_word(done)} — {_one_line(done.why)}",
            f"проба после действия: {_verdict_word(proof)} — {_one_line(proof.why)}",
            f"что сделать: {_one_line(proof.todo) or _one_line(done.todo) or '—'}",
            f"улики: {_fact_lines(dict(done.facts)) or '—'}"])


# ─────────────────────────────────────────────────────────────────────────────
# Порядок исполнения (§12.3) — ЕДИНСТВЕННЫЙ
# ─────────────────────────────────────────────────────────────────────────────

def _waits_for_human(*results: StepResult) -> bool:
    """Хоть один из результатов ждёт ЧЕЛОВЕКА, а не сломался (§12.7 п.1).

    Читаются ОБА — и действие, и проба после него, — потому что знать могут
    оба: действие знает, что не получило разрешения на трату; проба знает, что
    факта нет и появится он только руками человека. Слить эти исходы с
    «сломано» в один код значило бы приучить не смотреть на красное — ровно
    то, против чего решение владельца q2.

    🔴 У CLOSED флаг не читается вовсе: ФАКТ НА ДИСКЕ СТАРШЕ ОЖИДАНИЯ. Шаг
    закрыт — ждать нечего, что бы ни стояло в булевом поле. Иначе забытый
    флаг на закрытом шаге останавливал бы подключение навсегда, и остановка
    была бы про то, что уже случилось.
    """
    return any(bool(getattr(r, "waits_for_human", False))
               and not r.is_closed for r in results)


def _run_pipeline(steps: tuple[Step, ...], tail_ids: tuple[str, ...],
                  make_ctx: Callable[[], Ctx], journal: Journal) -> int:
    """Порядок §12.3 целиком. Возвращает код выхода.

    `ctx` собирается ЗАНОВО перед каждой пробой: `now` — время снаружи, а
    подключение живёт минутами (ожидание живости, дрил). Замороженное на
    старте время сделало бы протухший heartbeat вечно свежим — то есть
    погасило бы ровно тот сторож (Д10), ради которого приёмка живости и
    существует.
    """
    for step in steps:
        if step.id in tail_ids:
            # ПРОПУСКАЕМ, а не обрываем цикл: хвост вынесен из исполнения
            # (§12.10 п.1), но из карты не выкинут — её читает человек в
            # `--plan`, и путь, обрывающийся на дриле, соврал бы про то, чем
            # подключение кончается.
            continue

        ctx = make_ctx()
        result = step.probe(ctx)

        # Единственная ветка, где действие зовётся ПОВЕРХ вердикта пробы:
        # явно запрошенный повтор платного прогона (§4 `--drill-again`, Д3,
        # §12.9 п.8 — пробы флагов не читают, решает порядок исполнения).
        # Требуются ОБА флага: повтор — это тоже трата, и разрешение даёт
        # только `--drill-yes` (Д17). Повтор перекрывает и «закрыт» (прогон
        # был зелёный), и «противоречие» (прогон был красный или прерван) —
        # именно на второй случай проба и указывает человеку `--drill-again`.
        forced = (step.id == DRILL_STEP_ID and step.act is not None
                  and ctx.drill_again and ctx.drill_yes)

        if result.verdict == Verdict.CONFLICT and not forced:
            # Записи в журнале нет: шаг не исполнялся. Строка «посмотрел и
            # ничего не сделал» копилась бы сама по себе и превратила бы
            # журнал в фон (§12.10 п.3).
            _print_stop(step, result)
            return RC_CONFLICT

        if result.is_closed and not forced:
            continue

        if not result.is_closed and step.owner == Owner.HUMAN:
            _print_stop(step, result)
            return RC_HUMAN

        if step.act is None:
            # Недостижимо, пока жив инвариант «AUTO <=> act is not None»
            # (`Step.__post_init__`). Проверка стоит потому, что цена ошибки —
            # молчаливый пропуск шага, а не исключение.
            raise ConnectContractError(
                f"{step.id}: owner={step.owner.value}, а действия нет — "
                f"шаг некому закрыть (§3, §12.2)")

        done = step.act(ctx)

        # ДОКАЗАТЕЛЬСТВО, а не «act не упал» (§12.3): «команда отработала» и
        # «факт появился» — разные утверждения, и сегодня это стоило бы панели.
        # Проба гоняется ДАЖЕ после отказа действия: пробы не пишут на диск
        # (§12.5), стоит это чтения файла, а показывает состояние мира ПОСЛЕ
        # попытки — то самое, с чем человек останется после остановки.
        proof = step.probe(make_ctx())
        journal.executed(step, done, proof)
        if proof.is_closed:
            continue

        # Печатаем ТО, что объясняет: у отказавшего действия в `why` лежит
        # причина (смета дрила, отказ замера радиуса), у пробы — лишь
        # отсутствие факта.
        _print_stop(step, done if not done.is_closed else proof)
        return RC_HUMAN if _waits_for_human(done, proof) else RC_CONFLICT

    return _finish(steps, tail_ids, make_ctx)


def _finish(steps: tuple[Step, ...], tail_ids: tuple[str, ...],
            make_ctx: Callable[[], Ctx]) -> int:
    """Код 0: автоматические шаги закрыты, остались люди из хвоста карты.

    Печатается не «всё готово», а ЧТО ИМЕННО осталось: вычитать текст дрила
    глазами (S14) и открыть трафик (S15). Второе команда не делает ни при
    каком флаге, и человек обязан узнать об этом из вывода, а не из спеки.
    """
    print(f"{PREFIX} ГОТОВО: автоматические шаги подключения закрыты.")
    tail = [s for s in steps if s.id in tail_ids]
    for step in tail:
        result = step.probe(make_ctx())
        mark = "✅" if result.is_closed else "⏳"
        print(f"  {mark} {step.id} {step.title} — "
              + (_one_line(result.why) if result.is_closed
                 else _todo_or_defect(step.id, result.todo)))
    # Записи «ГОТОВО» в журнале нет: журнал ведёт исполненные ШАГИ (§12.10
    # п.3), а итог прогона человек только что прочитал на экране. Сводка сверх
    # этого сделала бы повторный запуск на завершённом подключении пишущим —
    # то есть сломала бы Д12 ради строки, которую никто не ищет.
    return RC_DONE


def _run_plan(steps: tuple[Step, ...], make_ctx: Callable[[], Ctx]) -> int:
    """`--plan`: карта шагов и вердикты. НИ ОДНОГО действия и ни одной записи.

    Пробы не пишут на диск по контракту (§12.5), действия не зовутся вовсе,
    журнал не трогается — поэтому `--plan` безопасен на живом дереве и годится
    как первый взгляд на чужое подключение.

    Код возврата всегда 0 при успешно снятой карте: `--plan` не прогон, он
    ничего не пытался сделать, и «жду человека» здесь не про что. Прочитать
    состояние надо ГЛАЗАМИ — на то он и план.
    """
    ctx = make_ctx()
    print(f"{PREFIX} план подключения «{ctx.slug}» (корень {ctx.root})")
    print(f"{PREFIX} ничего не выполняется: это карта §3 и вердикты проб")
    for step in steps:
        result = step.probe(make_ctx())
        mark = {Verdict.CLOSED: "✅", Verdict.OPEN: "⏳",
                Verdict.CONFLICT: "🔴"}.get(result.verdict, "•")
        print(f"  {mark} {step.id:<3} {step.owner.value:<8} {step.title}")
        print(f"        {_one_line(result.why)}")
        if not result.is_closed:
            print(f"        → {_todo_or_defect(step.id, result.todo)}")
    return RC_DONE


