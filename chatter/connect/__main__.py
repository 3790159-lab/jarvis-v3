def _default_root() -> Path:
    """Корень дерева: `chatter/connect/__main__.py` → на два уровня вверх."""
    return Path(__file__).resolve().parents[2]


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="python -m chatter.connect",
        description="Подключение клиента chatter под ключ (T7).")
    p.add_argument("slug", help="слаг клиента: chatter/clients/<slug>")
    p.add_argument("--plan", action="store_true",
                   help="НИЧЕГО не делать: напечатать карту шагов и вердикты")
    p.add_argument("--drill-yes", action="store_true",
                   help="разрешить ОДИН платный дрил-прогон (~$0.20–0.30)")
    p.add_argument("--drill-again", action="store_true",
                   help="повторить дрил, когда результат уже есть")
    # Не «флаг для шага N», а граница дерева: §9.1 требует репетиции в
    # ОТДЕЛЬНОМ корне, не касающейся ни живого реестра, ни живых сессий.
    # Без ключа корнем остаётся дерево, из которого запущен модуль.
    p.add_argument("--root", default=None,
                   help="корень дерева (по умолчанию — дерево этого модуля)")
    return p


def main(argv: list[str] | None = None, *,
         runner: CommandRunner | None = None,
         root: Path | None = None) -> int:
    """Точка входа §12.7 п.3. `runner=None` — боевой раннер, `root=None` — своё дерево.

    Имя параметра — `runner`, вслед за полем контекста (§12.7 п.3 в редакции
    после §12.8 п.4). Прежнее `run` оставляло ровно ту развилку, ради снятия
    которой поле и переименовали: «функция или объект с методом `run`». Одна
    вещь — одно имя, иначе пара авторов разойдётся на нём второй раз.

    Оба шва существуют ради сторожей: без них проверка форм остановки и кодов
    выхода потребовала бы живых подпроцессов и живого дерева, то есть не
    существовала бы вовсе. `runner` подставляется по ФОРМЕ (`CommandRunner` —
    Protocol), `isinstance` против конкретного класса не спрашивается нигде:
    подставной раннер обязан работать по форме, а не по родству (§12.7 п.7).

    Аргумент `--root` перекрывает параметр `root`: явно набранное человеком
    сильнее умолчания вызывающего кода.
    """
    _setup_stdout()
    args = _build_parser().parse_args(argv)

    slug = str(args.slug).strip()
    if not _SLUG_RE.match(slug):
        # Слаг попадает в ПУТИ (конфиг, сессия, БД, лог). «..» или разделитель
        # каталогов в нём — это правка не того клиента, а то и не того дерева.
        _print_not_run(
            f"слаг «{slug}» не годится: разрешены строчные буквы, цифры, "
            f"дефис и подчёркивание, до 64 знаков — слаг подставляется в пути "
            f"к конфигу, сессии, БД и логу",
            "проверь имя клиента (chatter/clients/<slug>)")
        return RC_NOT_RUN

    if args.drill_again and not args.drill_yes:
        # Повтор дрила — это ТА ЖЕ трата, что и первый прогон, и разрешение на
        # неё даётся только `--drill-yes` (Д17). Говорим это ДО того, как
        # человек уйдёт к телефону ждать прогона, которого не будет: молчаливое
        # «готово» на явную просьбу повторить читается как «повторил».
        print(f"ОСТАНОВ на {DRILL_STEP_ID}: повтор дрил-прогона.")
        print("ПОЧЕМУ: --drill-again просит ПОВТОРИТЬ платный прогон, а "
              "разрешения на трату нет: без --drill-yes дрил не запускается ни разу")
        print("ЧТО СДЕЛАТЬ: добавь --drill-yes к этой же команде; "
              "после этого повтори ту же команду.")
        return RC_HUMAN

    if args.root:
        tree = Path(args.root).resolve()
    elif root is not None:
        tree = Path(root).resolve()
    else:
        tree = _default_root()
    if not tree.is_dir():
        _print_not_run(
            f"корня {tree} нет: читать факты неоткуда, прогон ничего не докажет",
            "укажи существующий корень через --root")
        return RC_NOT_RUN

    journal = Journal(_journal_path(tree, slug))
    try:
        # Импорт ВНУТРИ: сборка карты проверяет контракт при импорте и падает
        # громко (§12.1, §12.6 п.5). Трассировка в лицо человеку, пришедшему
        # подключать клиента, — отказ, который ничего не объясняет.
        from chatter.connect.steps import STEPS, TAIL_HUMAN_IDS

        # Подставленный раннер берётся как есть, по форме протокола: `isinstance`
        # против конкретного класса запретил бы сторожу его же фейк (§12.7 п.7).
        live: CommandRunner = runner if runner is not None else SubprocessRunner()

        def make_ctx() -> Ctx:
            # Форма одна: `ctx.runner.run(...)` (§12.8 п.4). Временной
            # поддержки старого имени поля здесь больше нет — §12.11 п.6.
            return Ctx(root=tree, slug=slug, now=time.time(), env=os.environ,
                       runner=live, drill_yes=bool(args.drill_yes),
                       drill_again=bool(args.drill_again))

        if args.plan:
            return _run_plan(STEPS, make_ctx)
        # Д8 здесь БОЛЬШЕ НЕТ, и это правка, а не упрощение. Отказ «клиент уже
        # работает» переехал в `probe_s0` — внутрь цикла (§12.12 п.1 в
        # редакции 21.08). Стоя ЗДЕСЬ, он был недостижим для всего, что идёт
        # по контракту §12.3: цикл по `STEPS` объявлен единственным порядком
        # исполнения, и сторож на порядок, гоняющий этот цикл, отказа не видел
        # вовсе — конвейер снова переписывал `settings.yaml` живого клиента и
        # доходил до платного дрила в его боевой БД.
        #
        # Побочно это выпрямило и текст: остановка печатается общей формой
        # §12.4 («ОСТАНОВ на S0: …»), а не второй, своей. И `--plan` теперь
        # тоже НАЗЫВАЕТ живого клиента вместо того, чтобы молчать о нём: карту
        # он печатает, ничего не меняя, и код возврата у него всегда 0.
        return _run_pipeline(STEPS, tuple(TAIL_HUMAN_IDS), make_ctx, journal)

    except ConnectContractError as exc:
        # §12.6 п.5 и §12.10 п.4: нарушение контракта — код 2 с человеческим
        # текстом. Требование одно: НАЗВАТЬ, что именно нарушено. Трассировки
        # в лицо человеку, пришедшему подключать клиента, нет — она ничего ему
        # не объясняет.
        where = _record_crash(journal, "контракт нарушен")
        _print_not_run(
            f"контракт нарушен, {exc}",
            "покажи разработчику: это дефект самого подключения, а не состояния "
            "клиента" + (f" (трассировка дописана в {where})" if where else ""))
        return RC_NOT_RUN
    except KeyboardInterrupt:
        # Обрыв обязан быть невидим для результата (§6): факты на диске уже
        # записаны атомарно, следующий запуск продолжит с того же места.
        _record_crash(journal, "прогон прерван с клавиатуры")
        _print_not_run(
            "прогон прерван с клавиатуры — сделанное уже на диске, "
            "недоделанное не начиналось",
            "продолжай той же командой")
        return RC_NOT_RUN
    except Exception as exc:                                   # noqa: BLE001
        where = _record_crash(journal, "прогон упал внутри себя")
        _print_not_run(
            f"прогон упал внутри себя: {type(exc).__name__}: {_one_line(str(exc))}",
            "покажи разработчику: прогон ничего не доказал"
            + (f", трассировка дописана в {where}" if where else ""))
        return RC_NOT_RUN


def _record_crash(journal: Journal, title: str) -> str | None:
    """Трассировка — в журнал, и только если прогон УЖЕ что-то исполнял.

    Два правила сходятся здесь и не спорят: улику не глотаем (DEV-18), но
    прогон, не исполнивший ни одного шага, диска не касается (§12.10 п.3) —
    иначе падение на чтении фактов заводило бы журнал, которого не должно
    быть. Когда исполненные шаги были, журнал уже существует, и стек ложится
    туда же, где человек прочитает, на чём именно остановились.

    Возвращает путь журнала, если запись состоялась, — вызывающий назовёт его
    в «что сделать», а не пообещает вслепую.
    """
    if not journal.wrote:
        return None
    try:
        journal.entry(title, ["трассировка:", "```",
                              *traceback.format_exc().splitlines(), "```"])
        return str(journal.path)
    except OSError:
        # Журнал есть, а дописать не вышло: терять стек совсем хуже, чем
        # показать его в stderr (DEV-18).
        traceback.print_exc()
        return None


