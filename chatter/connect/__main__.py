class RunnerFailure(RuntimeError):
    """Внешний вызов НЕ СОСТОЯЛСЯ: таймаут, ненайденный исполняемый, отказ ОС.

    §12.6 п.3: это исключение, а не `CommandResult` с выдуманным `rc`. Ловит
    его вызывающее действие и превращает в CONFLICT — «замер не состоялся» и
    «замер сказал нет» обязаны различаться. Выдуманный `rc` слил бы их в одно.
    """


class SubprocessRunner:
    """Единственная реализация `CommandRunner` с настоящими подпроцессами.

    Живёт в CLI, а не в `actions.py`/`probes.py`, и это граница модуля: там
    прямой `subprocess` запрещён (§12.2), потому что подменяемый раннер и есть
    то, что делает сторожей возможными без живых процессов, без Telegram и без
    денег.

    `stdin` закрыт намеренно: ни один вызываемый скрипт ничего не спрашивает с
    клавиатуры (секреты вводит владелец отдельными командами, §5.4), а
    подпроцесс, тихо ждущий ввода, — это подключение, повисшее без строки в
    выводе. `errors="replace"` — потому что вывод у скриптов русский и
    украинский, а консольная кодовая страница под Windows своя.
    """

    def run(self, argv: list[str], *, cwd: Path, timeout: float) -> CommandResult:
        try:
            proc = subprocess.run(
                list(argv), cwd=str(cwd), timeout=timeout,
                stdin=subprocess.DEVNULL, capture_output=True,
                text=True, encoding="utf-8", errors="replace")
        except subprocess.TimeoutExpired as exc:
            raise RunnerFailure(
                f"вызов {argv[0]} не уложился в {timeout:.0f} с") from exc
        except OSError as exc:
            raise RunnerFailure(f"вызов {argv[0]} не выполнился: {exc}") from exc
        return CommandResult(rc=int(proc.returncode),
                             stdout=proc.stdout or "", stderr=proc.stderr or "")


