def _setup_stdout() -> None:
    """Консоль в UTF-8. Под Windows дефолт — cp1251, и первая же украинская
    цитата в `why` убила бы прогон исключением кодека: инструмент падал бы не
    потому, что нашёл дефект, а потому, что не смог о нём сказать."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError, OSError):
            # Поток подменён (pytest capture, пайп) — это не отказ инструмента.
            # Молчание намеренное и ограничено ровно настройкой кодировки.
            pass


def _one_line(text: str) -> str:
    """Схлопнуть в одну строку.

    §12.4 требует РОВНО три строки. Перенос в чужом `why` превратил бы форму
    остановки в четыре строки, и сторож Д11 краснел бы на тексте, а не на
    механике.
    """
    return " ".join(str(text or "").split())


def _todo_or_defect(step_id: str, todo: str) -> str:
    """Третья строка остановки, непустая ВСЕГДА (Д11).

    `StepResult` не даёт создать не-CLOSED без `todo`, так что сюда пустое
    может прийти только из пробелов. Подставляем не «см. спеку», а прямой
    адрес дефекта: человек, пришедший подключать клиента, получит хоть что-то
    исполнимое, а не пустую строку после двоеточия.
    """
    todo = _one_line(todo).rstrip(" .;,")
    if todo:
        return todo
    return (f"у шага {step_id} нет текста «что сделать» — это дефект пробы, "
            f"покажи разработчику")


def _print_stop(step: Step, result: StepResult) -> None:
    """Ровно три строки §12.4 и ничего сверх.

    «Ничего сверх» — не аскеза: остановка это то место, где человек читает и
    решает. Смета дрила, отказ замера радиуса и любая другая улика обязаны
    поместиться в `why` ОДНОЙ строкой — иначе они утонут в выводе, ради борьбы
    с которым арка и затевалась.
    """
    print(f"ОСТАНОВ на {step.id}: {_one_line(step.title)}.")
    print(f"ПОЧЕМУ: {_one_line(result.why)}")
    print(f"ЧТО СДЕЛАТЬ: {_todo_or_defect(step.id, result.todo)}; "
          f"после этого повтори ту же команду.")


def _print_not_run(what: str, todo: str) -> None:
    """Код 2 в форме §12.4: у «не состоялся» шага может не быть вовсе.

    Первая строка без id — прогон не дошёл до карты. Форма сохранена, потому
    что человек читает её глазами, а не разбирает парсером.
    """
    print("ОСТАНОВ: прогон НЕ состоялся.")
    print(f"ПОЧЕМУ: {_one_line(what)}")
    print(f"ЧТО СДЕЛАТЬ: {_todo_or_defect('запуск', todo)}; "
          f"после этого повтори ту же команду.")


