"""Предохранитель тестовых активов (решение владельца 2026-08-10).

Test-реквизиты и заглушки объёма существуют, чтобы Ф0 можно было прогнать
живьём до того, как Ольга пришлёт настоящие тексты и реквизиты. Цена этого
удобства — ровно один класс риска: тестовый актив, уехавший в живой диалог.
Для реквизитов это деньги клиента, ушедшие на посторонний счёт (риск 10.5,
единственный, который может стоить всей суммы счёта).

Поэтому гейт один на все тестовые активы и устроен максимально скучно:
множество дрил-контактов — константа модуля, а НЕ параметр вызова. Если бы
список передавали аргументом, любой вызыватель мог бы открыть шлюз, передав
своё множество, — а фейк, принимающий что угодно, мы уже проходили (урок
«живой смоук до живого прогона»).

Канон списка — `scripts/drill_reset.py:DRILL_CONTACTS`; расхождение держат два
сторожа (`tests/test_drill_contacts_sync.py`, `test_payments_drill_gate.py`).
"""
from __future__ import annotations

# Копия канона. Прод-пакет не импортирует из scripts/ (направление зависимости
# было бы вывернуто), поэтому список продублирован и закреплён тестом.
DRILL_CONTACTS: frozenset[str] = frozenset({
    "telegram:237616472:volska",
    "telegram:8849893367:volska",
    # Тот же дрил-аккаунт «Тест Т 1», но под персоной демо Ярины: суффикс — это
    # ПЕРСОНА, и один аккаунт даёт разные contact_id. Живого доступа строка не
    # открывает никому. Приехала с `f63f347e`, где обновили две копии канона из
    # трёх, — эту забыли, и месяц её держал только сторож.
    "telegram:8849893367:yarina",
})


class NotForProduction(Exception):
    """Тестовый актив запрошен для живого контакта. Всегда громко: молчаливый
    отказ неотличим от успеха (DEV-18), а тихая подстановка «чего-нибудь» —
    это ровно тот исход, ради предотвращения которого гейт и существует."""


def is_drill_contact(contact_id: str | None) -> bool:
    return contact_id in DRILL_CONTACTS


def guard_test_asset(*, contact_id: str | None, what: str) -> None:
    """Пропустить тестовый актив `what` только дрил-контакту.

    Бросает `NotForProduction` для всех остальных, включая пустой и неизвестный
    contact_id: «непонятно кто» — это не «наверное свой»."""
    if not is_drill_contact(contact_id):
        raise NotForProduction(
            f"{what} запрошены для контакта {contact_id!r}, которого нет в "
            f"DRILL_CONTACTS ({', '.join(sorted(DRILL_CONTACTS))}). "
            f"Тестовые активы живым лидам не выдаются никогда")
