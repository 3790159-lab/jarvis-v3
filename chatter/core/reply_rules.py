# -*- coding: utf-8 -*-
"""Правила ответа — ОДИН источник формулировок для промпта и playbook.

Спека: `docs/superpowers/specs/2026-08-17-reply-quality-four-rules.md`
(решения владельца 17.08, пункты 6, 7, 9; пункт 8 — счётчик вопросов —
ОТЛОЖЕН владельцем и здесь намеренно отсутствует).

## Почему модуль, а не строки по месту

Формулировка правила обязана существовать в ОДНОМ экземпляре: две копии
расходятся молча, и в споре «какая настоящая» побеждает найденная первой —
ровно та грабля, что записана как «два числа на одну вещь». Поэтому текст
здесь ровно один, а потребители его импортируют.

## Почему в playbook ССЫЛКА, а не текст правил 1 и 4 (правка 21.08)

Первая редакция клала правила 1 и 4 в playbook ДОСЛОВНО — «человеку, который
правит конфиг, они тоже нужны». Замер показал цену этой заботы: playbook
уезжает в модель ЦЕЛИКОМ (`brain.build_system_prompt`, секция «ПЛЕЙБУК»), и
человеческая копия оказывалась второй копией ДЛЯ МОДЕЛИ. Счёт
`messages.count_tokens` моделью эталона: 299 токенов в системном слое плюс те
же 299 внутри playbook — **каждый ход, у каждого клиента**.

Это ровно тот довод, которым обоснована срезка плейбука 19.08: «отдавать
модели текст, который уже сказан, значит платить за префикс дважды и ничего не
получать взамен». Поэтому правила 1 и 4 живут ТОЛЬКО в системном слое, а
playbook несёт короткую ссылку на них — человек по ней находит источник, а
модель не платит второй раз.

Правило 2 остаётся в playbook текстом, и это не непоследовательность: в
системный слой оно не едет вовсе (`prompt_rules_block` его не содержит), его
исполняет детерминированный список `COMPLAINT_FORBIDDEN_UK`. В playbook оно
единственная копия, а не вторая.

## Почему по-украински

Оба живых клиента (volska, yarina) говорят с лидами по-украински, и правило
про формулировки обязано быть на том языке, на котором формулировки
рождаются. Системный слой промпта при этом русский — смешение языков здесь
осознанное: правило цитируется ДОСЛОВНО, а не пересказывается, иначе «один
источник» перестаёт быть проверяемым.

## Чего тут НЕТ

Проверки «не нарушил ли бот правило» постфактум. Утверждение об услуге не
ловится числовым guardrail'ом («кераміка тримається 2–3 роки» проходит
числовую сверку чисто), а LLM-судья над своим же выходом — не сторож.
Правила 1 и 4 работают НА ВХОДЕ (промпт) и проверяются дрилом; правило 2
про претензию — детерминированное и живёт ниже в этом файле.
"""
from __future__ import annotations

# ═════════════════════════════════════════════════════════════════════════════
# Правило 1 (решение 6). Граница допущений: маршрут — можно, услуга — нельзя
#
# Критерий владельца — не «есть ли это в брифе», а «может ли навредить».
# Маршрутное допущение ведёт к человеку: человек поправит, цена ошибки ноль.
# Допущение об услуге доезжает до клиента: он приедет с ожиданием подбора,
# которого может не быть, и это стоит денег и доверия.
# ═════════════════════════════════════════════════════════════════════════════

ASSUMPTION_BOUNDARY_UK = (
    "Про МАРШРУТ припускати можна: «це до старшого майстра», «він підтвердить», "
    "«уточню в нього» — таке веде до людини, і людина виправить. "
    "Про ПОСЛУГУ припускати НЕ можна: не додумуй, що саме клієнту підійде, "
    "скільки це триває і як «зазвичай роблять». Вигадана послуга їде прямо до "
    "клієнта: він приїде з очікуванням, якого йому ніхто не давав."
)

# ═════════════════════════════════════════════════════════════════════════════
# Правило 4 (решение 9). Предыдущие ответы — не источник фактов
#
# Бот выдумал число один раз; оно попало в историю; на следующем ходу оно уже
# «своё» и звучит увереннее. Так одна ошибка становится фоном всего диалога.
# ═════════════════════════════════════════════════════════════════════════════

HISTORY_IS_NOT_A_SOURCE_UK = (
    "Джерело фактів — тільки розділ ЗНАННЯ. Історія діалогу показує, про що вже "
    "йшлося, але НЕ підтверджує факт: якщо ціну, строк чи умову ти назвав "
    "раніше, а в ЗНАННЯХ їх немає — вони не стають правдою від повторення. "
    "Пріоритет один: ЗНАННЯ → історія → нічого (здогадки немає)."
)

# ═════════════════════════════════════════════════════════════════════════════
# Правило 2 (решение 7). Режим претензии
#
# Повод — живая реплика Ярины: «мушу підключити старшого майстра — він
# розбереться в деталях і вирішить питання компенсації». «Вирішить питання
# компенсації» читается как «компенсация уже согласована»: бот выдал решение,
# которого никто не принимал.
#
# Список — ДАННЫЕ, а не уговор в промпте: уговор нельзя ни проверить, ни
# расширить без правки промпта, и держится он добротой модели.
# ═════════════════════════════════════════════════════════════════════════════

COMPLAINT_TAG = "complaint_promise"

# Хранятся в НОРМАЛИЗОВАННОМ виде (casefold): клиентский текст приходит в любом
# регистре, и «ПОВЕРНЕМО ГРОШІ» обязано ловиться так же, как строчное.
COMPLAINT_FORBIDDEN_UK: tuple[str, ...] = (
    # uk — решение уже принято за владельца
    "вирішить питання компенсації",
    "вирішимо питання компенсації",
    "повернемо гроші",
    "повернемо кошти",
    "компенсуємо",
    "зробимо безкоштовно",
    "переробимо безкоштовно",
    "гарантуємо повернення",
    # ru — тот же смысл, если клиент ведёт диалог по-русски
    "решит вопрос компенсации",
    "вернём деньги",
    "вернем деньги",
    "компенсируем",
    "сделаем бесплатно",
    "переделаем бесплатно",
)

# Разрешённая формулировка передачи. Правило, которое только запрещает,
# оставляет автора без слов: он придумает замену заново и, скорее всего, ту же
# самую. Роль владельца сюда НЕ вшита — она у каждого клиента своя.
COMPLAINT_HANDOFF_UK = (
    "розгляне вимогу і звʼяжеться з вами щодо цієї ситуації"
)


def complaint_promise(reply: str) -> str | None:
    """Оборот претензии в ОТВЕТЕ бота → сам оборот, иначе None.

    Сверяется по ответу, а не по входящему: лид имеет полное право требовать
    возврат этими же словами, и эскалацию его требования делает слой ключевых
    слов. Опасно другое — когда решение о компенсации объявляет БОТ.
    """
    text = (reply or "").casefold()
    for phrase in COMPLAINT_FORBIDDEN_UK:
        if phrase in text:
            return phrase
    return None


def prompt_rules_block() -> str:
    """Строки правил для системного слоя промпта (раздел ПРАВИЛА)."""
    return f"{ASSUMPTION_BOUNDARY_UK}\n{HISTORY_IS_NOT_A_SOURCE_UK}"


# Ссылка на системный слой ДЛЯ ЧЕЛОВЕКА, читающего playbook. Короткая
# намеренно: она тоже уезжает в модель, и длинное объяснение свело бы на нет
# экономию, ради которой правки и делались.
PROMPT_LAYER_NOTE_UK = (
    "Правила про припущення (маршрут — можна, послуга — ні) і про джерело "
    "фактів діють ЗАВЖДИ — вони в системному шарі промпту "
    "(chatter/core/reply_rules.py) і тут навмисно не дублюються."
)


def playbook_rules_block_uk(*, heading: str = "## Правила відповіді") -> str:
    """Блок правил для playbook клиента: ССЫЛКА на правила 1 и 4 плюс текст 2.

    Текста правил 1 и 4 здесь НЕТ намеренно — они уезжают в модель системным
    слоем, а playbook уезжает туда же целиком, и дословная копия стоила бы 299
    токенов каждый ход (см. шапку модуля). Возвращается ГОТОВЫЙ блок, а не
    список строк: собирать его на месте значит завести второе представление
    одного и того же, и оно разъедется.
    """
    return (
        f"{heading}\n"
        f"- {PROMPT_LAYER_NOTE_UK}\n"
        f"- У режимі претензії: не визнавати і не заперечувати провину, нічого "
        f"не обіцяти (повернення, знижку, компенсацію, переробку) і не "
        f"вигадувати рішення. Передати людині: «{COMPLAINT_HANDOFF_UK}»."
    )
