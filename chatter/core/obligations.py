"""Сеть обязательств: ловит, когда Аня ОБЕЩАЕТ то, чего нет в базе знаний —
без привязки к цифрам (аудит 2026-07-18, H1).

Гардрейл цен (`guardrails.py`) видит только ЧИСЛА, поэтому безцифровые обещания
(«могу сделать скидку», «даю гарантию», «перезвоню», «свяжется») проходили
насквозь: промпт их запрещал, но Аня всё равно давала. Нужен КОД, не правило.

Чистая функция, ноль сети — зеркало `brand_safety.forbidden_mention`, подключается
через `escalation.deterministic_escalation` по ОТВЕТУ Ани (не по входящему лида).

КРИТИЧНО (акцент владельца): честный ОТКАЗ обязан проходить. «Скидок нет», «без
гарантий», «рассрочку не делаем», «не могу обещать» — это НЕ обещания, это правда.
Бот, который не может сказать «нет», хуже болтливого (тот же класс, что Сбербанк:
защита, ломающая то, что защищает). Поэтому матч негейт-осведомлён: стем считается
ОБЕЩАННЫМ, только если рядом НЕТ отрицания.
"""
from __future__ import annotations

import re

# Стемы обещаний (подстрока в слове), ru+uk. Клиент может переопределить per-client.
# Намеренно НЕ включены двусмысленные («верн» → «наверное»/«верно» дали бы ложные
# срабатывания) — их безопасный матч требует токен-уровня, вынесен в бэклог.
DEFAULT_PROMISE_TERMS: tuple[str, ...] = (
    # ru
    "скидк", "гарант", "рассрочк", "бесплатн", "подар", "исключени",
    "договорим", "обеща", "перезвон", "свяж", "созвон",
    # uk
    "знижк", "розстрочк", "безкоштовн", "виняток", "домовим", "обіця", "передзвон",
)

# Отрицания рядом со стемом → это отказ, а не обещание (ru+uk).
_NEGATIONS = frozenset({
    "не", "нет", "нету", "без", "нельзя", "невозможно",
    "ні", "немає", "нема",
})

# Насколько близко (в токенах) отрицание должно стоять к стему, чтобы считать
# фразу отказом. 4 — с запасом в сторону «это отказ» (приоритет владельца:
# лучше пропустить обещание, чем подавить честное «нет»).
_NEG_WINDOW = 4

_WORD = re.compile(r"\w+", re.UNICODE)


def _tokens(text: str) -> list[str]:
    return _WORD.findall((text or "").casefold())


def _mentions_positively(tokens: list[str], stem: str) -> bool:
    """Стем встречается в тексте БЕЗ отрицания в окне — т.е. утверждается, а не
    отрицается. «скидок нет» → False (отказ); «сделаю скидку» → True (обещание)."""
    for i, tok in enumerate(tokens):
        if stem in tok:
            lo = max(0, i - _NEG_WINDOW)
            hi = min(len(tokens), i + _NEG_WINDOW + 1)
            if not any(tokens[j] in _NEGATIONS for j in range(lo, hi)):
                return True
    return False


def unbacked_promise(reply: str, knowledge: str, promise_terms) -> str | None:
    """Первый стем-обещание, который Аня УТВЕРЖДАЕТ в ответе и которого НЕТ
    (утвердительно) в knowledge, иначе None.

    - Пустой `promise_terms` → None (слой не задан).
    - Отрицаемый стем («скидок нет», «без гарантий») → НЕ обещание, пропускаем.
    - Стем, УТВЕРДИТЕЛЬНО присутствующий в knowledge (клиент реально предлагает,
      напр. «есть рассрочка») → обеспечен, пропускаем. Стем в knowledge под
      отрицанием («скидок нет») обеспечением НЕ считается.
    """
    if not promise_terms:
        return None
    reply_tokens = _tokens(reply)
    if not reply_tokens:
        return None
    knowledge_tokens = _tokens(knowledge)
    for term in promise_terms:
        stem = (term or "").casefold()
        if not stem:
            continue
        if _mentions_positively(reply_tokens, stem) and not _mentions_positively(knowledge_tokens, stem):
            return term
    return None
