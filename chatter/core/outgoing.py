# -*- coding: utf-8 -*-
"""ЯДРО ДОСТАВКИ: канало-независимая половина отправки из панели.

Спека: `docs/superpowers/specs/2026-08-28-web-d-panel-send.md` §2.1–§2.6.
Предшественница: `2026-08-25-panel-sends.md` §2, §3, §7, §8 — очередь, единая
точка перехвата и порядок «сначала перехват, потом отправка» пришли оттуда и
здесь НЕ пересматриваются, а переезжают из телеграмного раннера.

🔴 ЗАЧЕМ РАЗРЕЗ. До этой арки доставка знала ровно один канал, и знала его не
случайно: пятнадцать строк тела `deliver_outgoing` обращались к клиенту
Telegram напрямую. Пока канал один, это незаметно; на втором канале это
означает вторую очередь рядом с живой. Поэтому доставка режется на ДВЕ вещи:

* **ядро** (этот модуль) — взять строку очереди, проверить адресата, открыть
  перехват, позвать доставщика, разложить исход по трём вердиктам, записать
  историю и атрибуцию. Про адресацию внутри канала (сущности собеседника,
  ключи доступа, токены бизнес-API, открытые вкладки) оно не знает НИЧЕГО и
  знать не имеет права;
* **доставщик канала** — `deliverer_for(channel)`. Единственное место, которое
  знает, чем именно шлют.

ПРОВЕРКА РАЗДЕЛЕНИЯ ОДНИМ ВОПРОСОМ (§2.1): сколько строк надо тронуть, чтобы
добавить Instagram. Ответ обязан быть «одну регистрацию». Ноль строк ЭТОГО
файла — в том числе.

🔴 НИ ОДНОГО СРАВНЕНИЯ КАНАЛА С ЛИТЕРАЛОМ. `if channel == "web"` здесь — это и
есть признак провала, объявленный §1 спеки веба: код, который знает про `web` и
не знает про «канал вообще». Название канала для ядра — ключ словаря и больше
ничего.

КОНТРАКТ `Transport` НЕ РАСШИРЯЕТСЯ (§2.2). Доставка зовёт не транспорт, а
доставщика, и он отдаёт `SentRef`. Шестой abstract-метод сломал бы
`FakeConsoleTransport` и консольный раннер ради одного потребителя.
"""
from __future__ import annotations

import inspect
import logging
from dataclasses import dataclass
from typing import Callable

from chatter.core import contact_ref

log = logging.getLogger("chatter.core.outgoing")


# ── исход отправки ──────────────────────────────────────────────────────────

@dataclass(frozen=True)
class SentRef:
    """Что доставщик отдаёт ядру после УСПЕШНОЙ отправки (§2.2).

    Ровно одно поле, и оно `str | None`. `None` — ЗАКОННЫЙ исход: у канала
    может не быть числовых (и вообще никаких) идентификаторов сообщения, а
    факт отправки от этого не зависит. `Store.mark_outgoing_sent` принимает
    `msg_id: str | None` с 25.08, то есть ядро к этому готово.

    ПОЧЕМУ ОТДЕЛЬНЫЙ ТИП, А НЕ ГОЛАЯ СТРОКА. Голая строка не отличает «ушло,
    id нет» от «не ушло»: оба были бы `None`, и потерянное сообщение
    выглядело бы отправленным. Тип разводит их по построению — «не ушло»
    доставщик обязан сказать исключением (`Refusal` или `Postponed`).
    """

    msg_id: str | None = None


class Refusal(Exception):
    """Отказ доставки: `reason` — литеральный ключ, `human` — текст владельцу.

    Исключение здесь — способ ВЫЙТИ из середины доставки, а не способ
    сообщить о беде наружу: ядро ловит его само и превращает в СОСТОЯНИЕ
    СТРОКИ (`status='refused'`, `last_error` = те же слова). Наружу отказ не
    летит: «не доставлено» без причины отправляет владельца гадать, а
    исключение из фонового цикла он не увидит вовсе.

    Отказ ТЕРМИНАЛЕН по смыслу: он означает «писать физически некуда», а не
    «сейчас не вышло». Для второго есть `Postponed`.
    """

    def __init__(self, reason: str, human: str):
        super().__init__(f"{reason}: {human}")
        self.reason = reason
        self.human = human


class Postponed(Exception):
    """«Сейчас не вышло» — строка остаётся `pending` и уйдёт следующим тиком.

    Отдельным типом от `Refusal`, потому что разница между ними — это разница
    «повтор не поможет» и «поможет ровно повтор». Слив её в один тип означал
    бы либо вечный повтор заведомо мёртвой доставки каждые пять секунд, либо
    молча похороненное сообщение владельца.

    Текст пишет ДОСТАВЩИК: почему именно придержали, знает канал, а не ядро.
    """

    def __init__(self, human: str):
        super().__init__(human)
        self.human = human


# Литеральный набор причин отказа. Шире не выдумывать: `reason` — это ключ, по
# которому владелец однажды спросит «сколько раз и почему», и свободная строка
# превратила бы этот вопрос в разбор текстов. Набор ПЕРЕЕХАЛ из телеграмного
# раннера без единой новой причины, и это осознанно: пара D добавляет каналы,
# а не поводы не доставить.
REFUSAL_REASONS = (
    # клиент выключен в ростере / этим процессом не обслуживается
    "client_disabled",
    # у канала нет доставщика в этом процессе: слать нечем
    "no_transport",
    # канал закрыт для нас: собеседник заблокировал, писать запрещено, окно истекло
    "channel_window_closed",
    # адресата нет: id не разбирается, контакта нет в базе, аккаунт удалён
    "unknown_contact",
)


# ── реестр доставщиков ──────────────────────────────────────────────────────
#
# Словарь, а не цепочка `if`, — ровно затем, чтобы «добавить канал» стоило
# одну строку регистрации В МОДУЛЕ КАНАЛА, а не правку этого файла. Регистрирует
# себя тот, кто умеет слать: доставщик живёт там же, где импорт его библиотеки,
# и в процессе, где этой библиотеки нет, он просто не появится — что и есть
# ответ §2.8 на вопрос «кто сливает очередь».

_DELIVERERS: dict[str, Callable] = {}


def register_deliverer(channel: str, deliverer: Callable) -> None:
    """Объявить, чем этот процесс шлёт в канал `channel`.

    Повторная регистрация ГРОМКАЯ: два доставщика на один канал — это два
    ответа на вопрос «чем шлём», и молча победивший второй отправил бы
    сообщение не тем путём, которым его собирался отправить автор первого.
    """
    if not channel or not isinstance(channel, str):
        raise ValueError(
            "register_deliverer: канал обязан быть непустой строкой, пришло %r"
            % (channel,))
    if not callable(deliverer):
        raise ValueError(
            "register_deliverer: доставщик канала %r не вызываем (%r)"
            % (channel, deliverer))
    existing = _DELIVERERS.get(channel)
    if existing is not None and existing is not deliverer:
        raise ValueError(
            "register_deliverer: у канала %r уже есть доставщик %r — второй "
            "молча победил бы первый" % (channel, existing))
    _DELIVERERS[channel] = deliverer


def unregister_deliverer(channel: str) -> None:
    """Снять доставщик. Нужен стендам: регистрация — глобальное состояние."""
    _DELIVERERS.pop(channel, None)


def deliverer_for(channel: str):
    """Доставщик канала или `None`.

    `None` — не ошибка и не исключение: «этот процесс в этот канал не шлёт» —
    законное и частое состояние (§2.8), и решение, что с этим делать, принимает
    вызывающий: панель говорит заранее, ядро отказывает словами.
    """
    return _DELIVERERS.get(channel)


def registered_channels() -> tuple[str, ...]:
    """Каналы, которыми ЭТОТ процесс шлёт. Порядок стабилен ради логов."""
    return tuple(sorted(_DELIVERERS))


# ── можно ли писать в этот диалог ПРЯМО СЕЙЧАС ──────────────────────────────

def can_send_now(contact_id: str, ctx=None) -> Refusal | None:
    """ОДНА функция на ДВУХ вызывателей (§2.6). `None` = писать можно.

    Панель зовёт её ДО показа поля ввода и говорит заранее «в этот канал
    написать нельзя, потому что …»; ядро — ПЕРЕД отправкой, потому что между
    нажатием и сливом очереди проходит цикл поллинга и состояние успевает
    измениться.

    🔴 ИМЕННО ОДНА. Две реализации одного вопроса разъедутся, и меньшая
    погасит большую МОЛЧА ([[jarvis-two-numbers-for-one-thing]]): панель
    покажет поле ввода там, где доставка откажет, — то есть человек наберёт
    текст и узнает об отказе после отправки.

    `ctx` необязателен и означает «спрашивает процесс, который умеет слать».
    Половина ответа, зависящая от канала (подключён ли он у этого клиента, не
    закрылось ли окно), живёт у ДОСТАВЩИКА и спрашивается у него же — иначе
    правила WhatsApp приехали бы сюда, и ядро снова начало бы знать каналы
    поимённо (§4 спеки).
    """
    try:
        channel = contact_ref.channel_of(contact_id)
    except contact_ref.ContactRefError as exc:
        return Refusal(
            "unknown_contact",
            "адресат не определяется: id диалога %r не разбирается на «в каком "
            "канале», «кому» и «какая персона» (%s)" % (contact_id, exc))
    deliverer = deliverer_for(channel)
    if deliverer is None:
        return Refusal(
            "no_transport",
            "канал «%s» этим процессом не обслуживается — слать нечем" % channel)
    if ctx is not None:
        ask = getattr(deliverer, "can_send_now", None)
        if ask is not None:
            return ask(ctx, contact_id)
    return None


# ── единая точка открытия эпизода перехвата ─────────────────────────────────

def open_human_takeover(store, contact_id: str, *, msg_id, detail: str,
                        now: float, escalate: bool | None = None) -> bool:
    """Открыть эпизод перехвата человеком. `True` = эпизод НАШ (первый).

    ЕДИНСТВЕННАЯ точка открытия эпизода на всё дерево, и вызывателя у неё
    по-прежнему два: «владелец написал сам» (`on_human_takeover` телеграмного
    раннера) и «человек нажал отправить в панели» (ядро доставки ниже).
    Третьего пара D не заводит — доставщик канала своего пути к перехвату не
    получает: его зовёт ядро ПОСЛЕ того, как эпизод открыт (§2.3).

    ПОЧЕМУ ЖИВЁТ В ЯДРЕ, А НЕ В РАННЕРЕ. Внутри ровно две операции над
    `Store` — атомарный захват эпизода и событие в журнал; ни сети, ни
    транспорта здесь нет ни строки. Пока функция жила рядом с телеграмным
    клиентом, ядро доставки не могло её позвать, не притащив за собой всю
    библиотеку канала.

    🔴 КАРТОЧКУ НЕ ШЛЁТ. Решение о карточке принимает ВЫЗЫВАТЕЛЬ, потому что
    ответ у них разный (§9.2, решение владельца 25.08): на сообщение, набранное
    в мессенджере, карточка нужна — владелец мог не заметить, что диалог вёл
    бот; на СОБСТВЕННОЕ нажатие в панели она лишняя и учит жать «да» не глядя
    ([[jarvis-ask-bridge-auto-allow-suspect]]).

    🔴 `escalate` — ЦЕНА ЗАКРЫТИЯ [[jarvis-snooze-eats-the-takeover]] (§2.4).
    У паузы появляется СИЛА: `command`-со-сроком (снуз) слабее, `human_takeover`
    сильнее. Человеческая ОТПРАВКА повышает источник одним `UPDATE` при любом
    исходном состоянии строки — иначе снуз, поставленный десять минут назад,
    съедает перехват: эпизод не открывается, срок доживает до истечения, и бот
    заговаривает поверх человека.

    Повышает НЕ ВСЯКОЕ открытие, и различитель тут не выдуман, а уже лежит в
    сигнатуре: `msg_id`. `msg_id=None` означает «сообщения ЕЩЁ НЕТ» — эпизод
    открывается ПЕРЕД отправкой, а перед отправкой его открывает только
    человек, нажавший кнопку. `msg_id` заполнен — значит сообщение УЖЕ
    улетело, и мы лишь ОПОЗНАЁМ случившееся; присваивать себе чужую паузу
    задним числом такое опознание не вправе, иначе `/pause` владельца молча
    превращается в перехват (сторож
    `test_chuzhaya_pauza_ne_perepisyvaetsya_perehvatom`).

    Параметр всё равно вынесен ЯВНО: правило выше — это умолчание, а не
    единственный способ спросить, и вызыватель, которому нужно иное, обязан
    иметь возможность сказать это словом, а не подделкой `msg_id`.
    """
    if escalate is None:
        escalate = msg_id is None
    started = store.begin_takeover(contact_id, msg_id=msg_id, detail=detail,
                                   now=now, escalate=escalate)
    if started:
        store.add_event("takeover", contact_id=contact_id,
                        detail=None if msg_id is None else str(msg_id), ts=now)
    return started


# ── доставка ОДНОЙ строки очереди ───────────────────────────────────────────

async def deliver(ctx, row: dict, *, now: float) -> str:
    """Один шаг доставки ОДНОЙ строки очереди. Возвращает РОВНО одно из:
    `'sent'` | `'refused'` | `'retry'`.

    `ctx` — контекст процесса: у него спрашивают `primary_store()` и передают
    доставщику как есть. Больше ядру от него ничего не нужно, и это не
    случайность: всё, что зависит от канала, живёт у доставщика.

    🔴 ПОРЯДОК ОБЯЗАТЕЛЕН: сначала `open_human_takeover`, ПОТОМ отправка.
    Обратный порядок оставляет окно, в котором сообщение уже ушло собеседнику,
    а бот ещё не знает, что диалог ведёт человек, — и договаривает поверх него.
    Это тот же класс, что [[jarvis-catchup-reanswers-escalated-dialog]], и он
    опаснее шумного: он тихий. Цена выбранного порядка названа вслух — если
    отправка не удастся, эпизод перехвата останется открытым и бот промолчит.
    Из двух ошибок это дешёвая: лишнее молчание владелец видит и снимает,
    лишний ответ поверх человека он не видит вовсе.

    🔴 ТУМБЛЕРЫ ЗДЕСЬ НЕ СПРАШИВАЮТСЯ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ
    (спека 25.08 §8). `kill_switch`, `funnel_gate` и пауза по контакту —
    выключатели БОТА. Человек, нажавший «отправить», проходит поверх них:
    иначе владелец, выключивший бота, не сможет ответить клиенту сам ровно в
    тот момент, когда это нужнее всего.

    ЧТО ПРОВЕРЯЕТСЯ ДО ПЕРЕХВАТА, А ЧТО ПОСЛЕ. До — всё, что означает «этому
    заданию адресата нет вовсе»: разбор id, наличие доставщика, наличие
    контакта в базе, канальные предусловия доставщика. Такой отказ не имеет
    права оставлять за собой заглушённый диалог: сообщение не ушло и не уйдёт,
    а бот замолчал бы навсегда. После — только то, что случилось В ПРОЦЕССЕ
    отправки, и там молчание уже оплачено порядком (см. выше).
    """
    store = ctx.primary_store()
    row_id = int(row["id"])
    contact_id = str(row.get("contact_id") or "")
    text = (row.get("text") or "").strip()
    try:
        # ТА ЖЕ функция, которой панель отвечает ДО показа поля ввода. Не
        # копия её условий: подмена `can_send_now` обязана менять ОБА ответа,
        # иначе это два числа на одну вещь.
        refusal = can_send_now(contact_id, ctx)
        if refusal is not None:
            raise refusal
        if not store.has_contact(contact_id):
            # `get_or_create_contact` здесь НЕЛЬЗЯ: он завёл бы строку под
            # любую опечатку в id и объявил бы диалогом то, чего нет. Панель
            # берёт contact_id из ленты, поэтому его отсутствие — это не
            # «первый ход», а несовпадение баз.
            raise Refusal(
                "unknown_contact",
                "диалога %s нет в базе этого клиента: панель и раннер смотрят "
                "в разные базы либо контакт удалён" % contact_id)
        channel = contact_ref.channel_of(contact_id)
        deliverer = deliverer_for(channel)

        # ── СНАЧАЛА ПЕРЕХВАТ ─────────────────────────────────────────────
        # msg_id=None честно: сообщения ещё нет. Атрибуция наводится на
        # реальный id ПОСЛЕ отправки (ниже) — выдумывать его сейчас значило бы
        # положить в `pause_msg_id` число, которого в канале не существует.
        started = open_human_takeover(
            store, contact_id, msg_id=None, detail=text[:200], now=now)
        if not started:
            # Эпизод уже идёт — это НЕ повод не отправлять: человек проходит
            # поверх любой паузы. Чужую атрибуцию при этом не трогаем.
            log.info("outgoing #%s: эпизод перехвата уже открыт для %s",
                     row_id, contact_id)

        # ── ПОТОМ ОТПРАВКА ───────────────────────────────────────────────
        # Форма вызова доставщика — часть контракта ядра: `ctx` позиционно
        # (ему нужен тот же контекст процесса), остальное именованно, чтобы
        # добавление поля не переставляло аргументы у всех каналов сразу.
        sent = deliverer(ctx, contact_id=contact_id, text=text, row=row, now=now)
        if inspect.isawaitable(sent):
            # Синхронный доставщик — законный: у канала, который шлёт HTTP из
            # пула потоков, своего цикла событий нет. Ждём только то, что
            # действительно ждётся.
            sent = await sent
        if not isinstance(sent, SentRef):
            # Доставщик, вернувший что угодно вместо `SentRef`, — это «ушло?»
            # без ответа. Считать это успехом значило бы записать в историю
            # неотправленное; считать отказом — похоронить, возможно,
            # доставленное. Поэтому повтор и громкая строка в `last_error`.
            raise Postponed(
                "доставщик канала «%s» ответил %r вместо SentRef — не знаю, "
                "ушло ли; пробую ещё" % (channel, sent))
        msg_id = sent.msg_id
    except Refusal as refusal:
        # Отказ = СОСТОЯНИЕ СТРОКИ. Слова, которые прочитает владелец, и
        # ключ, по которому это можно посчитать, — обе половины сразу.
        store.mark_outgoing_failed(
            row_id, error=refusal.human, now=now, terminal=True)
        store.add_event("outgoing_refused", contact_id=contact_id,
                        detail="#%s %s: %s" % (row_id, refusal.reason, refusal.human),
                        ts=now)
        log.warning("outgoing #%s ОТКАЗ (%s): %s", row_id, refusal.reason,
                    refusal.human)
        return "refused"
    except Postponed as later:
        # «Сейчас не вышло»: строка остаётся в очереди и уйдёт на следующем
        # тике, а причина видна и в логе, и в `last_error`.
        store.mark_outgoing_failed(
            row_id, error=later.human, now=now, terminal=False)
        log.warning("outgoing #%s придержано: %s", row_id, later.human)
        return "retry"
    except Exception as exc:   # noqa: BLE001 — DEV-18: громко и с повтором
        # Всё неназванное — это «сейчас не вышло»: сеть, БД, незнакомая ошибка
        # канала. Молча проглотить нельзя: задание, застрявшее без объяснения,
        # — это ровно та тишина, ради которой очередь и заводилась.
        log.exception("outgoing #%s: доставка сорвалась, оставляю в очереди", row_id)
        store.mark_outgoing_failed(
            row_id, error="%s: %s" % (type(exc).__name__, exc), now=now,
            terminal=False)
        return "retry"

    # ПЕРВЫМ ДЕЛОМ закрываем строку, и только потом всё остальное: каждое
    # действие между «ушло» и «закрыто» — это окно, в котором сбой БД оставит
    # строку `pending`, и следующий тик отправит сообщение ВТОРОЙ раз.
    # Транзакции поверх сетевого вызова у нас нет и быть не может, поэтому окно
    # сужается порядком, а не обещанием.
    store.mark_outgoing_sent(row_id, msg_id=msg_id, now=now)
    # История и `last_human_out_ts` — ПОСЛЕ отправки, а не до: неотправленного
    # в истории нет (то же правило, что у бота в `run.process_batch`), иначе
    # повтор после сбоя удвоил бы ленту. `author='human'` при роли `assistant`
    # — спека 25.08 §5: роль уходит в API как есть, а автор живёт рядом.
    store.add_message(contact_id, "assistant", text, ts=now, author="human")
    store.note_human_out(contact_id, ts=now)
    if msg_id is not None and msg_id.isdigit():
        # Атрибуция паузы указывает на РЕАЛЬНО отправленное сообщение: по
        # `pause_msg_id` владелец адресует `/resume` реплаем, и колонка
        # сравнивается как ЧИСЛО (`update_pause_attribution`). Нечисловой id
        # (веб, бизнес-API) туда не кладём: он либо упадёт, либо соврёт про
        # порядок сообщений.
        store.update_pause_attribution(
            contact_id, msg_id=int(msg_id), detail=text[:200])
    store.add_event("outgoing_sent", contact_id=contact_id,
                    detail="#%s -> msg %s" % (row_id, msg_id), ts=now)
    log.info("outgoing #%s ОТПРАВЛЕНО в %s (msg %s)", row_id, contact_id, msg_id)
    return "sent"
