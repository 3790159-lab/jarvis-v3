# -*- coding: utf-8 -*-
"""Конверт входящего: в каком виде ход ЛЮБОГО канала попадает внутрь (§2).

ПОЧЕМУ ЯДРО. Конверт не знает о транспорте ничего: ни HTTP, ни Telethon, ни
сокета. Правило «ноль импортов Telethon в `chatter/core/*`» выполняется по
построению, а не соблюдением.

ЧЕГО В КОНВЕРТЕ НЕТ — И ЭТО ГЛАВНАЯ ПОЛОВИНА РЕШЕНИЯ (§2.2). Каждое
исключение с причиной:

1. `contact_id` как ПОЛЕ. Только производное свойство. Поле рядом с тремя
   своими частями — это два числа на одну вещь, и меньшее гасит большее молча.
2. Вложения (`attachments`). Медиа — отдельная работа, нужная всем каналам
   сразу; в `messages` под неё нет ни колонки, ни таблицы. Поле `attachments`,
   которое всегда пусто, — это место, где фото теряется молча, только теперь с
   видом порядка. Взамен — `attachments_dropped`.
3. `msg_id` канала. Его единственный потребитель — дедуп at-least-once, то
   есть очередь входящих. Поле, которое все кладут и никто не читает, хранит
   неверное значение ровно до дня, когда его прочтут. Производитель конверта
   сегодня ОДИН, значит добавить поле потом — это одно место.
4. `Store`, конфиг клиента, объект транспорта, способ ответить. Конверт —
   ДАННЫЕ, а не контекст, и проверка этому механическая: конверт обязан
   пережить `json.dumps` и вернуться равным себе.
5. IP, `User-Agent`, `Origin`, заголовки. Они принадлежат ДВЕРИ и умирают на
   её пороге. Причина не в чистоте, а в обещании: конверт переживает рестарт,
   попадает в очередь и в клиентский бэкап, а срок хранения переписки
   веб-посетителя — 365 дней, напечатанные в баннере. Положить IP в то, что
   хранится год, значит молча расширить обещание.
6. `role` / `author`. Конверт — это ВХОДЯЩЕЕ. Роль у него одна, и колонка для
   неё существовала бы только чтобы однажды принять неверное значение.
7. Что-либо про склейку (`lead_id`). Склейка — это СВЯЗЬ поверх двух
   личностей, а не поле внутри одной (решение владельца 24.08).

СТОЛКНОВЕНИЕ ИМЁН. У публичной двери УЖЕ есть `envelope` — обёртка транспорта
`{"client": ..., "payload": ...}` (`app/routers/public_door.py`). Это ДРУГАЯ
вещь: у неё в `payload` лежит нераспакованное тело запроса. `Inbound` — второй,
самостоятельный тип, и превращает первое во второе ПРИЁМНИК (`sink`). Слить
два имени в одно нельзя: у них разные производители, разные сроки жизни и
разная приёмка.
"""
from __future__ import annotations

from dataclasses import dataclass

from chatter.core.contact_ref import KNOWN_CHANNELS, ContactRefError, build

# Событие замера потери вложений (§2.3). ИМЯ РЕШЕНО ЗДЕСЬ: спека называет
# «событие в `control_events`», но не называет `kind`.
#
# `attachments_dropped` — то же слово, что у поля, и оно говорит, ЧТО
# произошло: «пришёл файл, который мы не берём». `has_media` через полгода
# прочтут как «медиа поддерживается».
#
# Это ЗАМЕР, а не тревога: событие существует, чтобы медиа-арка знала свой
# размер, и лампы себе не просит. Производителя у него сегодня нет — конверт
# в живой путь ещё не включён (§6 запрещает менять `Transport.receive` и
# `process_batch` в одном мерже с переписью живых баз), и включит его пара D.
ATTACHMENTS_DROPPED_EVENT = "attachments_dropped"


@dataclass(frozen=True)
class Inbound:
    """Входящее сообщение любого канала.

    Замороженный намеренно: конверт едет в очередь и в клиентский бэкап,
    значит его значение обязано быть тем же, что при сборке.

    Порядок полей — договор между ядром, дверью и очередью: конструктор зовут
    и позиционно, а перестановка двух соседних `str`-полей местами не упадёт
    нигде — она просто положит имя лида в текст.
    """

    channel: str                    # из ЛИТЕРАЛЬНОГО реестра KNOWN_CHANNELS
    external_id: str                # id собеседника В КАНАЛЕ (peer_id/session)
    persona: str                    # слуг персоны
    text: str                       # текст хода как его дал канал
    ts: float                       # время СОБЫТИЯ в канале, не нашего разбора
    display_name: str | None = None  # имя, если канал его дал; None != ""
    attachments_dropped: int = 0    # сколько вложений пришло и НЕ взято

    def __post_init__(self) -> None:
        # Сборка `contact_id` — она же и проверка трёх сегментов: пустой
        # сегмент и двоеточие внутри отвергаются ТАМ, в единственной точке
        # правды о форме. Иначе неразбираемый id родился бы ВНУТРИ нашего
        # кода, а покраснел бы через слой, у чужого разбора.
        build(channel=self.channel, external_id=self.external_id,
              persona=self.persona)
        if not isinstance(self.text, str):
            raise ContactRefError(
                "text конверта = %r (%s): конверт обязан пережить json и "
                "вернуться РАВНЫМ себе, а живой объект этого не умеет — и "
                "узнаётся это в день, когда очередь попробует его записать"
                % (self.text, type(self.text).__name__))
        if self.display_name is not None and not isinstance(self.display_name, str):
            raise ContactRefError(
                "display_name конверта = %r (%s): допустимы только строка и "
                "None, и они РАЗЛИЧИМЫ — None значит «канал имени не дал», "
                "пустая строка значит «канал дал пустое»"
                % (self.display_name, type(self.display_name).__name__))
        if isinstance(self.ts, bool) or not isinstance(self.ts, (int, float)):
            raise ContactRefError(
                "ts конверта = %r (%s): ждём число секунд эпохи"
                % (self.ts, type(self.ts).__name__))
        if isinstance(self.attachments_dropped, bool) \
                or not isinstance(self.attachments_dropped, int) \
                or self.attachments_dropped < 0:
            raise ContactRefError(
                "attachments_dropped = %r: это СЧЁТ потерянных вложений, "
                "неотрицательное целое" % (self.attachments_dropped,))

    @property
    def contact_id(self) -> str:
        """ПРОИЗВОДНОЕ свойство, а не поле (§2.2 п.1).

        Единственное обещание конверта наружу: всё остальное дерево адресует
        контакт этой строкой.
        """
        return build(channel=self.channel, external_id=self.external_id,
                     persona=self.persona)


__all__ = ["Inbound", "ATTACHMENTS_DROPPED_EVENT", "KNOWN_CHANNELS"]
