# -*- coding: utf-8 -*-
"""Личность контакта: ОДИН разбор `contact_id` вместо восьми по коду.

Сегодняшний `contact_id` собирается ровно в трёх местах и всегда одинаково —
`f"{sender_id}:{persona_slug}"` (`telethon_run.py:1702,1785,1855`). То есть
форма строго двухсегментная, и слуги (`volska`, `demo`, `demo2`, `yarina`)
двоеточий не содержат.

ЗАЧЕМ МОДУЛЬ. Восемь мест резали строку сами и брали ГОЛОВУ как telegram-peer.
Две делали это громко (`int(...)` -> `ValueError`), шесть — МОЛЧА. На формате
`"<channel>:<external_id>:<persona>"`, который вводит следующая арка, шесть
молчаливых вернули бы строку `"instagram"` там, где имелся в виду собеседник,
и это доехало бы до клиента. Замена восьми разборов одной fail-closed функцией
— ПРЕДУСЛОВИЕ смены формата, а не уборка заодно.

ПОЧЕМУ ЯДРО. Функция ничего не знает о транспорте: на входе строка, на выходе
строка. `chatter/core/*` держит правило «ноль импортов Telethon», и она ему
соответствует по построению.

ОПОЗНАЁМ ПО ЧИСЛУ СЕГМЕНТОВ, А НЕ ПО ГОЛОВЕ. Соблазнительная альтернатива —
«числовая голова значит telegram, нечисловая значит чужой канал» — тихо примет
`"12345:abc:volska"` ровно тогда, когда следующая арка введёт трёхсегментный
формат с числовым `external_id`. То есть заведёт молчаливое неверное поведение
на том самом переходе, ради которого этот модуль и пишется.
"""
from __future__ import annotations

SEPARATOR = ":"

# Сегодня — ровно два. Литералом, а не выведенным из чего-нибудь: список,
# согласный с кодом по определению, промолчит там, где код забыл
# (jarvis-literal-lists-not-introspection).
SEGMENTS_TODAY = 2


class ContactRefError(ValueError):
    """Форма `contact_id`, которой мы не знаем.

    Наследник `ValueError` намеренно: по типу это «правильный тип, неверное
    значение», и вызывающий, ловивший `ValueError` от прежнего `int(...)`,
    продолжает работать.

    Сообщение ОБЯЗАНО нести ВЕСЬ `contact_id`. Утечка `int()` несёт только
    голову (`'abc'`, не `'abc:volska'`), и без этого правила отказ этого
    модуля был бы неотличим от той самой ошибки, которую он заменяет.
    """


def _parts(contact_id: str) -> tuple[str, str]:
    """Разобрать на (отправитель, слуг) или ОТКАЗАТЬ.

    Fail-closed: форму, которой не знаем, не угадываем. Молчаливый
    правдоподобный ответ здесь дороже падения — падение видно в тот же день,
    а `"instagram"` вместо собеседника уезжает клиенту.
    """
    if not isinstance(contact_id, str):
        raise ContactRefError(
            "contact_id обязан быть строкой, пришло %r (%s)"
            % (contact_id, type(contact_id).__name__))
    parts = contact_id.split(SEPARATOR)
    if len(parts) != SEGMENTS_TODAY or not all(parts):
        raise ContactRefError(
            "contact_id %r: ждём ровно <peer>%s<slug> (%d сегмента, оба "
            "непустые), получили %d. Трёхсегментный формат вводит следующая "
            "арка — она же снимет этот запрет"
            % (contact_id, SEPARATOR, SEGMENTS_TODAY, len(parts)))
    return parts[0], parts[1]


def peer_of(contact_id: str) -> str:
    """ОТПРАВИТЕЛЬ. Строкой — как её отдавал прежний `split(":", 1)[0]`."""
    return _parts(contact_id)[0]


UNKNOWN_LABEL = "?"


def peer_label_of(contact_id) -> str:
    """ПОДПИСЬ отправителя для карточки владельца. НИКОГДА не бросает.

    ЗАЧЕМ ОТДЕЛЬНО ОТ `peer_of`. Замер §1 посчитал места СБОРКИ `contact_id`,
    а не места ВХОДА. Входит он и односегментным: `chatter/run.py:1086` задаёт
    `--contact console-user`, три формы `demo_switch` тоже без двоеточия. На
    таком входе fail-closed `peer_of` бросает — и владелец не получает
    карточку ВОВСЕ.

    Довод тот же, что уже записан у `slug_of` про `_persona_settings`:
    карточка должна уйти даже с битой личностью, а бросающая функция меняет
    «не на том языке» на «никак». Две карточки одной арки не могут судиться
    по разным правилам — это несогласованность, а не выбор.

    ГРАНИЦА, и она НЕ «везде помягче»:
      * значение АДРЕСУЕТ (по нему шлют) -> fail-closed, как было. Это
        `telegram_peer_of` на пути `telethon_run`: молчаливый мусор там
        означает сообщение НЕ ТОМУ человеку, и падение дешевле.
      * значение ПОДПИСЫВАЕТ (имя и ссылка в карточке) -> деградация. Тут
        падение означает, что владелец не узнал о лиде вовсе.

    ДЕГРАДАЦИЯ НЕ УГАДЫВАЕТ. Неизвестная форма отдаётся ЦЕЛИКОМ, а не головой:
    на трёхсегментном формате следующей арки голова — это `"instagram"`, ровно
    тот правдоподобный мусор, ради которого модуль и написан. Строку
    `"instagram:777:volska"` за собеседника никто не примет, а `"instagram"` —
    примет. Подпись обязана ломаться ЗАМЕТНО, а не правдоподобно.

    Потребители (`display_name`, `contact_link` из `chatter/core/console.py`)
    принимают `int | str` и `int()` не зовут — проверено, иначе деградация
    просто перенесла бы падение на шаг дальше.
    """
    try:
        return _parts(contact_id)[0]
    except ContactRefError:
        # Пустая подпись — это тоже отказ, просто тихий: карточка уедет с
        # дырой вместо имени. Поэтому у деградации есть свой пол.
        text = "" if contact_id is None else str(contact_id).strip()
        return text or UNKNOWN_LABEL


def slug_of(contact_id: str) -> str:
    """СЛУГ персоны.

    В проде сегодня не зовётся: единственное место, берущее хвост
    (`telethon_run._persona_settings`), делает это через `rsplit` и ОБЯЗАНО
    иметь фолбэк на primary — карточка должна уйти даже с битым слугом. Дать
    ему бросающую функцию значило бы поменять «не на том языке» на «никак».

    Функция существует ради инварианта обратимости (см. `is_reversible`) и
    ради следующей арки, которая формат меняет.
    """
    return _parts(contact_id)[1]


def telegram_peer_of(contact_id: str) -> int:
    """ОТПРАВИТЕЛЬ как telegram-peer.

    Отдельной функцией от `peer_of`, а не приведением на месте: «это вообще
    телеграмный контакт?» — вопрос, на который завтра будет НЕ всегда «да», и
    он обязан задаваться в одном месте.
    """
    head = peer_of(contact_id)
    try:
        return int(head)
    except ValueError:
        # `from None`: утечка исходного ValueError несёт только голову и
        # выглядит как ошибка недр int(). Отказ обязан называть contact_id.
        raise ContactRefError(
            "contact_id %r: голова %r не telegram-peer (не целое число)"
            % (contact_id, head)) from None


def is_reversible(contact_id: str) -> bool:
    """Разбор принятой формы обязан быть ОБРАТИМ.

    Ловит реализацию, которая приняла три сегмента и молча потеряла середину —
    самый правдоподобный способ «почти» выполнить требование о двух сегментах.
    """
    try:
        return peer_of(contact_id) + SEPARATOR + slug_of(contact_id) == contact_id
    except ContactRefError:
        return False
