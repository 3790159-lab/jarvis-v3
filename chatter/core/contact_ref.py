# -*- coding: utf-8 -*-
"""Личность контакта: ОДИН разбор и ОДНА сборка `contact_id` на всё дерево.

ФОРМА (пара C, §3.1): `"<channel>:<external_id>:<persona>"` — ровно три
сегмента, ни один не пуст, ни в одном нет двоеточия. `channel` берётся из
ЛИТЕРАЛЬНОГО реестра `KNOWN_CHANNELS`; голова телеграма — слово `telegram`, а
не `tg`: и замер, и мастер-спека пишут каналы словом, а двухбуквенное
исключение ровно для одного канала — это правило, у которого нет правила.

ЗАЧЕМ МОДУЛЬ. Двенадцать мест резали строку сами и брали ГОЛОВУ как
telegram-peer. Две делали это громко (`int(...)` -> `ValueError`), десять —
МОЛЧА. На трёхсегментной форме молчаливые вернули бы строку `"telegram"` там,
где имелся в виду собеседник, и это доехало бы до клиента.

ПОЧЕМУ ЯДРО. Функция ничего не знает о транспорте: на входе строка, на выходе
строка. `chatter/core/*` держит правило «ноль импортов Telethon», и она ему
соответствует по построению.

ОПОЗНАЁМ ПО ЧИСЛУ СЕГМЕНТОВ, А НЕ ПО ГОЛОВЕ. Соблазнительная альтернатива —
«числовая голова значит telegram, нечисловая значит чужой канал» — отвергает
группу (`peer_id` у групп отрицателен, но числовой) ровно тогда, когда веб
приносит НЕчисловой `external_id`. Число сегментов не зависит ни от того, ни
от другого.

ОБРАТНАЯ СОВМЕСТИМОСТЬ ЖИВЁТ В ОДНОМ НАЗВАННОМ МЕСТЕ — и это
`upgrade_legacy_callback_contact` (§3.4), применяемая в `route_callback`.
Двухсегментная форма строгим разбором ОТВЕРГАЕТСЯ: разбор обязан оставаться
свидетелем того, что база не мигрирована. Мягкий режим внутри `peer_of`
означал бы, что код молча работает на смеси двух форм и один человек живёт
двумя контактами.
"""
from __future__ import annotations

SEPARATOR = ":"

# ЛИТЕРАЛЬНЫЙ реестр каналов (§3.1). Литеральный, а не выведенный из классов
# транспорта: список, согласный с кодом по определению, промолчит ровно там,
# где код забыл (jarvis-literal-lists-not-introspection). Канал, пропавший
# отсюда, обязан краснеть, а не молча перестать проверяться.
TELEGRAM_CHANNEL = "telegram"
WEB_CHANNEL = "web"
KNOWN_CHANNELS: tuple[str, ...] = (TELEGRAM_CHANNEL, WEB_CHANNEL)

# Сколько сегментов у формы. Числа «сегодня» здесь нет намеренно: пока в
# модуле живёт число с таким именем, разбор будут сверять с ним, а не с
# форматом.
_SEGMENTS = 3


class ContactRefError(ValueError):
    """Форма `contact_id`, которой мы не знаем.

    Наследник `ValueError` намеренно (§13.2): по типу это «правильный тип,
    неверное значение». Отказ МИГРАЦИИ — это `RuntimeError`, и типы разные не
    из педантизма: первый уместно поймать и ответить лиду, второй ловить
    нельзя вовсе — он обязан остановить подъём.

    Сообщение ОБЯЗАНО нести ВЕСЬ `contact_id`. Утечка `int()` несёт только
    голову (`'abc'`, не `'abc:volska'`), и без этого правила отказ этого
    модуля был бы неотличим от той самой ошибки, которую он заменяет.
    """


def _parts(contact_id: str) -> tuple[str, str, str]:
    """Разобрать на (канал, собеседник, слуг) или ОТКАЗАТЬ.

    Fail-closed: форму, которой не знаем, не угадываем. Молчаливый
    правдоподобный ответ здесь дороже падения — падение видно в тот же день,
    а `"telegram"` вместо собеседника уезжает клиенту.
    """
    if not isinstance(contact_id, str):
        raise ContactRefError(
            "contact_id обязан быть строкой, пришло %r (%s)"
            % (contact_id, type(contact_id).__name__))
    parts = contact_id.split(SEPARATOR)
    if len(parts) != _SEGMENTS or not all(parts):
        raise ContactRefError(
            "contact_id %r: ждём ровно <channel>%s<external_id>%s<persona> "
            "(%d сегмента, все непустые), получили %d. Двухсегментная форма "
            "после переезда отвергается: её понимает ровно один переводчик "
            "старых кнопок, `upgrade_legacy_callback_contact`"
            % (contact_id, SEPARATOR, SEPARATOR, _SEGMENTS, len(parts)))
    if parts[0] not in KNOWN_CHANNELS:
        # ВСТРЕЧНАЯ ПОЛОВИНА реестра (§3.1): канал, которого в реестре нет,
        # обязан краснеть, а не приниматься. Без неё «12345:my:slug» прошло бы
        # как трёхсегментная форма с каналом «12345», и опознание «по числовой
        # голове» вернулось бы через заднюю дверь.
        raise ContactRefError(
            "contact_id %r: канал %r вне литерального реестра %r. Голова "
            "входит в адресацию, и чужой канал здесь — это либо форма, "
            "пришедшая ниоткуда, либо опечатка, дающая ДВА контакта на одного "
            "человека" % (contact_id, parts[0], list(KNOWN_CHANNELS)))
    return parts[0], parts[1], parts[2]


def build(*, channel: str, external_id: str, persona: str) -> str:
    """Собрать `contact_id`. ЕДИНСТВЕННАЯ сборка вместе с `Inbound.contact_id`.

    Девять f-строк по дереву знали форму наизусть и разъехались бы в день,
    когда форма меняется, — молча: f-строка не бросает никогда.

    Хвост `<external_id>:<persona>` собирается отдельным шагом намеренно: это
    ровно та строка, которой `contact_id` был ДО переезда, и переводчик старых
    кнопок приставляет к ней ту же голову канала (см.
    `upgrade_legacy_callback_contact`).
    """
    for name, value in (("channel", channel), ("external_id", external_id),
                        ("persona", persona)):
        if not isinstance(value, str) or not value or SEPARATOR in value:
            raise ContactRefError(
                "сегмент %s = %r непригоден: обязан быть непустой строкой без "
                "%r внутри — иначе трёхсегментный id родится четырёхсегментным "
                "ВНУТРИ нашего кода, а покраснеет через слой, у чужого разбора"
                % (name, value, SEPARATOR))
    if channel not in KNOWN_CHANNELS:
        raise ContactRefError(
            "канал %r вне литерального реестра %r. Опечатка в канале — это не "
            "странная строка в базе: голова входит в адресацию, и 'Telegram' "
            "рядом с 'telegram' дают ДВА контакта на одного человека, и оба "
            "выглядят живыми" % (channel, list(KNOWN_CHANNELS)))
    peer_ref = f"{external_id}:{persona}"
    return f"{channel}:{peer_ref}"


def channel_of(contact_id: str) -> str:
    """КАНАЛ. Вопрос «каким транспортом отвечать» задаётся в одном месте, а не
    срезом по первому двоеточию у каждого вызывающего."""
    return _parts(contact_id)[0]


def peer_of(contact_id: str) -> str:
    """СОБЕСЕДНИК — середина, а НЕ голова.

    Это тот самый дефект, ради которого писалась волна 1: голова — это канал,
    и `"telegram"` вместо собеседника доехало бы до клиента.
    """
    return _parts(contact_id)[1]


UNKNOWN_LABEL = "?"


def peer_label_of(contact_id) -> str:
    """ПОДПИСЬ отправителя для карточки владельца. НИКОГДА не бросает.

    ЗАЧЕМ ОТДЕЛЬНО ОТ `peer_of`. Замер §1 посчитал места СБОРКИ `contact_id`,
    а не места ВХОДА. Входит он и односегментным: `chatter/run.py:1086` задаёт
    `--contact console-user`, три формы `demo_switch` тоже без двоеточия. На
    таком входе fail-closed `peer_of` бросает — и владелец не получает
    карточку ВОВСЕ.

    Довод тот же, что уже записан у `slug_of` про `_persona_settings`:
    карточка должна уйти даже с битой личностью, а бросающая функция меняет
    «не на том языке» на «никак». Две карточки одной арки не могут судиться
    по разным правилам — это несогласованность, а не выбор.

    ГРАНИЦА, и она НЕ «везде помягче»:
      * значение АДРЕСУЕТ (по нему шлют) -> fail-closed, как было. Это
        `telegram_peer_of` на пути `telethon_run`: молчаливый мусор там
        означает сообщение НЕ ТОМУ человеку, и падение дешевле.
      * значение ПОДПИСЫВАЕТ (имя и ссылка в карточке) -> деградация. Тут
        падение означает, что владелец не узнал о лиде вовсе.

    ДЕГРАДАЦИЯ НЕ УГАДЫВАЕТ. Неизвестная форма отдаётся ЦЕЛИКОМ, а не головой:
    у трёхсегментной формы голова — это `"telegram"`, ровно тот правдоподобный
    мусор, ради которого модуль и написан. Строку `"telegram:777:volska"` за
    собеседника никто не примет, а `"telegram"` — примет. Подпись обязана
    ломаться ЗАМЕТНО, а не правдоподобно.

    Потребители (`display_name`, `contact_link` из `chatter/core/console.py`)
    принимают `int | str` и `int()` не зовут — проверено, иначе деградация
    просто перенесла бы падение на шаг дальше.
    """
    try:
        return _parts(contact_id)[1]
    except ContactRefError:
        # Пустая подпись — это тоже отказ, просто тихий: карточка уедет с
        # дырой вместо имени. Поэтому у деградации есть свой пол.
        text = "" if contact_id is None else str(contact_id).strip()
        return text or UNKNOWN_LABEL


def slug_of(contact_id: str) -> str:
    """СЛУГ персоны — последний сегмент.

    Персона — это то, чьим языком и чьей личностью бот отвечает; ошибка здесь
    уводит карточку владельцу на язык ЧУЖОЙ персоны, и в логе не будет ничего.
    """
    return _parts(contact_id)[2]


def telegram_peer_of(contact_id: str) -> int:
    """СОБЕСЕДНИК как telegram-peer.

    Отдельной функцией от `peer_of`, а не приведением на месте: «это вообще
    телеграмный контакт?» — вопрос, на который ответ НЕ всегда «да», и он
    обязан задаваться в одном месте.

    Отрицательная голова законна: у групп `peer_id = event.chat_id`
    отрицателен, и `telegram:-1001234567890:demo` есть живая форма.
    """
    peer = peer_of(contact_id)
    try:
        return int(peer)
    except ValueError:
        # `from None`: утечка исходного ValueError несёт только середину и
        # выглядит как ошибка недр int(). Отказ обязан называть contact_id.
        raise ContactRefError(
            "contact_id %r: собеседник %r не telegram-peer (не целое число)"
            % (contact_id, peer)) from None


def is_reversible(contact_id: str) -> bool:
    """Разбор принятой формы обязан быть ОБРАТИМ.

    Ловит реализацию, которая приняла три сегмента и молча потеряла середину —
    самый правдоподобный способ «почти» выполнить требование. Такая реализация
    проходит и `peer_of`, и `slug_of` по отдельности, а склеить обратно из её
    кусков исходную строку нельзя: значит какой-то кусок она выдумала.
    """
    try:
        parts = _parts(contact_id)
    except ContactRefError:
        return False
    return SEPARATOR.join(parts) == contact_id


def upgrade_legacy_callback_contact(s) -> str | None:
    """ЕДИНСТВЕННАЯ дверь для старой формы — кнопки, УЖЕ улетевшие в Telegram.

    `callback_data` кнопки живёт в чате владельца месяцами и тапабельно всё
    это время. Замер §3.4: живых карточек с флагом `esc_active` — 5 у demo и
    2 у yarina. Без этой двери семь живых кнопок становятся немыми тапами:
    `route_callback` на неизвестный тап отвечает «без мутаций», то есть
    отказом БЕЗ следа для того, кто жмёт.

    ПРАВИЛО УЗКОЕ: ровно два сегмента И числовая голова (с допуском ведущего
    `-`) -> голова канала `telegram` приставляется спереди. Всё прочее —
    `None`, то есть ОТКАЗ, а не догадка. Широкое правило дороже узкого:
    апгрейд, применённый ко всему похожему, превратил бы `web:abc:volska` в
    `telegram:web:abc:volska` — форму, которой нет ни в одной базе, и тап ушёл
    бы в никуда уже по НАШЕЙ вине.

    Безопасно это ровно потому, что до переписки баз ВСЕ существовавшие
    `contact_id` были телеграмными: 12 из 12 контактов в обеих базах, голова
    числовая у всех (§1.1).

    🔴 ЭТО НЕ «мягкий режим» внутри `peer_of`. Отдельная названная функция —
    чтобы (а) строгий разбор остался строгим и это пинилось сторожем;
    (б) послабление удалялось ОДНИМ куском, когда старые кнопки истекут.
    Временность записана в самом имени.
    """
    if not isinstance(s, str):
        return None
    parts = s.split(SEPARATOR)
    if len(parts) != 2 or not all(parts):
        return None
    head, tail = parts
    if not head.lstrip("-").isdigit():
        return None
    if SEPARATOR in tail:                       # недостижимо после split, но
        return None                             # правило обязано быть видно
    return f"{TELEGRAM_CHANNEL}:{s}"
