# -*- coding: utf-8 -*-
"""Определение языка текста по алфавиту — без сети и без зависимостей.

Спека `2026-08-04-chatter-sales-competence.md` §1.3, §5(б).

ЗАЧЕМ. `settings.language` — одна скалярка на клиента. Она уезжает и в
редакцию гардрейла, и в заглушки подавления, и в карточки. Живой случай:
диалог шёл по-русски, модель отвечала по-русски, а код вставлял в её текст
украинские константы — и отчёт засчитал это моделью, которая «забыла язык».
Смешивал языки код.

ПОЧЕМУ БУКВЫ, А НЕ СЛОВАРЬ. У uk и ru непересекающиеся буквы: і, ї, є, ґ
против ы, э, ъ, ё. На реплике от трёх слов этого достаточно, а словарь
стоп-слов пришлось бы вести и он врал бы на коротких репликах, где половина
слов общая («для», «на», «так»).

FAIL-OPEN ПО УМОЛЧАНИЮ, И ЭТО НАМЕРЕННО. Нет сигнала — возвращаем `default`,
то есть сегодняшнее поведение (`settings.language`). Детектор не имеет права
быть источником нового класса ошибок: худшее, что он может сделать при
отсутствии улик, — не менять ничего.
"""
from __future__ import annotations

# Буквы, которые есть В ОДНОМ языке и отсутствуют в другом.
_UK_ONLY = set("іїєґ")
_RU_ONLY = set("ыэъё")
_CYRILLIC = set("абвгдежзийклмнопрстуфхцчшщьюя")
_LATIN = set("abcdefghijklmnopqrstuvwxyz")


def detect_language(text: str, *, default: str = "ru") -> str:
    """`uk` | `ru` | `en` | `default`.

    Порядок решений: сначала различающие буквы (они однозначны), потом —
    какой алфавит вообще преобладает. Кириллица без различающих букв
    («Зробимо роботу» / «Сделаем работу») неразличима по построению, и врать
    тут нечем: отдаём `default`."""
    low = (text or "").lower()
    uk = sum(1 for ch in low if ch in _UK_ONLY)
    ru = sum(1 for ch in low if ch in _RU_ONLY)
    if uk > ru:
        return "uk"
    if ru > uk:
        return "ru"
    cyr = sum(1 for ch in low if ch in _CYRILLIC)
    lat = sum(1 for ch in low if ch in _LATIN)
    if lat and lat > cyr:
        return "en"
    return default
