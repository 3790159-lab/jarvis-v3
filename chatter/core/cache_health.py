"""Здоровье prompt-кэша: hit-rate и сигнатура регрессии (спека 2026-07-25 §6).

Зачем модуль вообще: 2026-07-23 18:23 арка «память» положила изменчивый профиль
в кэшируемый блок классификатора. Кэш умер (1 попадание из 22), счёт вырос на
треть — и это не увидел НИКТО: тесты зелёные, бот отвечает верно, лид доволен.
Единственный наблюдаемый след жил в `llm_usage`, куда никто не смотрел.

Чистые функции над строками `llm_usage`: ни БД, ни сети, ни ПДн.
"""
from __future__ import annotations

# Промахов подряд, после которых это уже не совпадение. Порог 3 (по образцу
# порога классификатора 2/сутки): на данных 23.07 сработал бы на третьем ходу
# после регрессии, а не через сутки. Ложное срабатывание требует трёх подряд
# промахов при ЖИВОМ кэше — то есть либо сломанный префикс, либо три подряд
# смены конфига (и те подавляются отдельно).
REGRESSION_STREAK = 3

# Верхняя граница «кэш ещё жив»: ttl:1h в llm.py. Промах после большего
# разрыва — истёкший TTL, а не поломка. См. поправку 2026-07-25: холод даёт
# ИСТЁКШИЙ TTL, а не рестарт раннера (кэш живёт на стороне API).
CACHE_TTL_SEC = 3600.0


def _is_hit(row) -> bool:
    return (row["cache_read_input_tokens"] or 0) > 0


def hit_rate(rows, tag: str) -> tuple[int, int]:
    """(попаданий, всего вызовов) по ОДНОМУ тегу.

    Возвращаем базу, а не процент, намеренно: «100%» на двух вызовах и «100%»
    на пятидесяти — разные утверждения, и решение принимается по второму.
    Проценты считает тот, кто печатает."""
    same = [r for r in rows if r["tag"] == tag]
    return sum(1 for r in same if _is_hit(r)), len(same)


def consecutive_misses(rows, tag: str, *, max_gap_sec: float = CACHE_TTL_SEC,
                       config_change_ts=()) -> int:
    """Длина хвоста промахов подряд ПРИ ЖИВОМ кэше — от самого свежего вызова
    назад. Цепочку обрывают:

    * попадание — кэш работает, дальше смотреть незачем;
    * разрыв ≥ TTL — кэш умер законно, промах после него уликой не является.

    Промах, которому непосредственно предшествовала смена конфига, НЕЙТРАЛЕН:
    не считается уликой и не обрывает цепочку. `/reload` плейбука меняет
    префикс законно, и платой за него будет ровно один промах — алертить на
    этом значит алертить на каждой правке базы знаний.

    Интервал меряется между вызовами ОДНОГО тега: у brain и классификатора
    разные префиксы, разные кэши и разные истории попаданий. Считать их вместе
    = «сократить» интервал чужим вызовом и потерять сигнатуру.
    """
    same = sorted((r for r in rows if r["tag"] == tag), key=lambda r: r["ts"])
    changes = sorted(config_change_ts or ())
    streak = 0
    for i in range(len(same) - 1, -1, -1):
        row = same[i]
        if _is_hit(row):
            break
        prev_ts = same[i - 1]["ts"] if i else None
        if prev_ts is not None and row["ts"] - prev_ts >= max_gap_sec:
            streak += 1          # сам этот промах ещё улика…
            break                # …а всё, что до разрыва, уже другая история
        if prev_ts is not None and any(prev_ts < c <= row["ts"] for c in changes):
            continue             # законная смена префикса — нейтрально
        streak += 1
    return streak


def is_regression(rows, tag: str, *, threshold: int = REGRESSION_STREAK,
                  max_gap_sec: float = CACHE_TTL_SEC, config_change_ts=()) -> bool:
    """True — префикс, похоже, сломан: пора смотреть, что въехало в кэшируемый
    блок, а не поднимать порог."""
    return consecutive_misses(rows, tag, max_gap_sec=max_gap_sec,
                              config_change_ts=config_change_ts) >= threshold
