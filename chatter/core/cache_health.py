"""Здоровье prompt-кэша: hit-rate и сигнатура регрессии (спека 2026-07-25 §6).

Зачем модуль вообще: 2026-07-23 18:23 арка «память» положила изменчивый профиль
в кэшируемый блок классификатора. Кэш умер (1 попадание из 22), счёт вырос на
треть — и это не увидел НИКТО: тесты зелёные, бот отвечает верно, лид доволен.
Единственный наблюдаемый след жил в `llm_usage`, куда никто не смотрел.

Чистые функции над строками `llm_usage`: ни БД, ни сети, ни ПДн.
"""
from __future__ import annotations

# Промахов подряд, после которых это уже не совпадение. Порог 3 (по образцу
# порога классификатора 2/сутки): на данных 23.07 сработал бы на третьем ходу
# после регрессии, а не через сутки. Ложное срабатывание требует трёх подряд
# промахов при ЖИВОМ кэше — то есть либо сломанный префикс, либо три подряд
# смены конфига (и те подавляются отдельно).
REGRESSION_STREAK = 3

# Верхняя граница «кэш ещё жив»: ttl:1h в llm.py. Промах после большего
# разрыва — истёкший TTL, а не поломка. См. поправку 2026-07-25: холод даёт
# ИСТЁКШИЙ TTL, а не рестарт раннера (кэш живёт на стороне API).
CACHE_TTL_SEC = 3600.0

# Префикс тега пингов keep-alive: `keepalive_classifier`, `keepalive_brain`.
# Отдельный тег — требование §5 п.3 спеки 2026-08-09: под общим тегом пинг
# изнутри неотличим от боевого вызова и мгновенно портит и hit-rate, и замер
# экономии. Константа живёт ЗДЕСЬ, а не у писателя пингов: читатель и писатель
# обязаны знать одно имя, а два строковых литерала в разных модулях расходятся
# молча — и расходятся ровно тогда, когда кто-то переименует один из них.
KEEPALIVE_TAG_PREFIX = "keepalive_"


def _is_hit(row) -> bool:
    return (row["cache_read_input_tokens"] or 0) > 0


def hit_rate(rows, tag: str) -> tuple[int, int]:
    """(попаданий, всего вызовов) по ОДНОМУ тегу.

    Возвращаем базу, а не процент, намеренно: «100%» на двух вызовах и «100%»
    на пятидесяти — разные утверждения, и решение принимается по второму.
    Проценты считает тот, кто печатает."""
    same = [r for r in rows if r["tag"] == tag]
    return sum(1 for r in same if _is_hit(r)), len(same)


def keepalive_touches(rows, tag: str) -> tuple[float, ...]:
    """Метки времени пингов keep-alive для префикса `tag`.

    Пинги пишутся в `llm_usage` под ОТДЕЛЬНЫМ тегом (`keepalive_<tag>`, §5 п.3
    спеки): под общим тегом они изнутри неотличимы от боевых вызовов и
    испортили бы и hit-rate, и замер §4. Здесь эта же раздельность работает во
    вторую сторону — она позволяет спросить «а грели ли мы эту запись», не
    подмешивая пинги в статистику попаданий.
    """
    want = KEEPALIVE_TAG_PREFIX + tag
    return tuple(sorted(r["ts"] for r in rows if r["tag"] == want))


def _gap_survived(prev_ts: float, ts: float, touches, max_gap_sec: float) -> bool:
    """Пережила ли кэш-запись промежуток между двумя боевыми вызовами?

    Нужно из-за keep-alive (спека 2026-08-09 §5). Без пингов «разрыв ≥ TTL»
    и «кэш умер» — одно и то же, и `consecutive_misses` справедливо обрывал
    на нём цепочку. С пингами это перестаёт быть одним и тем же: запись
    продлевается КАЖДЫМ касанием, и разрыв между боевыми вызовами может быть
    сколь угодно длинным, пока в нём стоят пинги.

    Поэтому смотрим не на длину разрыва, а на самый длинный подпромежуток
    внутри него: запись жива, если НИ ОДИН промежуток между соседними
    касаниями (боевыми и пинговыми) не дотянул до TTL.

    `touches` — метки времени пингов ЭТОГО ЖЕ префикса. Пустой список
    возвращает поведение к прежнему: любой разрыв ≥ TTL считается смертью.
    """
    last = prev_ts
    for t in sorted(t for t in touches if prev_ts < t < ts):
        if t - last >= max_gap_sec:
            return False
        last = t
    return ts - last < max_gap_sec


def consecutive_misses(rows, tag: str, *, max_gap_sec: float = CACHE_TTL_SEC,
                       config_change_ts=(), keepalive_ts=None) -> int:
    """Длина хвоста промахов подряд ПРИ ЖИВОМ кэше — от самого свежего вызова
    назад. Цепочку обрывают:

    * попадание — кэш работает, дальше смотреть незачем;
    * разрыв ≥ TTL, НЕ ПРИКРЫТЫЙ пингами — кэш умер законно, промах после него
      уликой не является.

    Промах, которому непосредственно предшествовала смена конфига, НЕЙТРАЛЕН:
    не считается уликой и не обрывает цепочку. `/reload` плейбука меняет
    префикс законно, и платой за него будет ровно один промах — алертить на
    этом значит алертить на каждой правке базы знаний.

    Интервал меряется между вызовами ОДНОГО тега: у brain и классификатора
    разные префиксы, разные кэши и разные истории попаданий. Считать их вместе
    = «сократить» интервал чужим вызовом и потерять сигнатуру.

    ── `keepalive_ts`: ПОЧЕМУ БЕЗ НЕГО АРКА ОСЛЕПЛЯЕТ ЭТОТ ДЕТЕКТОР ──────────

    Правило «разрыв ≥ TTL — кэш умер законно» верно ТОЛЬКО без keep-alive.
    Под пингами разрыв ≥ TTL больше не означает смерть: запись ДОЛЖНА была
    остаться живой, и промах после такого разрыва — как раз улика, самая
    ценная из возможных. Оставь мы прежнюю логику, арка, которая снижает число
    промахов, заодно выключила бы сторожа, эти промахи ловившего: он бы
    честно молчал, потому что каждый промах приходил после длинного разрыва.
    Ровно так 23.07 кэш умер и этого сутки никто не видел.

    Но и «под keep-alive любой разрыв — улика» неверно: пинг мог не уйти
    (сеть, 5xx, окно суток кончилось), и тогда запись умерла ЗАКОННО. Поэтому
    решает не флаг «арка включена», а ФАКТ касаний: пришли ли пинги в этот
    конкретный разрыв. Флаг соврал бы на каждом пропущенном пинге.

    Умолчание `None` — «достать касания из тех же `rows` самому». Не `()`, и
    это не мелочь: вызывающий, забывший передать пинги, получил бы ослеплённый
    детектор МОЛЧА — то есть ровно тот дефект, ради которого правка делается,
    только спрятанный на уровень глубже. Умолчание обязано быть безопасным.
    У клиента без keep-alive строк с пинговым тегом нет, извлечение вернёт
    пусто, и поведение остаётся байт-в-байт прежним.

    Явный `()` означает «пингов НЕ БЫЛО» и нужен там, где это утверждение
    проверяется (тесты, сравнение «как было бы без арки»).
    """
    same = sorted((r for r in rows if r["tag"] == tag), key=lambda r: r["ts"])
    changes = sorted(config_change_ts or ())
    if keepalive_ts is None:
        keepalive_ts = keepalive_touches(rows, tag)
    pings = tuple(keepalive_ts)
    streak = 0
    for i in range(len(same) - 1, -1, -1):
        row = same[i]
        if _is_hit(row):
            break
        prev_ts = same[i - 1]["ts"] if i else None
        if (prev_ts is not None and row["ts"] - prev_ts >= max_gap_sec
                and not _gap_survived(prev_ts, row["ts"], pings, max_gap_sec)):
            streak += 1          # сам этот промах ещё улика…
            break                # …а всё, что до разрыва, уже другая история
        if prev_ts is not None and any(prev_ts < c <= row["ts"] for c in changes):
            continue             # законная смена префикса — нейтрально
        streak += 1
    return streak


def is_regression(rows, tag: str, *, threshold: int = REGRESSION_STREAK,
                  max_gap_sec: float = CACHE_TTL_SEC, config_change_ts=(),
                  keepalive_ts=None) -> bool:
    """True — префикс, похоже, сломан: пора смотреть, что въехало в кэшируемый
    блок, а не поднимать порог.

    `keepalive_ts=None` (умолчание) — вытащить пинги из тех же `rows` самому.
    Это не «удобство»: вызывающий, забывший передать касания, получил бы
    ослеплённый детектор МОЛЧА, а молчащий сторож здесь и есть предмет §5.
    Явный пустой кортеж по-прежнему означает «пингов не было».
    """
    if keepalive_ts is None:
        keepalive_ts = keepalive_touches(rows, tag)
    return consecutive_misses(rows, tag, max_gap_sec=max_gap_sec,
                              config_change_ts=config_change_ts,
                              keepalive_ts=keepalive_ts) >= threshold
