def _file_age(path) -> float | None:
    """Возраст файла. ⚠️ По mtime, а не по размеру: на NTFS размер файла с
    открытым write-хэндлом показывается нулём, и «пустой heartbeat» — мираж."""
    try:
        return time.time() - Path(path).stat().st_mtime
    except OSError:
        return None


