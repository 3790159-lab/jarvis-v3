def _chatter_snapshot() -> dict | None:
    """Снимок для двух chatter-проб. psutil, а не PowerShell из питона
    (ловушка 5 спеки): psutil здесь уже используется для boot_time.

    Ошибка сбора → None, то есть пробы просто НЕ выполняются в этом цикле.
    Это осознанно: `evaluate()` замораживает состояние отсутствующих проб, и
    сбойный сбор не превращается в ложный DOWN о живом сервисе."""
    try:
        import psutil
    except Exception:
        return None
    try:
        procs = []
        for proc in psutil.process_iter(["pid", "name", "cmdline"]):
            try:
                procs.append({"pid": proc.info["pid"],
                              "name": proc.info["name"] or "",
                              "cmdline": " ".join(proc.info["cmdline"] or [])})
            except Exception:
                continue
        # Собираем ОБЕ формы отметки: легаси-файл и все per-slug. Шаблон узкий
        # намеренно — рядом в state лежат chatter_clients.json и
        # chatter_watch_alert_<slug>.json, живостью они не являются.
        state_dir = ROOT / "state"
        beats = {CHATTER_BEAT_LEGACY_NAME: _file_age(state_dir / CHATTER_BEAT_LEGACY_NAME)}
        try:
            for p in sorted(state_dir.glob(CHATTER_BEAT_CLIENT_GLOB)):
                beats[p.name] = _file_age(p)
        except OSError:
            pass
        runner_beat_age, runner_beat_source = chatter_beat_age(beats)
        # Пер-слаговые отметки ОТДЕЛЬНО от свёрнутой: свёрнутая берёт самую
        # свежую и по построению прячет смерть соседа. Префикс и суффикс
        # выводятся ИЗ ГЛОБА, а не пишутся вторым литералом: два места на одно
        # имя однажды разъедутся.
        _pre, _suf = CHATTER_BEAT_CLIENT_GLOB.split("*", 1)
        beats_by_slug = {}
        for name, age in beats.items():
            if name.startswith(_pre) and name.endswith(_suf):
                beats_by_slug[name[len(_pre):len(name) - len(_suf)]] = age
        return {
            "processes": procs,
            "runner_beat_age": runner_beat_age,
            "runner_beat_source": runner_beat_source,
            "beats": beats_by_slug,
            "legacy_beat_age": beats.get(CHATTER_BEAT_LEGACY_NAME),
            "roster": _roster_snapshot(),
            "guardian_beat_age": _file_age(ROOT / "state" / "chatter_guardian_heartbeat.txt"),
            "guardian_lock_pid": _read_lock_pid(ROOT / "state" / "locks" / "chatter_guardian.pid"),
            "root": str(ROOT),
        }
    except Exception as exc:
        print("[ops_watchdog] chatter snapshot failed: %s" % exc, file=sys.stderr)
        return None


def _worktree_snapshot() -> dict | None:
    """Снимок живого дерева: ветка + модифицированные tracked-файлы.

    `None` возвращается ТОЛЬКО когда дерева нет на этой машине — тогда
    watchdog просто не на деплой-хосте и мерить ему нечего. Сбой самого git
    отдаётся как `error`, то есть проба будет КРАСНОЙ, а не пропущенной: это
    разные вещи, и вторую нельзя выдавать за первую."""
    if not LIVE_TREE.exists():
        return None
    import subprocess
    try:
        branch = subprocess.run(
            ["git", "-C", str(LIVE_TREE), "rev-parse", "--abbrev-ref", "HEAD"],
            capture_output=True, text=True, timeout=GIT_TIMEOUT_S)
        status = subprocess.run(
            ["git", "-C", str(LIVE_TREE), *GIT_STATUS_ARGS],
            capture_output=True, text=True, timeout=GIT_TIMEOUT_S)
    except Exception as exc:
        return {"branch": None, "dirty": [], "error": "%s: %s" % (type(exc).__name__, exc)}
    if branch.returncode != 0 or status.returncode != 0:
        return {"branch": None, "dirty": [],
                "error": "git rc=%s/%s: %s" % (branch.returncode, status.returncode,
                                               (branch.stderr or status.stderr).strip()[:120])}
    dirty = [line for line in status.stdout.splitlines() if line.strip()]
    return {"branch": branch.stdout.strip(), "dirty": dirty, "error": None}


def _secrets_bundle_snapshot(live_tree: Path = LIVE_TREE,
                             bundle_dirs=BUNDLE_DIRS) -> dict | None:
    """Снимок: mtime материала бандла и самого свежего .jrvbak.

    ТОЛЬКО ЧТЕНИЕ — `stat` и `glob`, ни одной записи: сторож, трогающий
    секреты, портит ровно то, что сторожит.

    Отсутствующего каталога с бандлами достаточно, чтобы вернуть `bundle=None`
    — это и есть повод для алерта. `error` — другое: каталог ЕСТЬ, но не
    читается, и тогда мы не знаем, а не знаем-что-нет."""
    if not live_tree.exists():
        return None
    try:
        material = []
        # ОБА env-файла, а не «.env.enc, иначе .env». `collect_secrets`
        # предпочитает .enc, потому что его и экспортирует, — но проверка не о
        # том, что уедет в бандл, а о том, что УЖЕ изменилось. Живой прогон
        # 2026-08-10 показал цену разницы: .env от 08.08, .env.enc от 23.07,
        # бандл от 05.08 — версия «предпочесть .enc» рапортовала отставание
        # 0.0 суток, хотя рабочий .env ушёл вперёд бандла на двое суток.
        for name in (".env", ".env.enc"):
            f = live_tree / name
            if f.exists():
                material.append({"name": f.name, "mtime": f.stat().st_mtime})
        secrets_dir = live_tree / ".secrets"
        if secrets_dir.is_dir():
            for pattern in BUNDLE_MATERIAL_GLOBS:
                for f in secrets_dir.glob(pattern):
                    if f.is_file():
                        material.append({"name": f.name, "mtime": f.stat().st_mtime})

        newest = None
        searched = []
        for d in bundle_dirs:
            d = Path(d)
            searched.append(str(d))
            if not d.is_dir():
                continue
            for f in d.glob(BUNDLE_GLOB):
                if not f.is_file():
                    continue
                m = f.stat().st_mtime
                if newest is None or m > newest["mtime"]:
                    newest = {"name": f.name, "mtime": m}
        return {"material": material, "bundle": newest, "searched": searched, "error": None}
    except Exception as exc:
        return {"material": [], "bundle": None,
                "searched": [str(d) for d in bundle_dirs],
                "error": "%s: %s" % (type(exc).__name__, exc)}


def _restore_drill_snapshot(live_tree: Path = LIVE_TREE) -> dict | None:
    """Снимок для одиннадцатой пробы: разобранный вердикт дрила.

    ТОЛЬКО ЧТЕНИЕ. Улику пишет дрил на ноутбуке, сторож её не трогает.

    🔴 `None` (проба НЕ регистрируется) РОВНО в одном содержательном случае:
    в окружении нет `JARVIS_BACKUP_PUBLIC_KEY`. Без публичного ключа
    клиентский набор не шифруется и не уезжает ПО ПОСТРОЕНИЮ (§3.3 B) —
    дрилу нечего проверять, и красная лампа горела бы по построению, то есть
    была бы фоном: ровно дефект DEV-47, который мы не повторяем. Как только
    ключ появился, проба регистрируется, и отсутствие вердикта — уже красное.
    Условие проверяемо в ОБЕ стороны: без ключа снимка нет; с ключом и без
    файла вердикта проба обязана сказать `drill_never`.

    Отсутствие файла вердикта — НЕ повод для `None`: это и есть повод для
    алерта (`verdict=None` → `drill_never`). `error` — другое: файл ЕСТЬ, но не
    разбирается, и тогда мы не знаем, а не знаем-что-нет.

    Форма проверяется здесь, а не импортом `read_verdict`: этот скрипт
    stdlib-ONLY и обязан работать, когда `app/` мёртв (см. модульную
    docstring). Две проверки формы на один формат названы в docstring модуля
    `app/services/restore_drill_verdict.py` — они обязаны краснеть на одном и
    том же наборе поломок."""
    if not os.environ.get(BACKUP_PUBLIC_KEY_VAR, "").strip():
        return None
    if not live_tree.exists():
        return None

    path = live_tree / RESTORE_DRILL_REL
    base = {"path": str(path), "verdict": None, "error": None}
    try:
        raw = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return base
    except Exception as exc:
        return dict(base, error="%s: %s" % (type(exc).__name__, exc))

    try:
        data = json.loads(raw)
        if not isinstance(data, dict):
            raise ValueError("вердикт не JSON-объект: %s" % type(data).__name__)
        missing = [f for f in ("ran_at", "ok", "expected", "actual", "detail")
                   if f not in data]
        if missing:
            raise ValueError("в вердикте нет полей: %s" % ", ".join(missing))
        ran_at = data["ran_at"]
        # `bool` исключается явно: `isinstance(True, int)` истинно, и
        # `ran_at: true` проехало бы как формально годная отметка времени.
        if isinstance(ran_at, bool) or not isinstance(ran_at, (int, float)):
            raise ValueError("ran_at не число: %r" % (ran_at,))
        if not isinstance(data["ok"], bool):
            # Строка "false" истинна в Python: провал прочитался бы зелёным.
            raise ValueError("ok не bool: %r" % (data["ok"],))
    except Exception as exc:
        return dict(base, error="%s: %s" % (type(exc).__name__, exc))

    return dict(base, verdict={"ran_at": float(ran_at), "ok": data["ok"],
                               "expected": data["expected"],
                               "actual": data["actual"],
                               "detail": data["detail"]})


def main() -> int:
    state = _read_state()

    # DEV-24: ребут проверяем ПЕРВЫМ и шлём отдельным сообщением. Он не
    # зависит от здоровья сервисов — наоборот, чаще всего они уже здоровы
    # (гардианы подняли), и именно поэтому раньше ребут проходил незаметно.
    reboot_text = None
    in_boot_grace = False
    boot_time = _boot_time()
    if boot_time is not None:
        fired, state = detect_reboot(
            state, boot_time, time.time(),
            warn=lambda msg: print("[ops_watchdog] %s" % msg, file=sys.stderr))
        if fired:
            reboot_text = reboot_alert_text(boot_time, time.time())
        # Окно проверяем ОТДЕЛЬНО от факта детекта: 🚨 прилетали в 07:01-07:03,
        # то есть на нескольких тиках подряд, а не только на том, где сменился
        # boot_id. Подавлять надо всё окно, иначе дедупликация ничего не даст.
        in_boot_grace = within_boot_grace(boot_time, time.time())

    # Оба снимка берутся ПО ОДНОМУ РАЗУ и делятся между семействами проб.
    # Это не экономия вызовов, а единственность источника: второй
    # `_panel_client_snapshot()` рядом означал бы второй сбор адреса, а второй
    # `_roster_snapshot()` — второй состав фермы. Оба разъехались бы молча.
    chatter_snap = _chatter_snapshot()
    panel_snap = _panel_client_snapshot()
    # §5.1: снимок связи берётся ОДИН раз на цикл и живёт до конца main() — его
    # читают и пробы, и вердикт для пинга (§5.2). Второе измерение рядом дало бы
    # два ответа на один вопрос, и разошлись бы они ровно в тот момент, когда
    # провод мигает.
    reach_snap = _reachability_snapshot()
    probes = probe_all(_http_get, _disk_usage,
                       chatter_snapshot=chatter_snap,
                       worktree_snapshot=_worktree_snapshot(),
                       secrets_snapshot=_secrets_bundle_snapshot(),
                       panel_client_snapshot=panel_snap,
                       restore_drill_snapshot=_restore_drill_snapshot(),
                       token_at_rest_snapshot=_token_at_rest_snapshot(),
                       attention_snapshot=_attention_snapshot(
                           (chatter_snap or {}).get("roster"), panel_snap),
                       # Тот же ростер и тот же снимок панели: состав фермы и
                       # адрес инстанса собираются ПО ОДНОМУ разу на цикл, а
                       # семейства проб их делят. Второй сбор любого из них —
                       # второй источник правды, и разъедутся они молча.
                       outgoing_snapshot=_outgoing_snapshot(
                           (chatter_snap or {}).get("roster"), panel_snap),
                       reachability_snapshot=reach_snap)
    # Ядро зовётся НАПРЯМУЮ, а не через `transitions()` + `evaluate()`: второе
    # свернуло бы пробы в состояние ДВАЖДЫ, и владелец получил бы по два 🚨 на
    # падение. Тексты берутся из `to_owner`, а не из журнала: единственный
    # переход, существующий только для журнала, — подъём после ПОДАВЛЕННОГО
    # падения, и ✅ о том, о чём не было 🚨, читается как «чинили без меня».
    journal, to_owner, state = _transitions(
        state, probes, suppress_down=in_boot_grace)
    # Ключи слагов, исчезнувших из ростера, и легаси-ключ уезжают ПОСЛЕ
    # переходов и ДО записи: иначе файл состояния растёт слагами, а мёртвая
    # запись однажды прочитается как чья-то. Чистка молчит, когда ростер
    # неизвестен, — см. `prune_client_state`.
    state = prune_client_state(state, probes)
    # Вердикт связи кладётся на диск ПОСЛЕ переходов и ДО всякой отправки.
    #
    # ПОСЛЕ — потому что дебаунс живёт в `state`, и вердикт обязан считаться по
    # тому же счётчику, что и все прочие пробы. Считать его до переходов значило
    # бы завести ВТОРОЙ дебаунс, а два числа на одну вещь всегда кончаются тем,
    # что меньшее гасит большее молча.
    #
    # ДО отправки — потому что читатель вердикта (скрипт пинга) обязан получить
    # свежий ответ, даже если дальше в цикле всё развалится. То же правило, что
    # и у следа §5.3: сперва улика на диск, потом провод.
    write_reachability_verdict(reach_snap, state)
    # Тексты собирает `group_alerts` — тот же сборщик, что и у `evaluate()`.
    # Здесь стояла своя сборка, и она уже разошлась с той: фильтра по
    # `ALERTING_KINDS` в ней не было, поэтому падение в загрузочном окне
    # уезжало владельцу как 🚨 DOWN — то самое, о чём `suppressed` обещает
    # молчать. Второй сборщик текстов — второе определение того, что владелец
    # услышит; их и должно быть ноль.
    alerts = group_alerts(to_owner)

    if reboot_text and boot_time is not None:
        # В НАЧАЛО списка: ребут объясняет всё, что записано следом.
        journal.insert(0, reboot_record(boot_time, time.time()))

    # §5.3: каждая отправка оставляет след НА ДИСКЕ до провода и исход после.
    # `kind` различает поводы: «ничего не дошло» и «не дошёл конкретно вердикт
    # журнала» — разные аварии, и по общему следу их не разделить.
    if reboot_text:
        _send_tg(reboot_text, kind="reboot")
    for text in alerts:
        _send_tg(text, kind="alert")

    # Маркер живости — В КОНЦЕ и только при успехе: провал записи обязан
    # показывать себя протухающим маркером, а не тонуть в тишине (§2.5).
    trim_report = {}
    written = journal_append(journal, trim_report=trim_report)
    if written:
        touch_beat()
    journal_alerts, state = note_journal_health(state, written)
    # Порог передаётся ЯВНО, а не берётся умолчанием: умолчание связывается на
    # `def`, и подменить его в сторожах `main()` нельзя — сторож пришлось бы
    # писать через саму константу, то есть слепым к её правке. Гейт показал это
    # фактом: с порогом, поднятым до миллиарда, тест не покраснел, а просто шёл
    # 14 минут 47 секунд. (Число здесь НЕ повторяется цифрами намеренно: гейт
    # ищет фрагмент подстрокой, и копия в комментарии стала бы вторым местом,
    # куда мутация может попасть вместо самой константы.)
    trim_alerts, state = note_trim_health(state, trim_report,
                                          JOURNAL_TRIM_FAIL_STREAK)
    for text in journal_alerts + trim_alerts:
        _send_tg(text, kind="journal")

    # Стейт пишется ПОСЛЕДНИМ: в нём теперь живёт и дедуп жалобы на журнал,
    # а он обязан пережить цикл, иначе 🚨 повторится через 30 секунд.
    _write_state(state)
    return 0


if __name__ == "__main__":
    sys.exit(main())
