def _norm(text: str) -> str:
    return (text or "").replace("\\", "/").lower()


def chatter_beat_age(ages):
    """Возраст живости chatter по ОБЕИМ формам отметки -> (возраст, источник).

    Берём САМУЮ СВЕЖУЮ отметку, а не самую старую, и это осознанный выбор.
    Смена формы оставляет файл-сироту (после отката 16.08 таким остался
    `chatter_heartbeat_volska.txt`), и правило «красим по самому старому»
    сделало бы каждого выведенного клиента вечным красным — то есть заменило
    бы одно «врёт навсегда» другим.

    ⚠️ НАЗВАННОЕ ОГРАНИЧЕНИЕ: пока жив хоть один клиент, смерть соседа этот
    канал не покажет. Так и задумано — проба даёт ОДИН булев сигнал про
    chatter в целом и реестра не знает (её проверка процесса ровно так же
    «любой раннер», а не «каждый»). Per-client ливность — работа гардиана.
    Ограничение зафиксировано тестом, чтобы всплыло при подключении второго
    клиента, а не выяснилось следующей аварией.

    Источник возвращаем вместе с возрастом: без имени файла разбор аварии
    снова начинается с догадки, по какой разметке вынесен вердикт.
    """
    known = {name: age for name, age in (ages or {}).items() if age is not None}
    if not known:
        return (None, None)
    source = min(known, key=lambda name: known[name])
    return (known[source], source)


def read_roster(text):
    """Реестр клиентов -> `[{"slug": str, "enabled": bool}, ...]`.

    Бросает на всём, что не разбирается: «реестр не прочитан» и «клиентов нет»
    — РАЗНОЕ (§6 спеки). Пустой ростер вместо ошибки означал бы ферму, которая
    ненаблюдаема и при этом зелена.

    `enabled` по умолчанию **False** — тем же умолчанием, что у боевого
    парсера `chatter/core/client_registry.py`. Обратное умолчание дало бы
    алерт о клиенте, которого никто не поднимает.
    """
    import yaml                      # не stdlib; отсутствие ловится вызывающим

    data = yaml.safe_load(text)
    if not isinstance(data, dict):
        raise ValueError("реестр не словарь: %s" % type(data).__name__)
    clients = data.get("clients")
    if not isinstance(clients, dict):
        raise ValueError("clients не словарь: %s" % type(clients).__name__)
    out = []
    for slug, cfg in clients.items():
        cfg = cfg if isinstance(cfg, dict) else {}
        out.append({"slug": str(slug),
                    "enabled": bool(cfg.get("enabled", False)),
                    # Порт клиентской панели этого слага; `None` — панели нет.
                    # Разбор ЗЕРКАЛИТ боевой `_panel_port` в
                    # `chatter/core/client_registry.py`: `import chatter` тут
                    # запрещён (watchdog stdlib-only, чтобы уметь сказать
                    # «бэкенд мёртв» тогда, когда мертво всё, что делит с ним
                    # окружение), поэтому парсера ДВА — и их согласие предмет
                    # отдельного сторожа, а не внимательности.
                    "panel_port": _roster_panel_port(cfg)})
    return out


def _roster_panel_port(cfg: dict):
    """Порт панели из записи реестра. Битое значение — `None`, а не бросок.

    Здесь умолчание МЯГЧЕ, чем у боевого парсера, и это осознанно: боевой
    отвергает битую секцию, потому что по ней поднимают процесс. Watchdog
    только НАБЛЮДАЕТ, и падение всего цикла из-за опечатки в чужой секции
    погасило бы двадцать две пробы ради одной. Опечатка проявит себя тем, что
    панель не поднимется, а лампа останется красной, — то есть громко.
    """
    panel = cfg.get("panel")
    if not isinstance(panel, dict):
        return None
    try:
        port = int(panel.get("port"))
    except (TypeError, ValueError):
        return None
    return port if 1 <= port <= 65535 else None


def probe_roster(snapshot: dict) -> dict:
    """Знаем ли мы вообще состав фермы.

    Красное здесь — не «клиент умер», а «мы не знаем, за кем следить». Пока
    проба красная, пер-клиентных проб НЕТ и состояние их ключей не трогается
    (см. `prune_client_state`): секундный сбой чтения реестра не имеет права
    вымывать `alerted` у всех.
    """
    error = (snapshot or {}).get("error")
    if error:
        return {"ok": False, "reason": "roster_unreadable",
                "detail": "реестр клиентов не прочитан: %s" % error}
    clients = list((snapshot or {}).get("clients") or [])
    enabled = [c for c in clients if c.get("enabled")]
    return {"ok": True, "detail": "включено %d из %d" % (len(enabled), len(clients))}


def _names_client(cmdline, slug) -> bool:
    """`--client <slug>` или `--client=<slug>` — ТОКЕНОМ, не подстрокой.

    Подстрока сделала бы `volska` вечно живым за счёт соседа `volska2`.
    """
    toks = (cmdline or "").split()
    want = str(slug).lower()
    for i, tok in enumerate(toks):
        low = tok.lower()
        if low == CHATTER_CLIENT_FLAG and i + 1 < len(toks):
            if toks[i + 1].lower() == want:
                return True
        if low.startswith(CHATTER_CLIENT_FLAG + "=") and low.split("=", 1)[1] == want:
            return True
    return False


def probe_client_runner(processes, *, slug, beat_age, root):
    """Жив ли раннер КОНКРЕТНОГО клиента: процесс И свежая отметка.

    Та же пара условий, что у общей пробы, и те же две защиты: матч только по
    python-процессу (иначе проба ловит того, кто её выполняет — разбор 29.07) и
    только с корнем ЖИВОГО дерева со слешем на конце (иначе раннер из worktree
    сходит за боевой). Третья защита новая: слаг сверяется ТОКЕНОМ аргумента.

    Причины раздельные и без секунд: возраст растёт каждый цикл, а дедуп в
    `_transitions` идёт по причине — секунды в ней дали бы алерт раз в 30 с.
    """
    root_n = _norm(str(root)).rstrip("/") + "/"
    alive = [
        p for p in (processes or [])
        if (p.get("name") or "").lower().startswith("python")
        and CHATTER_RUNNER_MARKER in _norm(p.get("cmdline"))
        and root_n in _norm(p.get("cmdline"))
        and _names_client(p.get("cmdline"), slug)
    ]
    if not alive:
        return {"ok": False, "reason": "no_process",
                "detail": "%s: процес раннера не знайдено" % slug}
    if beat_age is None:
        return {"ok": False, "reason": "no_heartbeat",
                "detail": "%s: heartbeat відсутній" % slug}
    if beat_age > CHATTER_BEAT_MAX_AGE_S:
        return {"ok": False, "reason": "stale_heartbeat",
                "detail": "%s: heartbeat %.0fс тому (поріг %ds)"
                          % (slug, beat_age, CHATTER_BEAT_MAX_AGE_S)}
    return {"ok": True, "detail": "%s: PID %s, heartbeat %.0fс тому"
                                  % (slug, alive[0].get("pid"), beat_age)}


def probe_beat_legacy(age, *, max_age=CHATTER_BEAT_MAX_AGE_S):
    """Легаси-отметка `chatter_heartbeat.txt` — НЕ источник живости, а новость.

    Три исхода, и красный ровно один — тот, который является новостью:

    * файла нет — зелёное: состояние, к которому идём;
    * файл есть и ПРОТУХ — зелёное: сегодняшняя норма, файл лежит сиротой с
      16.08. Красная лампа на нём горела бы вечно, то есть стала бы фоном, а
      сигнал, всегда красный при нормальной работе, — не сторож;
    * файл есть и СВЕЖ — красное: кто-то ПИШЕТ отметку вне пер-клиентной
      разметки, значит живёт раннер, которого ростер не видит.
    """
    if age is None:
        return {"ok": True, "detail": "легаси-отметки нет"}
    if age > max_age:
        return {"ok": True, "detail": "сирота, возраст %.0fс" % age}
    return {"ok": False, "reason": "legacy_beat_alive",
            "detail": "легаси-отметка ОБНОВЛЯЕТСЯ (%.0fс тому): есть раннер вне "
                      "пер-клиентной разметки" % age}


def prune_client_state(state: dict, probes: dict) -> dict:
    """Убрать записи слагов, которых больше нет в ростере, и легаси-ключ.

    ТОЛЬКО при зелёном `chatter_roster`: красный означает «состава не знаем», и
    чистка в этот момент вымыла бы `alerted` у всех — то есть проглотила бы
    первый алерт после восстановления чтения.

    Легаси-ключ `chatter_runner` уезжает той же миграцией: оставить его значит
    держать вечно-зелёную запись, которую никто не считает.
    """
    roster = probes.get("chatter_roster")
    if not roster or not roster.get("ok"):
        return state
    live = {k for k in probes if is_client_check(k)}
    # Какие СЕМЕЙСТВА в этом цикле вообще мерились. Нужно из-за асимметрии,
    # которую нельзя схлопнуть:
    #   раннеры    — их состав определяет тот же ростер, что и условие выше;
    #                пусто у них означает «включённых клиентов нет», и чистка
    #                верна. Поведение остаётся прежним дословно;
    #   эскалации  — эти семейства могут отсутствовать ЦЕЛИКОМ при зелёном
    #   и отправка   ростере (нет `run_panel_client.py` — watchdog не на
    #                деплой-хосте, см. `_client_ops_snapshot`). Пусто у них
    #                означает «не мерили», и чистка вымыла бы `alerted` у всех —
    #                ровно то, от чего защищает условие на зелёный ростер выше.
    #                Список таких семейств — `SNAPSHOT_FAMILIES`, ОДНО место:
    #                второе семейство приехало сюда копией условия, третье
    #                стало бы копией копии, и однажды копию забыли бы.
    families_live = {client_family_of(k) for k in live}
    out = {}
    for key, value in state.items():
        if key == "chatter_runner":
            continue
        family = client_family_of(key)
        if family == CLIENT_PROBE_PREFIX and key not in live:
            continue
        if (family in SNAPSHOT_FAMILIES and family in families_live
                and key not in live):
            continue
        out[key] = value
    return out


def probe_chatter_runner(processes, *, beat_age, root, semidemo_flag=False,
                         beat_source=None):
    """Раннер жив? Процесс И свежий heartbeat — оба условия обязательны:
    живой процесс с протухшим beat это зависший раннер, а не здоровье.

    ⚠️ Матч ТОЛЬКО по python-процессу и ТОЛЬКО с нашим ROOT в командной строке.
    Без первого условия проба ловит того, кто её же и выполняет (строка-маркер
    попадает в командную строку искателя — ложное «раннер жив», стоило разбора
    29.07). Без второго — чужой раннер из worktree разработчика сойдёт за
    боевой, и сторож замолчит на мёртвом проде.

    `semidemo_flag` принимается и НАМЕРЕННО игнорируется (ловушка 4 спеки):
    проба меряет ПРОЦЕСС; отключённые флагом клиенты — предмет (б)/(г), и
    алерт по ним превратил бы сторожа в постоянный крик на законное состояние.
    """
    # Со СЛЕШЕМ на конце: голая подстрока "c:/jarvis" сидит внутри
    # "c:/jarvis_worktrees/panels/...", и раннер из чужого worktree сходил за
    # боевой — сторож замолчал бы на мёртвом проде, пока рядом крутится тест.
    root_n = _norm(str(root)).rstrip("/") + "/"
    alive = [
        p for p in (processes or [])
        if (p.get("name") or "").lower().startswith("python")
        and CHATTER_RUNNER_MARKER in _norm(p.get("cmdline"))
        and root_n in _norm(p.get("cmdline"))
    ]
    if not alive:
        return {"ok": False, "detail": "процес раннера не знайдено",
                "reason": "no_process"}
    if beat_age is None:
        return {"ok": False, "detail": "heartbeat відсутній",
                "reason": "no_heartbeat"}
    if beat_age > CHATTER_BEAT_MAX_AGE_S:
        # Причина БЕЗ секунд: возраст растёт каждый цикл, и текст в ключе
        # дедупа означал бы алерт раз в 30 секунд.
        return {"ok": False, "reason": "stale_heartbeat",
                "detail": "heartbeat %.0fс тому (поріг %ds)" % (beat_age, CHATTER_BEAT_MAX_AGE_S)}
    # Имя файла в detail: оператор обязан видеть, ПО КАКОЙ разметке вынесен
    # вердикт. Ровно этого не хватило 16.08, чтобы отличить «раннер мёртв» от
    # «сторож смотрит не туда».
    src = " (%s)" % beat_source if beat_source else ""
    return {"ok": True, "detail": "PID %s, heartbeat %.0fс тому%s"
                                  % (alive[0].get("pid"), beat_age, src)}


def probe_chatter_guardian(processes, *, lock_pid, beat_age):
    """Гардиан жив? PID из state/locks/chatter_guardian.pid ДОЛЖЕН существовать
    И быть powershell'ом.

    ⚠️ ЛОВУШКА 3 спеки: PID-файл переживает kill. Если ОС успела выдать тот же
    номер чужому процессу, «PID существует» не значит «гардиан жив» — поэтому
    сверяем имя процесса, а не только наличие номера.
    """
    if lock_pid is None:
        return {"ok": False, "detail": "PID-лок відсутній або нечитний",
                "reason": "no_lock"}
    match = next((p for p in (processes or []) if p.get("pid") == lock_pid), None)
    if match is None:
        return {"ok": False, "detail": "PID %s мертвий" % lock_pid,
                "reason": "dead_pid"}
    if not (match.get("name") or "").lower().startswith("powershell"):
        return {"ok": False, "reason": "stale_lock",
                "detail": "PID %s зайнятий чужим процесом (%s), лок протух — очікувався powershell"
                          % (lock_pid, match.get("name"))}
    if beat_age is None:
        return {"ok": False, "detail": "heartbeat гардіана відсутній",
                "reason": "no_heartbeat"}
    if beat_age > CHATTER_BEAT_MAX_AGE_S:
        return {"ok": False, "reason": "stale_heartbeat",
                "detail": "heartbeat %.0fс тому (поріг %ds)" % (beat_age, CHATTER_BEAT_MAX_AGE_S)}
    return {"ok": True, "detail": "PID %s, heartbeat %.0fс тому" % (lock_pid, beat_age)}


def probe_worktree(snapshot: dict, *, trunk: str = TRUNK_BRANCH) -> dict:
    """Восьмая проверка: живое дерево на транке и чисто по tracked-файлам.

    Почему это вообще сторож, а не дисциплина: дерево — деплой-путь гардиана.
    2026-08-10 оно дважды оказалось не в том состоянии (осталось на ветке арки
    после сессии; откат мутационного харнесса стёр незакоммиченную правку) —
    оба раза это поймало ВНИМАНИЕ, то есть ночью не поймало бы ничто.

    Обе причины называются вместе: узнав только про ветку, вернёшь её и решишь,
    что починил, — а грязные файлы останутся и уедут в деплой.

    Невозможность спросить git — тоже КРАСНОЕ. На машине, где git и есть
    механизм деплоя, «не смогли посмотреть» это аномалия, а зелёное здесь
    означало бы слепую зону ровно там, где мы её и закрываем."""
    error = (snapshot or {}).get("error")
    if error:
        return {"ok": False, "reason": "unreadable",
                "detail": "не удалось определить состояние дерева: %s" % error}

    branch = ((snapshot or {}).get("branch") or "").strip()
    dirty = list((snapshot or {}).get("dirty") or [])
    problems = []
    reasons = []

    if not branch:
        problems.append("ветка не определена")
        reasons.append("no_branch")
    elif branch != trunk:
        # Обе ветки в тексте: иначе непонятно, куда возвращать.
        problems.append("HEAD на «%s», ожидался «%s»" % (branch, trunk))
        reasons.append("branch:%s" % branch)

    if dirty:
        shown = ", ".join(line.strip() for line in dirty[:DIRTY_SHOWN])
        tail = "" if len(dirty) <= DIRTY_SHOWN else " и ещё %d" % (len(dirty) - DIRTY_SHOWN)
        problems.append("модифицировано tracked-файлов: %d (%s%s)" % (len(dirty), shown, tail))
        # Причина — ПУТИ, и все, а не количество и не первые DIRTY_SHOWN.
        # Счётчик не различал бы «один файл сменился другим», а обрезка
        # сделала бы невидимым четвёртый файл — ровно тот, который и
        # окажется недеплоенным кодом. Статус-буквы git снимаем: « M x» и
        # «M  x» — одно состояние, алерт на смену пробелов был бы шумом.
        reasons.append("dirty:" + "|".join(sorted(
            line.strip().split(None, 1)[-1] for line in dirty)))

    if problems:
        return {"ok": False, "detail": "; ".join(problems),
                "reason": "; ".join(reasons)}
    return {"ok": True, "detail": "%s, чисто" % trunk}


def probe_secrets_bundle(snapshot: dict, *,
                         max_lag_days: float = BUNDLE_MAX_LAG_DAYS) -> dict:
    """Девятая проверка: копия секретов не отстала от материала.

    Красное, если бандла нет вовсе, если материал новее бандла больше чем на
    `max_lag_days`, или если каталог с бандлами не удалось прочитать. Обе
    причины называются В ОДНОМ алерте — тем же принципом, что у worktree-чека:
    узнав одну из двух, починишь её и решишь, что закрыл вопрос.

    Граница строгая (`>`): ровно на седьмые сутки владелец ещё в графике, а
    сторож, загорающийся на самой границе, приучает к тому, что он слегка врёт.

    Порог — напоминание, а не SLA: экспорт ручной, пароль вводит владелец, и
    сторож не может и не должен делать копию сам.

    ГРАНИЦА (PROBLEMS P26): сравниваются ДАТЫ, а не содержимое. Переэкспорт из
    устаревшего `.env.enc` даёт свежий mtime при старом содержимом — здесь это
    зелёное. Содержимое доказывает только `scripts/verify_bundle.py`, который
    открывает бандл паролем; гонять его после каждого экспорта."""
    error = (snapshot or {}).get("error")
    if error:
        return {"ok": False, "reason": "unreadable",
                "detail": "не удалось проверить копию секретов: %s" % error}

    material = list((snapshot or {}).get("material") or [])
    bundle = (snapshot or {}).get("bundle")
    searched = list((snapshot or {}).get("searched") or [])
    problems = []

    reasons = []
    if not material:
        # Не «нечего бэкапить», а «мы ничего не увидели»: зелёное здесь было бы
        # слепой зоной вокруг единственного пути восстановления.
        problems.append("материал секретов не найден — сравнивать не с чем")
        reasons.append("no_material")

    if bundle is None:
        where = ", ".join(searched) if searched else "каталоги не заданы"
        problems.append("бандла %s нет (искали: %s)" % (BUNDLE_GLOB, where))
        reasons.append("no_bundle")

    if problems:
        return {"ok": False, "detail": "; ".join(problems),
                "reason": "; ".join(reasons)}

    newest = max(material, key=lambda m: m.get("mtime") or 0.0)
    lag_days = ((newest.get("mtime") or 0.0) - (bundle.get("mtime") or 0.0)) / 86400.0
    lag_days = max(lag_days, 0.0)          # бандл свежее материала — не «минус дней»

    if lag_days > max_lag_days:
        others = len(material) - 1
        tail = "" if others <= 0 else " и ещё %d файл(ов)" % others
        # Причина без числа дней: отставание растёт само по себе.
        return {"ok": False, "reason": "stale", "detail":
                "бандл %s отстал на %.1f сут (порог %.0f): новее всего «%s»%s" % (
                    bundle.get("name"), lag_days, max_lag_days, newest.get("name"), tail)}

    return {"ok": True, "detail": "бандл %s, отставание %.1f сут (порог %.0f)" % (
        bundle.get("name"), lag_days, max_lag_days)}


def probe_token_at_rest(snapshot: dict) -> dict:
    """DEV-74: учётные данные не лежат в данных.

    Красное, если под живым `state/` нашёлся хоть один файл с `bot<цифры>:`.
    Файлы НАЗЫВАЮТСЯ поимённо — «где-то есть токен» не чинится.

    Нечитаемый каталог — тоже красное (`unreadable`), а не зелёное: «не смогли
    посмотреть» и «посмотрели, чисто» — разные ответы, и подменять первый
    вторым значит гасить пробу ровно тогда, когда она нужнее всего.

    Охват СУЖЕН осознанно (см. TOKEN_SCAN_SKIP_*), и суженное называется в
    detail даже на зелёном: проба, молчащая про то, чего не смотрела, врёт
    объёмом. Сам секрет в detail не попадает НИКОГДА — только путь к файлу:
    алерт уезжает в Telegram, и сторож, печатающий то, что охраняет, был бы
    вторым каналом утечки.
    """
    if not isinstance(snapshot, dict):
        return {"ok": False, "reason": "unreadable",
                "detail": "снимок токенов не собран"}
    error = snapshot.get("error")
    if error:
        return {"ok": False, "reason": "unreadable",
                "detail": "не удалось просмотреть state/: %s" % error}

    offenders = list(snapshot.get("offenders") or [])
    scanned = int(snapshot.get("scanned") or 0)
    oversize = int(snapshot.get("oversize") or 0)
    unread = int(snapshot.get("unreadable") or 0)

    # Хвост про охват одинаков на красном и на зелёном — иначе зелёное
    # выглядело бы полнее, чем оно есть.
    #
    # 🔴 «Слишком большой» и «не прочитался» считаются ОТДЕЛЬНО. Живой прогон
    # 25.08 показал цену слияния: проба рапортовала «по размеру пропущено 1»,
    # хотя файлов свыше порога не было ни одного — пропущен был занятый файл.
    # Одно число на две разные причины врёт про причину, а чинят их по-разному.
    tail = "просмотрено %d файлов, пропущено каталогов %s" % (
        scanned, ", ".join(TOKEN_SCAN_SKIP_DIRS))
    if oversize:
        tail += ", по размеру пропущено %d" % oversize
    if unread:
        tail += ", не прочиталось %d" % unread

    if offenders:
        shown = ", ".join(offenders[:5])
        if len(offenders) > 5:
            shown += " и ещё %d" % (len(offenders) - 5)
        return {"ok": False, "reason": "token_at_rest",
                "detail": "токен бота открытым текстом в данных: %s (%s)" % (shown, tail)}

    return {"ok": True, "detail": "токенов в данных нет (%s)" % tail}


def _token_at_rest_snapshot(live_tree: Path = LIVE_TREE) -> dict | None:
    """Снимок для пробы DEV-74: обход `state/` живого дерева.

    ТОЛЬКО ЧТЕНИЕ. Смотрит на LIVE_TREE, а не на дерево, из которого запущен:
    в worktree мерж-гейта `state/` гитигнорен и отсутствует, и относительный
    путь превратил бы пробу в вечное «нечего проверять».

    `None` (пробы в цикле НЕТ вовсе) — только если живого `state/` нет: это
    чужое окружение, а не авария. Каталог есть, но не читается → `error`,
    и это красное.
    """
    state = live_tree / "state"
    if not state.is_dir():
        return None
    offenders: list[str] = []
    scanned = 0
    oversize = 0
    unreadable = 0
    try:
        for p in state.rglob("*"):
            if not p.is_file():
                continue
            if set(TOKEN_SCAN_SKIP_DIRS) & set(p.parts):
                continue
            if p.suffix.lower() in TOKEN_SCAN_SKIP_SUFFIXES:
                continue
            try:
                if p.stat().st_size > TOKEN_SCAN_MAX_FILE_BYTES:
                    oversize += 1
                    continue
                blob = p.read_bytes()
            except OSError:
                # Одиночный неподатливый файл (занят, гонка) не должен ронять
                # весь обход — но и молчать о нём нельзя: считаем как
                # непросмотренный, а не как чистый. И считаем ОТДЕЛЬНО от
                # «слишком большого»: причины разные и чинятся по-разному.
                unreadable += 1
                continue
            scanned += 1
            if TOKEN_AT_REST_RE.search(blob):
                try:
                    offenders.append(str(p.relative_to(live_tree)))
                except ValueError:
                    offenders.append(p.name)
        return {"offenders": sorted(offenders), "scanned": scanned,
                "oversize": oversize, "unreadable": unreadable, "error": None}
    except Exception as exc:
        return {"offenders": [], "scanned": scanned, "oversize": oversize,
                "unreadable": unreadable,
                "error": "%s: %s" % (type(exc).__name__, exc)}


def _drill_numbers(values) -> str:
    """Величины §4.3 одной строкой, в порядке ключей — для detail."""
    if not isinstance(values, dict) or not values:
        return "—"
    return ", ".join("%s=%s" % (k, values[k]) for k in sorted(values))


def probe_restore_drill(snapshot: dict, *,
                        max_lag_days: float = DRILL_MAX_LAG_DAYS,
                        future_tolerance_s: float = DRILL_FUTURE_TOLERANCE_S,
                        now: float | None = None) -> dict:
    """Одиннадцатая проверка: дрил восстановления подтвердил клиентский бэкап.

    🔴 ТРИ СОСТОЯНИЯ, А НЕ ДВА (DEV-46 §9.4). Одна лампа «дрил не зелёный»
    склеивает два положения дел с ПРОТИВОПОЛОЖНЫМИ действиями: «провалился» —
    бэкап негоден, чинить срочно; «не гонялся» — не известно НИЧЕГО, и бэкап
    при этом может быть в полном порядке. После §9.2 второе будет случаться
    регулярно и по бытовой причине (ноутбук выключен, владелец в отъезде), а
    склеенная лампа приучает читать красное как «опять ноутбук» — и настоящий
    провал прочтут так же. Это ровно DEV-43, только в сторожевой пробе.

    Поэтому `reason` присутствует ВСЕГДА, в том числе на зелёном: иначе три
    состояния неразличимы машинно, а дедуп по причине (см. модульную
    docstring) не увидит смены состояния красного на другое красное.

      `drill_ok`     вердикт есть, ok: true, возраст в пределах порога
      `drill_failed` вердикт есть, ok: false — дрил нашёл расхождение
      `drill_stale`  вердикт есть, но прогон старше порога — пропуск запуска
      `drill_never`  вердикта нет вовсе — задача не заведена или ни разу не шла
      `unreadable`   вердикт есть, но возраст недоказуем: битая форма ЛИБО
                     отметка прогона в будущем сверх допуска

    `drill_never` и `drill_stale` РАЗНЫЕ, хотя оба «не гонялся»: первое
    чинится заведением задачи, второе — разбором пропуска. Различие стоит одну
    строку, а склейка стоит правильной реакции.

    🔴 ВОЗРАСТ СЧИТАЕТСЯ ПО `ran_at` ВНУТРИ ВЕРДИКТА, А НЕ ПО MTIME ФАЙЛА.
    Файл переезжает между машинами (§9.2 п. 2) — mtime переезда это время
    копирования, а не время проверки, и по нему протухший дрил выглядел бы
    свежим ровно тогда, когда улику перевезли заново.

    Граница строгая (`>`), как у `probe_secrets_bundle`.

    Ни одно состояние не зелёное по умолчанию: нет файла — красное, не
    разобрались — красное. Отметка прогона в БУДУЩЕМ сверх
    `future_tolerance_s` — тоже красное, и именно `unreadable`: см. комментарий
    в теле, проверка стоит ПЕРЕД разбором `ok`."""
    now = time.time() if now is None else now
    snapshot = snapshot or {}

    error = snapshot.get("error")
    if error:
        return {"ok": False, "reason": "unreadable",
                "detail": "вердикт дрила не разбирается: %s" % error}

    verdict = snapshot.get("verdict")
    if not verdict:
        where = snapshot.get("path") or RESTORE_DRILL_REL
        return {"ok": False, "reason": "drill_never", "detail":
                "вердикта дрила нет ни разу (%s): задача на ноутбуке не "
                "заведена или ещё не отработала — о бэкапе не известно "
                "НИЧЕГО" % where}

    ran_at = verdict.get("ran_at") or 0.0
    ahead_s = ran_at - now

    # 🔴 ОТМЕТКА ИЗ БУДУЩЕГО СВЕРХ ДОПУСКА — ЭТО `unreadable`, И ПРОВЕРЯЕТСЯ
    # ОНА ПЕРВОЙ, ДО РАЗБОРА `ok`. Мы не «нашли провал» и не «знаем, что дрил не
    # гонялся»: мы НЕ МОЖЕМ ВЫЧИСЛИТЬ ВОЗРАСТ, а «возраст недоказуем» — это не
    # «прошёл». Та же мысль, по которой `unreadable` уже стоит на битой форме:
    # там нечитаема форма, здесь нечитаема отметка времени.
    #
    # Шестого состояния не заводим: пять значений `reason` перечислены
    # исчерпывающе. И вердикт из будущего с `ok: false` обязан попасть сюда же —
    # при разъехавшихся часах мы не знаем, о КАКОМ прогоне речь.
    if ahead_s > max(float(future_tolerance_s), 0.0):
        ahead_days = ahead_s / 86400.0
        span = ("%.1f сут" % ahead_days if abs(ahead_days) >= 1.0
                else "%.1f ч" % (ahead_s / 3600.0))
        return {"ok": False, "reason": "unreadable", "detail":
                "отметка прогона в БУДУЩЕМ на %s (допуск %.0f с): часы "
                "разъехались, возраст вердикта вычислить нечем — это НЕ "
                "«дрил прошёл»" % (span, future_tolerance_s)}

    # В пределах допуска — обычный рассинхрон часов: возраст неотрицательный,
    # как у `probe_secrets_bundle`, состояние дальше обычное.
    age_days = max((now - ran_at) / 86400.0, 0.0)

    numbers = "ждали {%s}, нашли {%s}" % (_drill_numbers(verdict.get("expected")),
                                          _drill_numbers(verdict.get("actual")))
    tail = (verdict.get("detail") or "").strip()

    if not verdict.get("ok"):
        # Провал важнее протухания и потому проверяется ПЕРВЫМ: «бэкап негоден»
        # остаётся верным и через месяц, а возраст всё равно назван в тексте.
        # Числа в detail обязательны — «restore failed» без них не говорит, что
        # чинить (§7 п. 6).
        return {"ok": False, "reason": "drill_failed", "detail":
                "дрил ПРОВАЛИЛСЯ: %s; прогон %.1f сут назад%s" % (
                    numbers, age_days, "; %s" % tail if tail else "")}

    if age_days > max_lag_days:
        # Причина без числа дней: отставание растёт само по себе, и дедуп по
        # причине слал бы алерт каждый цикл.
        return {"ok": False, "reason": "drill_stale", "detail":
                "дрил не гонялся %.1f сут (порог %.0f): последний прогон был "
                "зелёным, но он устарел — о СЕГОДНЯШНЕМ бэкапе не известно "
                "ничего" % (age_days, max_lag_days)}

    return {"ok": True, "reason": "drill_ok", "detail":
            "дрил зелёный %.1f сут назад (порог %.0f): %s" % (
                age_days, max_lag_days, numbers)}


def probe_panel_client(snapshot: dict) -> dict:
    """Десятая проверка: клиентская панель отвечает на своём порту.

    Аргумент — СНИМОК, одним позиционным словарём, как у `probe_worktree` и
    `probe_secrets_bundle`. Форма:

        {"host": <str|None>, "port": <int>, "status": <int|None>,
         "problem": <str|None>}

    `problem` может отсутствовать вовсе — читаем через `.get()`, отсутствие
    ключа не ошибка. Единая форма у всех снимочных проб не косметика: пока
    подпись была россыпью именованных аргументов, снимок уезжал в первый
    позиционный (`status`), `host` оставался пустым, и здоровая панель
    получала вердикт `no_bind_address`. Это худший из возможных отказов —
    «не смогли спросить» под видом измерения.

    Три исхода различаются ПРИЧИНОЙ, потому что чинятся они по-разному:

    * `no_bind_address` — адрес бинда не вычислился вовсе. Зелёное здесь было
      бы худшим из возможных: «не смогли спросить» выдавалось бы за «панель
      жива». Мерить в этом случае нечего, и говорить об этом надо вслух;
    * `no_response`     — на адресе никто не слушает: процесс мёртв, порт
      свободен. Это работа гардиана, и если она не сделана — гардиана нет;
    * `http:<код>`      — процесс жив и отвечает, но не 200: плохо ВНУТРИ
      живого процесса, гардиан тут не поможет.

    В `reason` не попадает ни адрес, ни секунды: `reason` — это ключ дедупа
    алертов, а адрес тайнета меняется сам по себе, и алерт на его смену был бы
    шумом. Адрес называется в `detail`, где ему и место: без него разбор снова
    начинается с догадки, КУДА ходила проба.
    """
    snapshot = snapshot or {}
    host = snapshot.get("host")
    port = snapshot.get("port", PANEL_CLIENT_PORT)
    status = snapshot.get("status")
    problem = snapshot.get("problem")

    host = (host or "").strip() if isinstance(host, str) else host
    if not host:
        # Причина от резолвера дословно — она объясняет, ПОЧЕМУ адреса нет
        # (сегодня единственный такой случай: `0.0.0.0` в PANEL_CLIENT_HOST,
        # который резолвер отвергает намеренно).
        detail = problem or "адрес бинда панели не вычислился"
        return {"ok": False, "reason": "no_bind_address", "detail": detail}

    where = "%s:%s%s" % (host, port, PANEL_CLIENT_HEALTH_PATH)
    if status is None:
        return {"ok": False, "reason": "no_response",
                "detail": "%s: нет ответа (refused/timeout)" % where}
    return {"ok": status == 200,
            "detail": "%s: HTTP %s" % (where, status),
            "reason": "http:%s" % status}


def _fmt_age(seconds) -> str:
    """Возраст СЛОВАМИ, а не голыми секундами. Только для `detail`.

    «2298240с» — это не число, которое читают: 26.6 суток и 6.4 часа владелец
    различает мгновенно, а семизначные секунды приходится делить в уме. В
    `reason` эта строка не попадает никогда — там дедуп, и любой возраст в нём
    дал бы алерт раз в 30 секунд.
    """
    if seconds is None:
        return "неизвестно"
    s = float(seconds)
    if s >= 86400.0:
        return "%.1f сут" % (s / 86400.0)
    if s >= 3600.0:
        return "%.1f ч" % (s / 3600.0)
    return "%.0f мин" % (s / 60.0)


def _attention_payload_problem(payload) -> str:
    """Что не так с телом `/ops/attention`. Пустая строка = тело годное.

    Требуются ЧЕТЫРЕ ключа контракта и их типы. Лишние ключи ошибкой НЕ
    считаются намеренно: проба, краснеющая от расширения ручки, была бы
    красной на здоровом инстансе — то есть фоном. Состав ответа В ОБЕ стороны
    пинится там, где он собирается, а не здесь.

    `stale_open > open` проверяется отдельно: это не придирка, а единственный
    способ поймать перепутанные местами числа — при котором проба продолжала бы
    выдавать осмысленные вердикты о неверной величине.
    """
    if not isinstance(payload, dict):
        return "ответ не JSON-объект"
    for name in ("open", "stale_open"):
        value = payload.get(name)
        # bool — подкласс int, и `True` прошёл бы как «одна карточка».
        if isinstance(value, bool) or not isinstance(value, int):
            return "%s не целое" % name
        if value < 0:
            return "%s отрицательное" % name
    for name in ("oldest_age_s", "oldest_wait_s"):
        if name not in payload:
            return "нет ключа %s" % name
        value = payload[name]
        if value is not None and (isinstance(value, bool)
                                  or not isinstance(value, (int, float))):
            return "%s не число и не null" % name
    if payload["stale_open"] > payload["open"]:
        return "stale_open больше open"
    return ""


def probe_attention(snapshot: dict) -> dict:
    """Одиннадцатая проверка, ПЕР-КЛИЕНТНАЯ: есть ли у клиента карточка
    эскалации, которую никто не открыл.

    Аргумент — СНИМОК, одним позиционным словарём, как у `probe_worktree`,
    `probe_secrets_bundle` и `probe_panel_client`. Россыпь именованных
    аргументов уже стоила вердикта `no_bind_address` на совершенно здоровой
    панели: снимок уезжал в первый позиционный, `host` оставался пустым.
    Форма:

        {"slug": <str>, "instance": <bool>, "host": <str|None>, "port": <int>,
         "status": <int|None>, "payload": <dict|None>, "problem": <str|None>}

    ИСХОДОВ ШЕСТЬ, и каждый чинится по-разному:

    * `no_bind_address` — адреса инстанса нет вовсе: мерить нечем;
    * `no_instance`     — клиент в ростере включён, а инстанса для него нет.
      Красное, а не зелёное и не отсутствие ключа: сегодня инстанс ОДИН
      (`yarina`), а из четырёх открытых карточек три принадлежат volska,
      включая самую старую — 26.6 суток. Проба, построенная «по инстансам»,
      была бы ЗЕЛЁНОЙ ПО ПОСТРОЕНИЮ ровно там, где лежит вся проблема;
    * `no_response`     — на адресе никто не слушает: работа гардиана;
    * `http:<код>`      — ответил не 200. **404 = ручки ещё нет**, то есть
      инстанс не перезапущен после деплоя; отличать это от «инстанс мёртв»
      обязательно, иначе обратный порядок выкатки даёт красное на здоровом;
    * `bad_payload`     — 200, но тело не той формы;
    * `attention_stale` — инстанс ЖИВ, ответил, и `stale_open > 0`.

    🔴 ПЕРВЫЕ ПЯТЬ — НОВОСТИ ПРО НАБЛЮДЕНИЕ («не знаю, читают ли карточки»),
    ШЕСТОЙ — ПРО ДЕЛО («не читают»). Владелец читает ФРАЗУ, а не имя
    переменной, поэтому тексты `detail` различаются словами, а не только
    ключом: пять первых говорят «неизвестно», шестой — «никто не открыл».

    🔴 `bad_payload` КРАСНЫЙ, А НЕ ЗЕЛЁНЫЙ. Соблазн «не разобрали тело —
    значит всё тихо» даёт пробу, которая при ЛЮБОЙ поломке ручки говорит
    «карточки читают». Такая хуже отсутствующей: на зелёное никто не смотрит,
    в том и смысл зелёного.

    ПОРОГА У ПРОБЫ НЕТ. `stale_open` считает ИНСТАНС своим `STALE_AFTER`
    (48 ч) — тем же, которым панель красит блок «Требует вас». Второе число на
    ту же вещь погасило бы большее молча. Ровно поэтому решение «протухло или
    нет» принимает инстанс: watchdog stdlib-only и `app.*` не импортирует.

    В `reason` не попадает НИ ОДНОГО возраста и НИ ОДНОГО адреса: `reason` —
    ключ дедупа, возраст растёт каждый цикл, и секунды в нём дали бы алерт раз
    в 30 секунд. Адрес и числа живут в `detail`.

    ⚠️ `instance` при ОТСУТСТВИИ ключа читается как «инстанс есть»: снимок
    собирается здесь же и ключ ставит всегда, а умолчание «нет» превратило бы
    любой недособранный снимок в `no_instance` — то есть в вердикт о ростере
    вместо вердикта об инстансе. Зелёного это умолчание не даёт ни при каком
    входе: зелёное требует разобранного тела с `stale_open == 0`.
    """
    snapshot = snapshot or {}
    host = snapshot.get("host")
    host = (host or "").strip() if isinstance(host, str) else host
    port = snapshot.get("port", PANEL_CLIENT_PORT)

    if not snapshot.get("instance", True):
        return {"ok": False, "reason": "no_instance",
                "detail": "инстанса панели для этого клиента НЕТ — спросить "
                          "об эскалациях некого, читают ли его карточки, "
                          "неизвестно"}
    if not host:
        # Причина от резолвера дословно — она объясняет, ПОЧЕМУ адреса нет.
        return {"ok": False, "reason": "no_bind_address",
                "detail": (snapshot.get("problem")
                           or "адрес инстанса не вычислился") +
                          " — мерить нечем, читают ли карточки, неизвестно"}

    where = "%s:%s%s" % (host, port, ATTENTION_PATH)
    status = snapshot.get("status")
    if status is None:
        return {"ok": False, "reason": "no_response",
                "detail": "%s: нет ответа (refused/timeout) — инстанс молчит, "
                          "читают ли карточки, неизвестно" % where}
    if status != 200:
        # 404 назван вслух: это НЕ поломка, это порядок деплоя. Ручка едет
        # первой, проба второй; обратный порядок даёт красное на здоровом.
        hint = ("ручки ЕЩЁ НЕТ — инстанс не перезапущен после деплоя"
                if status == 404 else
                "инстанс жив, но ручка эскалаций не отвечает")
        return {"ok": False, "reason": "http:%s" % status,
                "detail": "%s: HTTP %s — %s, читают ли карточки, неизвестно"
                          % (where, status, hint)}

    payload = snapshot.get("payload")
    problem = _attention_payload_problem(payload)
    if problem:
        return {"ok": False, "reason": "bad_payload",
                "detail": "%s: HTTP 200, но тело не той формы (%s) — читают "
                          "ли карточки, неизвестно" % (where, problem)}

    open_n = payload["open"]
    stale_n = payload["stale_open"]
    if stale_n > 0:
        # Возрастов ДВА, и они про разное: `oldest_age_s` — сколько карточка
        # висит (НАШЕ обязательство), `oldest_wait_s` — сколько ждёт человек.
        # Старая карточка при свежем ожидании значит «лид ещё пишет»; оба
        # старые — «лид уже ушёл», и чинить поздно.
        return {"ok": False, "reason": "attention_stale",
                "detail": "%s: %d из %d %s эскалации НИКТО НЕ ОТКРЫЛ; самой "
                          "старой %s, человек ждёт ответа %s"
                          % (where, stale_n, open_n,
                             _plural(open_n, "карточки", "карточек", "карточек"),
                             _fmt_age(payload.get("oldest_age_s")),
                             _fmt_age(payload.get("oldest_wait_s")))}
    age = payload.get("oldest_age_s")
    return {"ok": True,
            "detail": "%s: открытых карточек %d, протухших нет%s"
                      % (where, open_n,
                         "" if age is None
                         else " (самой старой %s)" % _fmt_age(age))}


def _outgoing_payload_problem(payload) -> str:
    """Что не так с телом `/ops/outgoing`. Пустая строка = тело годное.

    Требуются ЧЕТЫРЕ ключа контракта и их типы; лишние ключи ошибкой не
    считаются (проба, краснеющая от расширения ручки, была бы красной на
    здоровом инстансе, то есть фоном).

    Две сверки СМЫСЛА, а не только типов, и обе ловят ровно то, что иначе
    прошло бы как осмысленный ответ о неверной величине:

    * `stuck` при пустой очереди — застрять нечему; так выглядит порог,
      применённый не к тому числу;
    * `pending > 0` без возраста — возраст самого старого задания обязан
      существовать, раз задание есть. Иначе лампа «застряло» слепа по
      построению: `stuck` считается из того самого возраста.

    `stuck` проверяется как BOOL строго: `bool` — подкласс `int`, и обратной
    ловушки («1» прошло бы как True) тут нет, но ЛЮБОЕ число вместо флага
    означает, что ручка отдаёт не то поле.
    """
    if not isinstance(payload, dict):
        return "ответ не JSON-объект"
    for name in ("pending", "refused"):
        value = payload.get(name)
        if isinstance(value, bool) or not isinstance(value, int):
            return "%s не целое" % name
        if value < 0:
            return "%s отрицательное" % name
    if "oldest_age_s" not in payload:
        return "нет ключа oldest_age_s"
    age = payload["oldest_age_s"]
    if age is not None and (isinstance(age, bool) or not isinstance(age, (int, float))):
        return "oldest_age_s не число и не null"
    if not isinstance(payload.get("stuck"), bool):
        return "stuck не булев"
    if payload["stuck"] and payload["pending"] == 0:
        return "stuck при пустой очереди"
    if payload["pending"] > 0 and age is None:
        return "pending есть, а возраста нет"
    return ""


def probe_public_door(snapshot: dict) -> dict:
    """Публичная дверь: жива ли, и — главное — ОТКАЗЫВАЕТ ли чужому.

    Аргумент — СНИМОК, одним позиционным словарём (форма та же, что у
    `probe_outgoing`: россыпь именованных уже стоила ложного вердикта на
    здоровой панели):

        {"enabled": <bool>, "host": <str|None>, "port": <int|None>,
         "no_token_status": <int|None>}

    `no_token_status` — код, которым дверь ответила на запрос БЕЗ токена.

    🔴 ГЛАВНОЕ ПРО ЭТУ ПРОБУ. Проверять «дверь отвечает» здесь недостаточно:
    такая лампа зелена и у РАСПАХНУТОЙ двери. Поэтому меряем не живость, а
    отказ: дверь обязана ответить чужому `401`.

    Исходов пять:

    * `off` — ключа нет, двери не существует. Это НОРМАЛЬНОЕ состояние, а не
      красное: до включения владельцем дверь и не должна существовать. Зелёное
      с причиной — тот же приём, что у `drill_ok`;
    * `no_address` — дверь объявлена включённой, а адреса нет: мерить нечем;
    * `no_response` — на адресе никто не слушает;
    * `door_refuses_strangers` — ответила `401`. ЕДИНСТВЕННОЕ зелёное «по делу»;
    * `door_accepts_without_token` — ответила `2xx` на запрос БЕЗ токена.
      Это не «лампа покраснела», это чужой уже может писать в диалоги клиента.
      Отдельной причиной от `http:<код>` намеренно: у них разная срочность и
      разный первый шаг.
    """
    if not snapshot.get("enabled"):
        return {"ok": True, "reason": "off"}
    if not snapshot.get("host") or not snapshot.get("port"):
        return {"ok": False, "reason": "no_address",
                "detail": "дверь включена, а адреса для проверки нет"}
    status = snapshot.get("no_token_status")
    if status is None:
        return {"ok": False, "reason": "no_response",
                "detail": "дверь включена, на %s:%s никто не слушает"
                          % (snapshot.get("host"), snapshot.get("port"))}
    status = int(status)
    if status == 401:
        return {"ok": True, "reason": "door_refuses_strangers"}
    if 200 <= status < 300:
        return {"ok": False, "reason": "door_accepts_without_token",
                "detail": "дверь приняла запрос БЕЗ токена (ответ %d): чужой "
                          "может писать в диалоги клиента ПРЯМО СЕЙЧАС" % status}
    return {"ok": False, "reason": "http:%d" % status,
            "detail": "дверь ответила %d там, где ждали 401" % status}


def probe_outgoing(snapshot: dict) -> dict:
    """Восемнадцатая проверка (нумерация контракта арки), ПЕР-КЛИЕНТНАЯ:
    уехало ли то, что владелец отправил из панели.

    Аргумент — СНИМОК, одним позиционным словарём, ФОРМА ТА ЖЕ, что у
    `probe_attention` (россыпь именованных аргументов уже стоила вердикта
    `no_bind_address` на здоровой панели: снимок уезжал в первый позиционный):

        {"slug": <str>, "instance": <bool>, "host": <str|None>, "port": <int>,
         "status": <int|None>, "payload": <dict|None>, "problem": <str|None>}

    ИСХОДОВ СЕМЬ, и каждый чинится по-разному:

    * `no_bind_address` — адреса инстанса нет вовсе: мерить нечем;
    * `no_instance`     — клиент в ростере включён, а инстанса для него нет
      (сегодня это volska: панели у неё НЕТ, и спросить некого);
    * `no_response`     — на адресе никто не слушает: работа гардиана;
    * `http:<код>`      — ответил не 200. **404 = ручки ещё нет** (инстанс не
      перезапущен после деплоя), **500 = базу не прочитали ИЛИ таблицы очереди
      в ней нет** (раннер не перезапущен на код с очередью — то есть нажатия
      владельца ложатся в базу и не уезжают никому);
    * `bad_payload`     — 200, но тело не той формы;
    * `outgoing_stuck`  — инстанс ЖИВ, ответил, и `stuck` — задание висит
      дольше порога инстанса, но ещё уедет, как только раннер поднимут;
    * `outgoing_refused` — есть НЕСНЯТЫЙ отказ: сообщение владельца не уйдёт
      НИКОГДА, причина названа словами в самом задании.

    🔴 ПЕРВЫЕ ПЯТЬ — НОВОСТИ ПРО НАБЛЮДЕНИЕ («не знаю, уехало ли»), ПОСЛЕДНИЕ
    ДВА — ПРО ДЕЛО («не уехало» и «не уедет»). Тексты `detail` различаются
    СЛОВАМИ, а не только ключом: владелец читает фразу, а не имя переменной.

    🔴 СТАРШИНСТВО: `outgoing_refused` ВАЖНЕЕ `outgoing_stuck`. «Потеряно
    навсегда» сильнее, чем «ещё едет», и `reason` (ключ дедупа) обязан называть
    ГЛАВНУЮ беду — иначе владелец пойдёт поднимать раннер там, где надо было
    прочитать причину и ответить лиду другим способом. Но `detail` в ОБОИХ
    случаях называет ОБА числа: одно число, погасившее второе, — известная
    грабля этого дома.

    🔴 У КРАСНОГО ОТКАЗА ЕСТЬ ПУТЬ СНЯТИЯ, и без него этот исход заводить было
    НЕЛЬЗЯ. Отказ терминален: строка сама не рассосётся, и лампа горела бы
    вечно, то есть за неделю стала бы фоном (класс, чиненный тут дважды).
    Гасит её владелец — `POST /api/outgoing/dismiss` переводит строку в
    `dismissed`, и она уходит из счётчика `refused`. Время не гасит ничего:
    «потерянное сообщение забылось само» — это не выздоровление.

    🔴 `bad_payload` КРАСНЫЙ, А НЕ ЗЕЛЁНЫЙ — соблазн «не разобрали тело, значит
    всё тихо» даёт пробу, которая при любой поломке ручки говорит «всё уехало».

    ПОРОГА У ПРОБЫ НЕТ. «Застряло или нет» решает ИНСТАНС своим
    `OUTGOING_STUCK_AFTER` — тем же числом, которым он ответит и панели.
    Второго числа на ту же вещь здесь не заводится: меньшее погасило бы большее
    молча. Ровно поэтому watchdog и остаётся stdlib-only: он спрашивает, а не
    считает.

    В `reason` не попадает НИ ОДНОГО возраста и НИ ОДНОГО адреса: `reason` —
    ключ дедупа, возраст растёт каждый цикл, и секунды в нём дали бы алерт раз
    в 30 секунд.

    ⚠️ `instance` при ОТСУТСТВИИ ключа читается как «инстанс есть» — как и у
    `probe_attention`, и по той же причине: снимок собирается здесь же и ключ
    ставит всегда, а умолчание «нет» превратило бы любой недособранный снимок в
    вердикт о ростере вместо вердикта об инстансе.
    """
    snapshot = snapshot or {}
    host = snapshot.get("host")
    host = (host or "").strip() if isinstance(host, str) else host
    port = snapshot.get("port", PANEL_CLIENT_PORT)

    if not snapshot.get("instance", True):
        return {"ok": False, "reason": "no_instance",
                "detail": "инстанса панели для этого клиента НЕТ — отправлять "
                          "из панели некому и спросить некого, уехало ли "
                          "нажатое, неизвестно"}
    if not host:
        return {"ok": False, "reason": "no_bind_address",
                "detail": (snapshot.get("problem")
                           or "адрес инстанса не вычислился") +
                          " — мерить нечем, уехало ли нажатое, неизвестно"}

    where = "%s:%s%s" % (host, port, OUTGOING_PATH)
    status = snapshot.get("status")
    if status is None:
        return {"ok": False, "reason": "no_response",
                "detail": "%s: нет ответа (refused/timeout) — инстанс молчит, "
                          "уехало ли нажатое, неизвестно" % where}
    if status != 200:
        # 404 и 500 названы вслух разными фразами: первое — порядок деплоя
        # панели, второе — НЕ перезапущенный раннер (таблицы очереди нет) либо
        # нечитаемая база. Владелец по этим двум идёт в разные места.
        if status == 404:
            hint = "ручки ЕЩЁ НЕТ — инстанс не перезапущен после деплоя"
        elif status == 500:
            hint = ("панель не смогла прочитать очередь — базы нет, она "
                    "нечитаема, ЛИБО раннер не перезапущен на код с очередью")
        else:
            hint = "инстанс жив, но ручка очереди не отвечает"
        return {"ok": False, "reason": "http:%s" % status,
                "detail": "%s: HTTP %s — %s, уехало ли нажатое, неизвестно"
                          % (where, status, hint)}

    payload = snapshot.get("payload")
    problem = _outgoing_payload_problem(payload)
    if problem:
        return {"ok": False, "reason": "bad_payload",
                "detail": "%s: HTTP 200, но тело не той формы (%s) — уехало ли "
                          "нажатое, неизвестно" % (where, problem)}

    pending = payload["pending"]
    refused = payload["refused"]
    # 🔴 ОБА ЧИСЛА НАЗЫВАЮТСЯ В КАЖДОМ ИСХОДЕ, включая зелёный и включая нули.
    # Одно число, погасившее второе, — известная грабля этого дома: владелец
    # читает «не уехало 2» и не узнаёт, что ещё три потеряны навсегда. Поэтому
    # очередь и отказы всегда идут в `detail` парой, а не по очереди.
    queue_words = ("очередь пуста" if pending == 0 else
                   "в очереди %d %s, самому старому %s"
                   % (pending,
                      _plural(pending, "сообщение", "сообщения", "сообщений"),
                      _fmt_age(payload.get("oldest_age_s"))))
    refused_words = ("отказов нет" if refused == 0 else
                     "ОТКАЗАНО %d (причина у каждого задания в панели)" % refused)

    # СТАРШИНСТВО: отказ важнее застревания. «Потеряно навсегда» сильнее, чем
    # «ещё едет»: застрявшее уедет, как только раннер поднимут, а отказанное не
    # уедет никогда и требует решения человека. `reason` — ключ дедупа, и он
    # обязан называть ГЛАВНУЮ беду, иначе владелец пойдёт поднимать раннер там,
    # где надо было прочитать причину и ответить лиду другим способом.
    if refused > 0:
        # Снимается это НЕ временем, а владельцем: `POST /api/outgoing/dismiss`
        # переводит строку в `dismissed`, она уходит из счётчика, и лампа
        # гаснет. Без такого пути исход был бы вечно красным, то есть фоном, —
        # ровно поэтому снятие и появилось вместе с ним.
        return {"ok": False, "reason": "outgoing_refused",
                "detail": "%s: %s — доставить НЕЛЬЗЯ; лампа гаснет, когда "
                          "отказ снят в панели (dismiss), временем не гаснет; "
                          "%s" % (where, refused_words, queue_words)}
    if payload["stuck"]:
        return {"ok": False, "reason": "outgoing_stuck",
                "detail": "%s: НЕ УЕХАЛО из панели: %s; %s"
                          % (where, queue_words, refused_words)}
    return {"ok": True, "detail": "%s: %s, %s" % (where, queue_words, refused_words)}


def probe_all(http_get, disk_usage, min_disk_gb: float = MIN_DISK_GB,
              chatter_snapshot: dict | None = None,
              worktree_snapshot: dict | None = None,
              secrets_snapshot: dict | None = None,
              panel_client_snapshot: dict | None = None,
              restore_drill_snapshot: dict | None = None,
              token_at_rest_snapshot: dict | None = None,
              attention_snapshot: dict | None = None,
              outgoing_snapshot: dict | None = None,
              reachability_snapshot: dict | None = None) -> dict:
    """Compose the cycle's probes. ``http_get(path) -> int|None`` (HTTP status,
    or None on connection refused/timeout); ``disk_usage(path) -> (total, used,
    free)`` (shutil.disk_usage-shaped)."""
    probes = {}

    status = http_get("/health")
    backend_ok = status == 200
    probes["backend"] = {
        "ok": backend_ok,
        "detail": "HTTP %s" % status if status is not None else "no response (refused/timeout)",
        # «Не отвечает» и «отвечает 500» — разные аварии: первая про процесс,
        # вторая про код внутри живого процесса, и чинятся они по-разному.
        "reason": "no_response" if status is None else "http:%s" % status,
    }
    if backend_ok:
        for key, path in _OPS_ENDPOINTS.items():
            s = http_get(path)
            probes[key] = {"ok": s == 200, "detail": "HTTP %s" % s,
                           "reason": "no_response" if s is None else "http:%s" % s}

    try:
        _total, _used, free = disk_usage(DISK_PATH)
        free_gb = free / (1024 ** 3)
        probes["disk"] = {
            "ok": free_gb >= min_disk_gb,
            "detail": "%.1fGB free (min %.1fGB)" % (free_gb, min_disk_gb),
            # Гигабайтам в ключе дедупа не место: они дрейфуют каждый цикл.
            "reason": "low_space",
        }
    except Exception as exc:
        probes["disk"] = {"ok": False, "detail": "disk check failed: %s" % exc,
                          "reason": "unreadable"}

    # Снимок отсутствует → состав проб ПРЕЖНИЙ. Обратная совместимость тут не
    # вежливость: watchdog на старом окружении не имеет права слать DOWN о том,
    # чего он не мерил.
    if chatter_snapshot:
        cs = chatter_snapshot
        roster_snap = cs.get("roster")
        if roster_snap is None:
            # Снимок БЕЗ ростера — старое окружение. Состав проб прежний:
            # watchdog не имеет права слать DOWN о том, чего не мерил.
            probes["chatter_runner"] = probe_chatter_runner(
                cs.get("processes"), beat_age=cs.get("runner_beat_age"),
                root=cs.get("root", ROOT), beat_source=cs.get("runner_beat_source"))
        else:
            probes["chatter_roster"] = probe_roster(roster_snap)
            beats = cs.get("beats") or {}
            for entry in (roster_snap.get("clients") or []):
                # Выключенный клиент — законное состояние: пробы НЕТ вовсе, а
                # не красная и не зелёная (§5.1).
                if not entry.get("enabled"):
                    continue
                slug = entry.get("slug")
                probes[CLIENT_PROBE_PREFIX + str(slug)] = probe_client_runner(
                    cs.get("processes"), slug=slug, beat_age=beats.get(slug),
                    root=cs.get("root", ROOT))
            probes["chatter_beat_legacy"] = probe_beat_legacy(cs.get("legacy_beat_age"))
        probes["chatter_guardian"] = probe_chatter_guardian(
            cs.get("processes"), lock_pid=cs.get("guardian_lock_pid"),
            beat_age=cs.get("guardian_beat_age"))
    if worktree_snapshot:
        probes["worktree"] = probe_worktree(worktree_snapshot)
    if secrets_snapshot:
        probes["secrets_bundle"] = probe_secrets_bundle(secrets_snapshot)
    if panel_client_snapshot:
        probes["panel_client"] = probe_panel_client(panel_client_snapshot)
    if restore_drill_snapshot:
        probes["restore_drill"] = probe_restore_drill(restore_drill_snapshot)
    if token_at_rest_snapshot:
        probes["token_at_rest"] = probe_token_at_rest(token_at_rest_snapshot)
    # §5.1: связь наружу — ОТДЕЛЬНЫЙ КЛЮЧ НА КАЖДЫЙ ПРОВОД.
    #
    # 🔴 Здесь нет и не может быть агрегирующего ключа вроде `reach` или
    # `network`. Он бы означал ровно ту лампу, против которой написана вся
    # спека: «два провода из трёх целы» ушло бы владельцу как ОДИН вердикт, и
    # любой его цвет был бы враньём — зелёный скрыл бы немого бота, красный
    # отправил бы чинить работающее. Дебаунс, `alerted` и дедуп по причине тоже
    # живут внутри записи ключа, поэтому общий ключ означал бы вдобавок, что
    # авария одного провода глушит алерт о другом.
    #
    # Состав — ИЗ СНИМКА, не из `REACH_WIRES` здесь: провод без адреса в снимок
    # не попал, и второе чтение состава рядом стало бы вторым источником правды.
    if reachability_snapshot:
        for name, entry in (reachability_snapshot.get("terms") or {}).items():
            probes[REACH_PROBE_PREFIX + str(name)] = probe_reachability(entry)
    # Снимка нет → проб этого семейства в цикле НЕТ ВОВСЕ, а не ноль штук и не
    # красные: watchdog не имеет права слать DOWN о том, чего он не мерил.
    # Состав берётся ИЗ СНИМКА, а не из ростера здесь: ростер в снимок уже
    # уехал (см. `_attention_snapshot`), и второе его чтение рядом стало бы
    # вторым источником правды о составе фермы.
    if attention_snapshot:
        for slug, entry in (attention_snapshot.get("clients") or {}).items():
            probes[ATTENTION_PROBE_PREFIX + str(slug)] = probe_attention(entry)
    # Третье семейство, собранное ТЕМ ЖЕ снимком-строителем и по тому же
    # правилу: состав из РОСТЕРА, снимка нет → проб нет вовсе.
    if outgoing_snapshot:
        for slug, entry in (outgoing_snapshot.get("clients") or {}).items():
            probes[OUTGOING_PROBE_PREFIX + str(slug)] = probe_outgoing(entry)
    return probes


