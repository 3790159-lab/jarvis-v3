def _surviving_files(path: Path) -> list[Path]:
    """Файлы, ПЕРЕЖИВШИЕ снос. Ответ на «что осталось», а не «упало ли rmtree».

    Гарантию даёт состояние диска, а не то, что вызов не бросил исключение."""
    if not path.exists():
        return []
    try:
        return sorted(p for p in path.rglob("*") if p.is_file())
    except OSError:
        return [path]


def _rmtree_forcing(path: Path) -> None:
    """`rmtree`, который не бросает работу на первом же неподатливом файле.

    Голый `shutil.rmtree` бросает на первой ошибке и оставляет всё, до чего
    не дошёл: замер 22.08 — один запертый `plain/<псевдоним>/db` оставил на
    диске ещё и `manifest.json`, и `requisites.yaml`, которые снеслись бы
    свободно. Обработчик снимает read-only, пробует ещё раз и в любом случае
    даёт обходу идти дальше, поэтому открытого текста на диске остаётся
    МИНИМУМ возможного, а не всё подряд.

    Ошибки здесь не глотаются, а откладываются: остаток называет поимённо
    `remove_sandbox`, посмотрев на то, что реально осталось на диске."""
    def _on_error(func, target, exc) -> None:  # noqa: ANN001
        try:
            os.chmod(target, stat.S_IWRITE)
            func(target)
        except OSError:
            pass  # остаток назовёт _surviving_files — тишины не будет

    try:
        shutil.rmtree(path, onexc=_on_error)
    except OSError:
        pass


def _to_stderr(message: str) -> None:
    print(message, file=sys.stderr)


def remove_sandbox(path: Path,
                   report: Callable[[str], None] | None = None) -> list[Path]:
    """Снести песочницу ЦЕЛИКОМ. Возвращает то, что снести НЕ удалось.

    Провал сноса — ГРОМКИЙ и ПОИМЁННЫЙ, а не `ignore_errors=True`:
    оставшийся каталог — это расшифрованная переписка и реквизиты на диске,
    о которых никто не знает. Молчать про это нельзя (DEV-18). Но и
    подменять этим настоящую причину провала вызывающего тоже нельзя —
    поэтому текст и возвращённый список, а не исключение: код возврата обязан
    говорить про БЭКАП, а не про уборку.

    `report` — куда сказать. Умолчание — stderr (так это читает человек,
    запустивший дрил руками); ежедневная заливка передаёт сюда `logger.error`,
    потому что её никто не смотрит живьём и всё, что она сказала, обязано
    попасть в журнал.

    Второй заход после `gc.collect()` — не суеверие, а следствие корня
    (DEV-48): на Windows файл держит открытый ХЭНДЛ, и хэндл, застрявший в
    недостижимом цикле ссылок, освобождает только сборщик мусора. Если второй
    заход помог — значит соединение всё-таки утекло, и это НАЗЫВАЕТСЯ вслух:
    снос такую утечку маскирует, а не лечит."""
    say = _to_stderr if report is None else report
    try:
        _rmtree_forcing(path)
        left = _surviving_files(path)
        if left:
            gc.collect()
            _rmtree_forcing(path)
            after = _surviving_files(path)
            if not after:
                say(f"\N{WARNING SIGN} песочница {path} снеслась только СО ВТОРОГО "
                    f"захода, после сборки мусора: {len(left)} файл(ов) держал "
                    "открытый хэндл. Снос это замаскировал; чинить надо "
                    "утечку соединения, а не уборку.")
                return []
            left = after
        if left:
            names = "\n".join(f"   - {item}" for item in left[:20])
            tail = (f"\n   ... и ещё {len(left) - 20}" if len(left) > 20 else "")
            say(f"\N{POLICE CARS REVOLVING LIGHT} ПЕСОЧНИЦА НЕ СНЕСЕНА: {path}\n"
                f"   осталось файлов: {len(left)}\n{names}{tail}\n"
                "   В них лежит РАСШИФРОВАННАЯ переписка и реквизиты. "
                "Удалите каталог руками.")
        return left
    except Exception as exc:  # noqa: BLE001
        # Уборка зовётся из `finally`. Исключение отсюда подменило бы собой
        # настоящую причину провала вызывающего — и человек чинил бы уборку
        # вместо бэкапа. Поэтому громко и без повторного возбуждения.
        say(f"\N{POLICE CARS REVOLVING LIGHT} СНОС ПЕСОЧНИЦЫ САМ УПАЛ "
            f"({type(exc).__name__}): {path}: {exc}\n"
            "   Считайте, что открытый текст остался на диске: проверьте "
            "каталог руками.")
        return [path]
