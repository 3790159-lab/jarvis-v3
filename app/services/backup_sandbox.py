# -*- coding: utf-8 -*-
"""Общее сито временных каталогов бэкапа (DEV-46, амендменты Г и Д).

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, а не по копии в каждом месте. Открытый текст
клиента — снимок базы и реквизиты — за время арки ложится во временный
каталог ТРИЖДЫ: дрил восстановления его туда распаковывает, ежедневная
заливка кладёт туда снимок живой базы, генератор ключей пишет рядом
приватный ключ. Правило у всех трёх одно: **этого не должно оказаться ни в
дереве репозитория, ни в `.secrets/`**.

Пока правило жило в двух местах, оно расходилось молча и расходилось в
сторону СЛАБЕЕ — потому что слабое не краснеет. Замер 22.08: дрил
отказывался распаковывать набор в дерево репозитория, а заливка в то же
дерево писала открытую базу без единого вопроса, потому что её временный
корень вообще ничем не проверялся. Два правила на одну вещь; сильное было
видно, слабое молчало.

Отсюда расположение: `app/services/`, а не `scripts/`. `app/` не имеет права
импортировать из `scripts/` — значит общим местом может быть только `app/`, и
`scripts/backup_keygen.py` с `scripts/restore_drill.py` берут определение
отсюда. Функция `repo_roots` при этом ОДНА, а не две одинаковые.

ТРИ СВОЙСТВА, КОТОРЫЕ ЗДЕСЬ НЕ УКРАШЕНИЕ:

1. **Корень берётся из окружения В МОМЕНТ ВЫЗОВА** (`default_sandbox_root`).
   `tempfile.gettempdir()` кэширует результат в `tempfile.tempdir` при первом
   вызове в процессе: кто угодно, тронувший tempfile раньше нас, замораживает
   корень навсегда — и `TMPDIR`/`TEMP`/`TMP` перестают действовать вовсе.
   Кэш не сдвигает проверку, он её ГАСИТ.
2. **Проверка идёт по РАЗОБРАННОМУ пути** (`resolve()`), а не по строке:
   `C:\\jarvis\\..\\jarvis\\.secrets` — это внутри дерева, и строковое
   сравнение этого не видит.
3. **Снос даёт гарантию РЕЗУЛЬТАТОМ, а не фактом вызова** (`remove_sandbox`).
   `ignore_errors=True` здесь запрещён (DEV-18): расшифрованная переписка,
   оставшаяся на диске из-за незакрытого хэндла SQLite, обязана быть названа
   вслух и поимённо, а не исчезнуть в проглоченной ошибке.
"""
from __future__ import annotations

import gc
import os
import shutil
import stat
import sys
import tempfile
from pathlib import Path
from typing import Callable, Mapping

__all__ = [
    "SandboxRefused",
    "TMP_ENV_VARS",
    "repo_roots",
    "is_inside",
    "default_sandbox_root",
    "forbidden_sandbox_reason",
    "make_sandbox",
    "remove_sandbox",
]

#: Корень дерева: ``<корень>/app/services/backup_sandbox.py``.
_ROOT = Path(__file__).resolve().parents[2]

_SECRETS_DIR = ".secrets"

#: Порядок ровно как у ``tempfile._candidate_tempdir_list``. Список
#: ЛИТЕРАЛЬНЫЙ, а не выведенный из tempfile: выведенный согласен с ним по
#: определению и промолчит ровно там, где разойдётся с ожиданием человека
#: ([[jarvis-literal-lists-not-introspection]]).
TMP_ENV_VARS = ("TMPDIR", "TEMP", "TMP")


class SandboxRefused(Exception):
    """Временный каталог создать ОТКАЗАЛИСЬ: писать открытый текст туда нельзя.

    Общий тип для общего сита. Вызывающие переводят его в свой словарь
    отказа — дрил в ``DrillNotRun`` (rc 2, вердикт не пишется), заливка в
    ``ClientBackupRefused`` (наружу не ушло ни байта), — потому что рассказать
    о случившемся они обязаны каждый по-своему, а РЕШЕНИЕ принимается здесь и
    ровно одно.
    """


# --------------------------------------------------------------------------
# Запретная зона
# --------------------------------------------------------------------------

def repo_roots() -> list[Path]:
    """Корни, под которыми открытому тексту и приватному ключу лежать нельзя.

    Первый — дерево, в котором лежит этот модуль. Второй появляется, когда
    это дерево — worktree: файл ``.git`` тогда указывает на
    ``<главное дерево>/.git/worktrees/<имя>``, и писать в ГЛАВНОЕ дерево из
    worktree — та же ошибка, просто этажом выше. Разбирается только точная
    форма маркера; всё прочее оставляет один корень, и это честнее, чем
    гадать.

    Определение ОДНО на всю арку: и генератор ключей, и дрил, и ежедневная
    заливка спрашивают эту функцию, а не пишут по своей копии рядом."""
    roots = [_ROOT]
    marker = _ROOT / ".git"
    if marker.is_file():
        text = marker.read_text(encoding="utf-8", errors="replace").strip()
        if text.startswith("gitdir:"):
            gitdir = Path(text.split(":", 1)[1].strip())
            if not gitdir.is_absolute():
                gitdir = _ROOT / gitdir
            parts = gitdir.resolve().parts
            if len(parts) >= 3 and parts[-2] == "worktrees" and parts[-3] == ".git":
                main_root = Path(*parts[:-3])
                if main_root not in roots:
                    roots.append(main_root)
    return roots


def is_inside(path: Path, root: Path) -> bool:
    """`path` лежит под `root` (или равен ему) — по разобранным путям."""
    try:
        path.relative_to(root)
    except ValueError:
        return False
    return True


#: Прежнее имя: ``scripts/backup_keygen.py`` звал его так и продолжает звать.
_is_inside = is_inside


def forbidden_sandbox_reason(path: Path | str) -> str | None:
    """Почему в этот каталог нельзя класть расшифрованные данные (или None).

    Проверка по РАЗОБРАННОМУ пути: `resolve()` схлопывает `..`, и
    `C:\\jarvis\\..\\jarvis\\state\\tmp` опознаётся как дерево репозитория,
    хотя строкой на него не похоже. Запретны:

    * любой каталог `.secrets` на пути — там живут боевые базы клиенток под
      живыми раннерами, и класть рядом расшифрованный снимок нельзя даже
      «на минуту»;
    * дерево репозитория (и главное дерево, если мы в worktree) — гейты,
      гардианы и автодеплой ходят по нему постоянно, а расшифрованная
      переписка не должна пережить прогон ни секунды.
    """
    resolved = Path(path).expanduser().resolve()
    for part in resolved.parts:
        if part.lower() == _SECRETS_DIR:
            return (f"каталог назначения {resolved} лежит внутри {_SECRETS_DIR}: "
                    "там боевые базы клиенток под живыми раннерами. "
                    "Расшифрованный снимок рядом с оригиналом — это лишняя "
                    "копия чужой переписки в самом опасном месте дерева")
    for root in repo_roots():
        if is_inside(resolved, root):
            return (f"каталог назначения {resolved} лежит внутри дерева "
                    f"репозитория {root}: по дереву ходят гейты, гардианы и "
                    "автодеплой, а открытый текст переписки и реквизитов не "
                    "должен пережить прогон ни секунды. Укажите каталог вне "
                    "дерева (переменные TEMP/TMP)")
    return None


# --------------------------------------------------------------------------
# Корень и создание
# --------------------------------------------------------------------------

def default_sandbox_root(env: Mapping[str, str] | None = None) -> Path:
    """Корень песочницы, когда его не назвали явно, — ИЗ ОКРУЖЕНИЯ, В МОМЕНТ ВЫЗОВА.

    Не `tempfile.gettempdir()`, и это не придирка. `gettempdir` кэширует
    результат в `tempfile.tempdir` при ПЕРВОМ вызове в процессе: кто угодно,
    тронувший tempfile раньше нас, замораживает корень навсегда, и
    `TMPDIR`/`TEMP`/`TMP` перестают действовать вовсе. Проверка запретной
    зоны при этом не сдвигается — она ГАСНЕТ, потому что применяется к
    замороженному значению, а не к тому, что назвал человек.

    Два довода, и ни один не про удобство теста:

    1. **Сообщение об отказе обязано быть правдой.** `forbidden_sandbox_reason`
       дословно советует «Укажите каталог вне дерева (переменные TEMP/TMP)».
       Совет, которому код не следует, — это враньё в сообщении об ошибке.
    2. **Без этого шва запретная зона недостижима ниоткуда, кроме питонного
       аргумента**, то есть в бою она мёртвая ветка, зелёная по построению
       ([[jarvis-guard-caught-dead-branch]]).

    Переменная окружения — такой же непроверенный ввод, как аргумент, и
    проходит ровно то же сито."""
    env = os.environ if env is None else env
    for name in TMP_ENV_VARS:
        value = env.get(name)
        if value and value.strip():
            return Path(value)
    # Ни одной переменной нет — тогда и замораживать нечего: пусть tempfile
    # называет свой умолчательный каталог сам.
    return Path(tempfile.gettempdir())


def make_sandbox(sandbox_root: str | Path | None = None, *,
                 prefix: str, env: Mapping[str, str] | None = None) -> Path:
    """Свой временный каталог — и ничего кроме него.

    Корень: явный `sandbox_root`, иначе `TMPDIR`/`TEMP`/`TMP` в момент вызова.

    Корень проверяется ДО `mkdtemp`: иначе отказ уже создал бы каталог там,
    куда мы отказываемся писать. Созданный каталог проверяется ЕЩЁ РАЗ —
    симлинк в корне временных файлов может увести куда угодно, а `resolve()`
    его разворачивает.

    Отказ — `SandboxRefused`; вызывающий переводит его в свой словарь."""
    root = (Path(sandbox_root) if sandbox_root is not None
            else default_sandbox_root(env))
    reason = forbidden_sandbox_reason(root)
    if reason is not None:
        raise SandboxRefused(reason)
    try:
        root.mkdir(parents=True, exist_ok=True)
        path = Path(tempfile.mkdtemp(prefix=prefix, dir=str(root)))
    except OSError as exc:
        raise SandboxRefused(
            f"песочница не создаётся в {root} ({type(exc).__name__}): {exc}") from exc

    reason = forbidden_sandbox_reason(path)
    if reason is not None:
        remove_sandbox(path)
        raise SandboxRefused(reason)
    return path


