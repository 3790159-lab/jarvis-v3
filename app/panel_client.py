# -*- coding: utf-8 -*-
"""Клиентская панель ОТДЕЛЬНЫМ инстансом: только дашборд, ничего больше.

Спека: docs/superpowers/specs/2026-08-18-yarina-client-panel-instance.md.
Ключ от этого приложения уходит СТОРОННЕМУ человеку, поэтому оно собрано не
«как `app.main`, только с другим TAMAPI_DB». Замер назвал две причины, по
которым так нельзя:

1. `app/main.py:308-309` вешает на старте `_watchdog_loop()`, зовущий
   `restart_bot_if_dead()` каждые 60 с. Второй инстанс — второй хозяин у
   живого бота. Этот класс уже стоил прода 18.08 (DEV-38) и 13 ч 42 мин
   простоя Ольги 16.08.
2. `app/main.py:236-244` монтирует клиентский дашборд и `/panel/jarvis` одним
   блоком, а `require_owner` у них на ОДНОМ ключе. Ключ клиента открыл бы
   PID'ы, ветки и сроки ключей фермы.

Поэтому здесь ровно два роутера и ни одного обработчика старта. Закрыто ПО
СОСТАВУ: то, чего в приложении нет, нельзя открыть опечаткой в env.
"""
from __future__ import annotations

import time

from fastapi import Depends, FastAPI, Form, HTTPException

# Переменные, которые ОБЯЗАН задать запускающий. Дефолты у них есть
# (`tamapi_dashboard._db_path` -> `.secrets/demo.db`, `_slug` -> `volska`), и в
# этом вся опасность: инстанс, поднятый без них, молча показал бы клиенту
# переписку ОЛЬГИ. Здесь дефолт = отказ стартовать.
REQUIRED_INSTANCE_VARS = ("TAMAPI_DB", "TAMAPI_SLUG")

# 🔴 ЛОВУШКА `limit`: `needs_attention` сортирует `card_ts` УБЫВАЮЩЕ и режет
# `out[:limit]`, а умолчание там 50. То есть на 51-й открытой карточке САМАЯ
# СТАРАЯ выпала бы из выборки, и ручка молча занизила бы возраст — сторож,
# который врёт тем сильнее, чем хуже дела. Лимит поэтому передаётся ЯВНО и
# заведомо больше любого живого числа (прецедент: `active_dialogs` зовёт
# `dialog_feed(..., limit=100_000)`).
ATTENTION_SCAN_LIMIT = 100_000

# Ключи тела ответа — ЛИТЕРАЛЬНЫМ кортежем и ровно четыре. Список нужен не для
# сборки (её видно ниже построчно), а чтобы у формы ответа было ОДНО имя,
# которое можно назвать в сторожах и в спеке. Цена ответа названа у самой
# ручки: ни слага, ни contact_id, ни имён, ни текстов, ни пути к базе.
ATTENTION_KEYS = ("open", "stale_open", "oldest_age_s", "oldest_wait_s")


# Ключи тела `/ops/outgoing` — ЛИТЕРАЛЬНЫМ кортежем и ровно четыре, по той же
# причине, что и `ATTENTION_KEYS`: у формы ответа должно быть ОДНО имя, которое
# называют и спека, и сторож, и проба. Появление снятия отказов состав НЕ
# меняет: снятое просто уходит из `refused`.
OUTGOING_KEYS = ("pending", "oldest_age_s", "stuck", "refused")

# 🔢 ЕДИНСТВЕННЫЙ ПОРОГ «ЗАСТРЯЛО», и живёт он ЗДЕСЬ, у инстанса. У пробы в
# `ops_watchdog` своего числа нет и не будет: два числа на одну вещь разъедутся,
# и меньшее погасит большее молча (ровно так устроен `stale_open` у эскалаций).
#
# ОТКУДА 10 МИНУТ. Раннер опрашивает очередь раз в 5 секунд
# (`OUTGOING_POLL_INTERVAL_SECONDS`), пишет отметку живости раз в 30 секунд, а
# гардиан считает его мёртвым и поднимает через 180 секунд. То есть штатный
# худший случай «раннер лежал и его подняли» укладывается в ~4 минуты вместе с
# запуском. Задание, не ушедшее за 10 минут, означает не «медленно», а «его не
# заберёт никто»: раннер мёртв дольше гардиана, либо смотрит в другую базу,
# либо очередь ему не видна вовсе.
OUTGOING_STUCK_AFTER = 600.0


def outgoing_summary(raw: dict, *, now: float) -> dict:
    """Свернуть факты об исходящей очереди в РОВНО четыре числа.

    Чистая функция и по той же причине, что `attention_summary`: проверять надо
    СВЁРТКУ (когда лампа краснеет), а не то, что HTTP как-то ответил.

    `stuck` — это ЕДИНСТВЕННОЕ место, где применяется порог. Он тут один, и он
    не «дублирует» интервал поллинга: интервал отвечает на вопрос «как часто
    забирать», порог — на вопрос «через сколько считать, что не заберут».

    `refused` не входит в `stuck` НАМЕРЕННО: отказ — это законченная история с
    названной причиной, которую владелец читает словами в самой строке
    (`last_error`); задание, застрявшее без причины, — незаконченная. Свалить
    их в один счётчик значило бы, что одна причина глушит другую. Числа два, и
    краснеют они по-разному (см. `probe_outgoing`).

    🔴 `refused` СЧИТАЕТ ТОЛЬКО НЕСНЯТЫЕ. Снятый владельцем отказ живёт как
    `dismissed` и сюда не приходит вовсе (`outgoing_raw` группирует по статусу)
    — в этом весь смысл снятия: отказ терминален, и без пути погасить его лампа
    горела бы вечно, то есть стала бы фоном. Улика при этом цела: строка
    остаётся в очереди со своим текстом и причиной.
    """
    pending = int(raw.get("pending") or 0)
    created = raw.get("oldest_created_ts")
    # Возраст берётся от САМОГО СТАРОГО pending. Пустая очередь даёт None, а не
    # 0.0: ноль читался бы как «только что положили», то есть как «всё свежо»
    # ровно тогда, когда в очереди нет ничего.
    age = None if created is None else float(now - float(created))
    return {
        "pending": pending,
        "oldest_age_s": age,
        "stuck": bool(age is not None and age > OUTGOING_STUCK_AFTER),
        "refused": int(raw.get("refused") or 0),
    }


def attention_summary(rows: list[dict], *, now: float) -> dict:
    """Свернуть строки `needs_attention` в РОВНО четыре числа.

    Чистая функция: решение отделено от ручки по той же причине, что и
    `instance_env_problems` — проверять надо СВЁРТКУ, а не то, что HTTP как-то
    ответил. Второй реализации подсчёта здесь нет: сколько карточек открыто и
    какая протухла, решает `needs_attention` (и её порог `STALE_AFTER`), иначе
    панель и проба начнут спорить о числе открытых карточек.

    САМАЯ СТАРАЯ берётся по МИНИМУМУ `card_ts`, причём карточка без `card_ts`
    считается САМОЙ старой (`or 0.0`), а не самой свежей. Это не мелочь:
    карточка, которой нет в `console_cards`, — это «возраст недоказуем», и
    выдать её за свежую значило бы спрятать ровно тот случай, ради которого
    ручка заводится. Возраст у неё при этом честный — `None`, а не выдуманный.
    """
    oldest = min(rows, key=lambda r: r.get("card_ts") or 0.0) if rows else None
    card_ts = oldest.get("card_ts") if oldest else None
    last_ts = oldest.get("last_ts") if oldest else None
    return {
        "open": len(rows),
        "stale_open": sum(1 for r in rows if r.get("stale")),
        # `now - card_ts` — сколько карточка ВИСИТ (бот поднял руку).
        "oldest_age_s": None if card_ts is None else float(now - card_ts),
        # `now - last_ts` ТОЙ ЖЕ карточки — сколько ЖДЁТ человек. Возрастов два,
        # и чинятся они по-разному: старая карточка при свежем `last_ts` — лид
        # ещё пишет; оба старые — лид уже ушёл.
        "oldest_wait_s": None if last_ts is None else float(now - last_ts),
    }


def instance_env_problems(env, *, owner_key: str = "") -> list[str]:
    """Что не так с окружением инстанса. Пустой список = можно поднимать.

    Чистая функция: решение отделено от запуска, потому что проверить надо
    именно РЕШЕНИЕ, а не то, что процесс как-то поднялся.
    """
    problems: list[str] = []
    key = (env.get("JARVIS_PANELS_KEY") or "").strip()
    if not key:
        problems.append(
            "JARVIS_PANELS_KEY не задан: панель закрыта по умолчанию и без "
            "ключа не поднимается")
    elif owner_key and key == owner_key:
        # Главная ловушка: `.env` грузится с override=False, поэтому НЕзаданный
        # ключ процесса молча заменяется ключом ВЛАДЕЛЬЦА из `.env`. А тот же
        # ключ открывает панель Джарвиса на 8010. То есть забытая переменная
        # выдала бы стороннему человеку доступ к ферме — без единой ошибки.
        problems.append(
            "JARVIS_PANELS_KEY инстанса СОВПАДАЕТ с ключом владельца из .env: "
            "этот ключ открывает и панель Джарвиса на основном бэкенде")
    for name in REQUIRED_INSTANCE_VARS:
        if not (env.get(name) or "").strip():
            problems.append(
                "%s не задан: без него панель показала бы клиента по умолчанию "
                "(volska/.secrets/demo.db), то есть ЧУЖУЮ переписку" % name)
    return problems


def build_app() -> FastAPI:
    """Собрать приложение. Импорты внутри — чтобы модуль можно было
    импортировать (и проверять) без поднятого окружения."""
    from app.routers import tamapi_dashboard
    from app.routers.panels_auth import (install_panel_auth_redirect,
                                         panels_enabled, require_owner)
    from app.routers.panels_auth import router as login_router
    from app.routers.tamapi_dashboard import router as tamapi_router
    from app.services import tamapi_metrics

    if not panels_enabled():
        raise RuntimeError("JARVIS_PANELS_KEY не задан — панель fail-closed")

    # Схема API наружу не отдаётся: клиенту она не нужна, а перечень ручек —
    # это карта для того, кто ключ подберёт.
    api = FastAPI(title="TAMAPI client panel",
                  docs_url=None, redoc_url=None, openapi_url=None)
    api.include_router(login_router)
    api.include_router(tamapi_router)
    # Отказ обязан иметь выход: браузеру — форма входа, машине — прежний 401.
    # Ставится там же, где монтируются роутеры, как и в app/main.py.
    install_panel_auth_redirect(api)

    # ── проба живости для супервизора ───────────────────────────────────────
    # Спека 2026-08-20-client-panel-supervisor §3, вариант B (ОК владельца).
    #
    # ПОЧЕМУ ОТДЕЛЬНАЯ РУЧКА, А НЕ «МЕРИТЬ ПО 401». Машинный GET
    # `/panel/tamapi` без ключа уже даёт 401, и проба по нему не стоила бы ни
    # строки кода — но она села бы на ПОЛИТИКУ АВТОРИЗАЦИИ. Поменяем редирект —
    # и сторож покраснеет на здоровой панели или, что хуже, позеленеет на
    # больной. Контракт живости обязан быть явным, а не выведенным из чужого
    # поведения.
    #
    # ПОЧЕМУ БЕЗ АВТОРИЗАЦИИ И ПОЧЕМУ ЭТО НЕ ДЫРА. Обходить здесь нечего:
    # `require_owner` — это ЯВНАЯ зависимость на роутерах панели, а не
    # middleware, а `install_panel_auth_redirect` вешает лишь обработчик
    # исключения `PanelLoginRequired`. Ручка, которая этого исключения не
    # бросает, до обработчика не доходит вовсе — то есть авторизацию не
    # «обходят», её тут просто нет, и добавлять её нельзя: у watchdog'а ключа
    # клиента нет и быть не должно.
    #
    # ЦЕНА ОТВЕТА. В теле — РОВНО факт «процесс жив»: ни слага, ни имени
    # клиента, ни пути к базе. Порт биндится на адрес тайнета, карта ручек
    # закрыта (`openapi_url=None`), так что эта ручка не рассказывает даже
    # того, ЧЕЙ инстанс отвечает.
    #
    # Маршрут вешается на приложение, а НЕ приезжает третьим роутером:
    # состав роутеров — предмет отдельного сторожа, и живость не имеет права
    # его менять.
    @api.get("/health")
    async def health() -> dict:
        return {"ok": True}

    # ── проба «карточки эскалации не читают» ────────────────────────────────
    # Спека 2026-08-24-escalation-seen-probe.md §3, форма 1 (ОК владельца).
    #
    # ЗАЧЕМ. Величина «сколько карточка эскалации висит незакрытой» сегодня не
    # измеряется НИГДЕ: бот поднял руку, человек не пришёл — и об этом узнают
    # только открыв панель. Замер 24.08 нашёл четыре такие карточки возрастом
    # до 26.6 суток. Плитка в панели молчит, пока панель не открыли, а TTL у
    # флага уничтожил бы единственный след, — поэтому спрашивает ПРОБА, и
    # спрашивает она инстанс.
    #
    # ПОЧЕМУ БЕЗ КЛЮЧА И ПОЧЕМУ ЭТО НЕ ДЫРА — дословно то же, что у `/health`
    # выше: `require_owner` живёт ЯВНОЙ зависимостью на роутерах панели, а не
    # middleware; ручка, не бросающая `PanelLoginRequired`, до обработчика не
    # доходит. Авторизацию тут не «обходят», её нет — и добавлять нельзя: у
    # watchdog'а ключа клиента нет и быть не должно.
    #
    # 🔴 ЦЕНА ОТВЕТА. РОВНО четыре числа (`ATTENTION_KEYS`) и НИЧЕГО больше:
    # ни слага, ни `contact_id`, ни имён, ни текстов, ни пути к базе. Ручка не
    # рассказывает даже того, ЧЕЙ инстанс отвечает. Цена, которую мы всё-таки
    # платим, названа в спеке вслух: любой, кто дотянулся до порта в тайнете,
    # узнаёт, что у КОГО-ТО тут висят незакрытые эскалации. Это принято как
    # решение владельца, а не проглядено.
    #
    # ПОРОГ НЕ ЗАВОДИТСЯ. `stale_open` считает `needs_attention` по своему
    # `STALE_AFTER` (48 ч) — тому же, которым панель уже красит блок «Требует
    # вас». Своего числа нет ни у ручки, ни у пробы: разъехаться им нечем
    # только пока источник один. Ровно поэтому решение «протухло или нет»
    # принимает ИНСТАНС, а не watchdog (он stdlib-only и `app.*` не знает).
    #
    # ОШИБКУ НЕ ГЛОТАЕМ (DEV-18): нечитаемая БД обязана стать HTTP 500, и
    # проба скажет `http:500`. Пустой ответ «всё тихо» на сломанном чтении —
    # это зелёное по построению, худший из возможных отказов.
    #
    # Маршрут вешается на приложение, а НЕ приезжает третьим роутером — по той
    # же причине, что и `/health`: состав роутеров предмет отдельного сторожа.
    @api.get("/ops/attention")
    async def ops_attention() -> dict:
        # `now` берётся ОДИН раз и уезжает и в `needs_attention` (там по нему
        # ставится `stale`), и в вычитание возрастов. Два разных показания
        # часов дали бы `stale_open` по одному моменту, а возраст по другому.
        now = time.time()
        # Путь к базе — ТА ЖЕ функция, которой его берёт остальной инстанс.
        # Свой `os.getenv("TAMAPI_DB", ...)` рядом стал бы вторым источником
        # правды с ДРУГИМ дефолтом, то есть однажды показал бы чужую базу.
        rows = tamapi_metrics.needs_attention(
            tamapi_dashboard._db_path(), now=now, limit=ATTENTION_SCAN_LIMIT)
        return attention_summary(rows, now=now)

    # ── отправка из панели: панель КЛАДЁТ, отправляет РАННЕР ────────────────
    # Спека 2026-08-25 §2. Панель отправить не может физически: транспорт
    # привязан к конкретному чату и живёт внутри раннера, а сессия Telethon —
    # файл, который держит живой процесс (второй клиент на том же файле это в
    # лучшем случае отказ, в худшем разлогин аккаунта клиентки). Поэтому ручка
    # ставит ЗАДАНИЕ в общую базу, и на этом её работа кончается.
    #
    # ЗА `require_owner`, как и остальные ручки панели: это МУТИРУЮЩАЯ ручка,
    # она пишет лиду от имени клиента. Немыми (`/health`, `/ops/*`) остаются
    # только те, что ничего не меняют и ничего не рассказывают.
    #
    # `event_token` ОБЯЗАТЕЛЕН (`Form(...)`, а не `Form(None)`): это личность
    # НАЖАТИЯ, и без неё двойное нажатие кнопки породило бы второе сообщение
    # лиду. Отсутствие токена — отказ на входе, а не «попробуем разобраться».
    #
    # Вид кнопки — вне границы (спека §11): здесь ручка, оформления нет.
    @api.post("/api/outgoing", dependencies=[Depends(require_owner)])
    async def post_outgoing(contact_id: str = Form(...), text: str = Form(...),
                            event_token: str = Form(...)) -> dict:
        from chatter.storage.db import Store
        # `with`, а не голый `Store(...)`: соединение закрывается ДЕТЕРМИНИРОВАННО,
        # на выходе из блока. Панель — процесс, живущий неделями, и нажатие
        # кнопки не имеет права оставлять за собой открытый хэндл файла БД:
        # на Windows такой хэндл держит файл занятым (бэкап, ротация и любая
        # работа с базой начинают падать «файл занят другим процессом»), а на
        # длинной дистанции это просто утечка. У `Store` для этого есть
        # `__enter__/__exit__` — идиома дома, а не выдумка.
        with Store(tamapi_dashboard._db_path()) as store:
            try:
                row_id, created = store.enqueue_outgoing(
                    contact_id, text, token=event_token, now=time.time())
            except ValueError as exc:
                # Пустой текст/токен: отказ СЛОВАМИ и 400, а не 500 и не тихое
                # «ок». Владелец обязан узнать, что его нажатие не превратилось
                # в задание, — иначе он будет ждать доставки того, чего нет.
                raise HTTPException(400, str(exc)) from exc
        # `duplicate` не прячется: повтор по тому же токену — это НОРМА (кнопку
        # нажали дважды), но панель обязана показать, что второго сообщения не
        # будет, а не притвориться, что поставила второе задание.
        return {"queued": True, "id": row_id, "duplicate": not created}

    # ── снятие отказа: путь, без которого лампу нельзя было заводить ───────
    # Дополнение к контракту 25.08. Отказ ТЕРМИНАЛЕН: строка `refused` не
    # рассосётся сама, и лампа, зажжённая по ней, горела бы вечно. Вечно
    # красная лампа за неделю становится фоном — этот класс в доме уже чинили
    # дважды, и заводить его третий раз своими руками нельзя. Поэтому вместе с
    # красным исходом появляется путь снятия, и он ЗДЕСЬ.
    #
    # ЗА `require_owner`: снятие гасит красное, и право на это есть только у
    # владельца. Немыми остаются лишь ручки, которые ничего не меняют.
    #
    # `row_id`, а не `contact_id`: гасится КОНКРЕТНЫЙ отказ, а не «всё по этому
    # диалогу». Иначе одно нажатие похоронило бы вместе с увиденным отказом и
    # тот, который владелец ещё не читал.
    #
    # `dismissed=False` — ЧЕСТНЫЙ ответ «снимать было нечего» (строки нет либо
    # она не в отказе), а не тихое «ок». Панель обязана показать разницу: иначе
    # нажатие по строке, которую раннер прямо сейчас отправляет, читалось бы как
    # отмена отправки — а отменить `pending` этим путём НЕЛЬЗЯ (см.
    # `Store.dismiss_outgoing`).
    #
    # Кнопки нет: вид — вне границы (спека §11).
    @api.post("/api/outgoing/dismiss", dependencies=[Depends(require_owner)])
    async def dismiss_outgoing_handle(row_id: int = Form(...)) -> dict:
        from chatter.storage.db import Store
        now = time.time()
        # `with` — по той же причине, что и у ручки постановки задания выше:
        # открытый хэндл БД, оставленный нажатием кнопки, держит файл занятым.
        with Store(tamapi_dashboard._db_path()) as store:
            dismissed = store.dismiss_outgoing(row_id, now=now)
            if dismissed:
                # Снятие ГАСИТ КРАСНОЕ, поэтому оно обязано быть видно в
                # журнале: погашенная лампа без следа о том, кто и когда её
                # погасил, — это тот же тихий отказ, только с другой стороны.
                # Пишем ТОЛЬКО факт снятия: причина отказа уже лежит в самой
                # строке (`last_error`).
                store.add_event("outgoing_dismissed", detail="#%d" % row_id, ts=now)
        return {"dismissed": dismissed}

    # ── лампа «задание из панели не уехало» ─────────────────────────────────
    # Спека §3.3 + §10 п.7 (решение владельца 25.08: лампа берётся СРАЗУ).
    #
    # ПОЧЕМУ БЕЗ КЛЮЧА — дословно то же, что у `/health` и `/ops/attention`:
    # `require_owner` живёт ЯВНОЙ зависимостью на роутерах панели, а не
    # middleware; ручка, не бросающая `PanelLoginRequired`, до обработчика не
    # доходит. Авторизацию тут не «обходят», её нет — и добавлять нельзя: у
    # watchdog'а ключа клиента нет и быть не должно.
    #
    # 🔴 ЦЕНА ОТВЕТА. РОВНО четыре числа (`OUTGOING_KEYS`): сколько ждёт,
    # сколько ждёт САМОЕ старое, застряло ли, сколько отказано И НЕ СНЯТО. Ни
    # слага, ни `contact_id`, ни текстов, ни пути к базе — тексты заданий это
    # переписка с живыми людьми, и в немой ручке им места нет.
    #
    # Состав ключей ПРЕЖНИЙ и после появления снятия: `dismissed` наружу не
    # уезжает отдельным числом. Оно ответило бы на вопрос, которого никто не
    # задаёт («сколько отказов закрыто»), а лампе нужен ровно один — «сколько
    # ещё кричит».
    #
    # ПОРОГ ОДИН И ЖИВЁТ ЗДЕСЬ (`OUTGOING_STUCK_AFTER`), у пробы своего числа
    # нет — та же конструкция, что у `stale_open`.
    #
    # ОШИБКУ НЕ ГЛОТАЕМ (DEV-18): нечитаемая БД и ОТСУТСТВИЕ таблицы очереди
    # обязаны стать HTTP 500, и проба скажет `http:500`. Второе особенно важно:
    # нет таблицы = раннер не перезапущен на код с очередью = всё, что владелец
    # нажмёт, ляжет в базу и не уедет никому. Ответ «pending 0, всё тихо» на
    # этот вопрос был бы зелёным по построению.
    @api.get("/ops/outgoing")
    async def ops_outgoing() -> dict:
        # `now` берётся ОДИН раз: возраст самого старого задания и вердикт
        # «застряло» обязаны быть посчитаны по ОДНОМУ показанию часов.
        now = time.time()
        # Путь к базе — ТА ЖЕ функция, которой его берёт остальной инстанс
        # (свой `os.getenv` рядом стал бы вторым источником правды с ДРУГИМ
        # дефолтом, то есть однажды показал бы чужую базу).
        raw = tamapi_metrics.outgoing_raw(tamapi_dashboard._db_path())
        return outgoing_summary(raw, now=now)

    return api
