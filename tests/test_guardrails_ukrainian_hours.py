# -*- coding: utf-8 -*-
"""Украинские ЧАСЫ как единица срока в `chatter.core.guardrails`.

Замер на живом проде (2026-08-16, ветка до правки):

    «Зробимо за 3 години.»  -> findings: ['price']      # срок увиден КАК ЦЕНА
    «Зробимо за 3 часа.»    -> findings: ['deadline']   # по-русски — как срок
    _context_numbers('Тривалість полірування — 6–10 годин') -> (set(), set())

Корень: «година» начинается на `год`, а этот стем в `_TIME_UNIT` занят русским
«год» (= year) и закрыт явными окончаниями + `\\b`. Украинские часы не попадают
ни в `_TIME_UNIT`, ни в `_TIME_UNIT_STEMS`, ни, как следствие, в
`_ANY_TIME_UNIT`, которым размечается knowledge.

Чем это стоит. У клиента Ярины (детейлинг) сроки в часах — ОСНОВНАЯ форма
(«тривалість 6–10 годин», «1,5–2,5 години»), поэтому дыра бьёт в ОБЕ стороны:

  A. ПРОПУСК. Бот обещает лиду «зробимо за 8 годин», в knowledge таких часов
     нет — числовой сторож молчит либо ругается не на то правило.
  B. ЛОЖНОЕ СРАБАТЫВАНИЕ (дороже). Наивный стем `годин\\w*` / `год\\w*`
     проглотит «годинник» (прибор), «годиться/годяться» (подходить),
     «годування/годувати» (кормление) — и живой лид получит МОЛЧАНИЕ или
     затёртую редакцией фразу вместо ответа.
  D. Обеспеченность обязана считаться по-настоящему: срок, который ЕСТЬ в
     knowledge, findings давать не должен, иначе «увидели» = «глушим всё».
  E. Бесчисловая ветка (`_TIME_UNIT_STEMS` + `_mentions_stem`) на слишком
     широком стеме даёт ЛОЖНОЕ «обеспечено» и ПРЯЧЕТ дефект — в проде уже
     есть комментарий ровно про эту грабку (снятый 2-символьный стем «ма»).

Сторожа написаны ОТ КОНТРАКТА и опираются на ПОСЛЕДСТВИЕ (`_findings`,
`contains_unbacked_claim`, `_context_numbers`), а не на форму регэкспа:
регэксп — реализация, последствие — контракт. Тест, повторивший допущения
реализации, зеленеет вместе с ней на неверном поведении.
"""
from __future__ import annotations

import pytest

from chatter.core.guardrails import (
    _ANY_TIME_UNIT,
    _context_numbers,
    _findings,
    contains_unbacked_claim,
)

# ---------------------------------------------------------------------------
# База знаний БЕЗ единиц времени и БЕЗ чисел: любое число/срок в ответе на ней
# необеспечен по определению.
#
# ⚠️ Слова подобраны так, чтобы не задеть уже существующие стемы `_TIME_UNIT`.
# Особенно «майстерня»: `\\bма[йя]\\w*` (месяц МАЙ) матчит «МАЙстерні», и
# knowledge с этим словом молча стал бы «срочным» фрагментом, обеспечив числа,
# которые сторож обязан был поймать. Здесь этого слова нет намеренно.
NEUTRAL = "Ми робимо детейлінг авто. Працюємо у Києві."

# Реальная форма прайса Ярины (детейлинг): сроки заданы В ЧАСАХ, включая
# дробные диапазоны.
YARINA = (
    "Детейлінг кузова.\n"
    "Полірування — тривалість 6–10 годин.\n"
    "Керамічне покриття — 1,5–2,5 години.\n"
    "Хімчистка салону — 4 години."
)

# Все падежные формы украинского «година», которые встречаются в прайсах и в
# репликах бота.
HOUR_FORMS = [
    "година", "години", "годину", "годиною", "годин",
    "годині", "годинах", "годинам", "годинами",
]

# Слова, которые НАЧИНАЮТСЯ на «годин»/«год», но единицей времени НЕ являются.
NOT_TIME_WORDS = [
    "годинник",    # часы-прибор; начинается ровно на «годин»
    "годинники",
    "годиться",    # годитися = подходить
    "годяться",
    "годування",   # кормление
    "годувати",
]


def _rules(reply: str, knowledge: str = NEUTRAL) -> set[str]:
    """Множество сработавших ПРАВИЛ — это и есть наблюдаемое последствие.

    Сравниваем правила, а не количество находок: одно и то же место ловится
    и правилом `deadline`, и проверкой чисел в ценовом предложении, поэтому
    число находок — деталь реализации, а набор правил — контракт.
    """
    return {f.rule for f in _findings(reply, knowledge)}


# ---------------------------------------------------------------------------
# A. ПРОПУСК: необеспеченный срок в часах обязан быть увиден — и увиден КАК СРОК
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("form", HOUR_FORMS)
def test_unbacked_hour_deadline_is_seen_as_deadline(form):
    """Класс ошибки: выдуманный срок в часах уезжает лиду необеспеченным.

    «Зробимо за 12 годин» при базе, где о часах не сказано ничего, обязано
    дать находку правила `deadline`. Правило важно не меньше самого факта
    находки: пока часы не единица времени, число «12» сверяется с ЦЕНОВЫМ
    множеством knowledge (замер выше: rule='price'). Значит, стоит владельцу
    положить в прайс цену «12 000», и выдуманный срок «за 12 годин» станет
    «обеспеченным» ценой — сторож промолчит на живом лиде.

    Число < 100 намеренно: иначе находку дал бы запасной backstop больших
    чисел и тест зеленел бы, не проверяя часы вовсе.
    """
    assert _rules(f"Зробимо за 12 {form}.") == {"deadline"}


@pytest.mark.parametrize("form", HOUR_FORMS)
def test_bare_hour_claim_without_number_is_seen(form):
    """Класс ошибки: бесчисловое обещание срока проходит мимо сторожа.

    «Зробимо за годину» числа не содержит, поэтому ловится отдельной веткой
    (`_DEADLINE_NO_NUM` + `_TIME_UNIT_STEMS`). Ветка независима: единицу можно
    внести в список для чисел и забыть в списке стемов — тогда числовые сроки
    в часах ловятся, а «зробимо за годину» лид получает как обещание, которого
    в базе нет. Русское «Сделаем за час» этой веткой ловится (rule=bare_unit),
    украинское обязано вести себя так же.
    """
    assert _rules(f"Зробимо за {form}.") == {"bare_unit"}


@pytest.mark.parametrize(
    "fragment, expected",
    [
        ("Тривалість полірування — 6–10 годин", {"6", "10"}),
        ("Керамічне покриття — 1,5–2,5 години", {"1,5", "2,5"}),
        ("Хімчистка салону триває 4 години", {"4"}),
        ("Робота займає одну годину", set()),
    ],
)
def test_knowledge_hours_mark_their_numbers_as_deadline(fragment, expected):
    """Класс ошибки: сроки САМОГО клиента не признаются сроками.

    `_context_numbers` размечает числа knowledge по контексту фрагмента. Если
    «годин/години» не единица времени, срочные числа прайса Ярины не попадают
    в срочное множество вообще — и её собственный, дословно верный ответ
    «полірування — 6 годин» подавляется как выдуманный. Это ровно инцидент
    P20 («21 календарний день»), только на другой морфологии.

    Последняя строка — контроль: без чисел множество пустое, тест не может
    позеленеть на том, что разметка просто сгребает всё подряд.
    """
    price, deadline = _context_numbers(fragment)
    assert deadline == expected
    assert price == set(), "во фрагменте нет ни валюты, ни ценового слова"


def test_ukrainian_hours_are_not_blinder_than_russian():
    """Класс ошибки: «починили только ту фразу, что была в тикете».

    Паритет — это и есть контракт: украинская формулировка про часы обязана
    видеться РОВНО так же, как её русский эквивалент. Тест не выдумывает
    поведение (в том числе там, где прод не ловит НИ ТУ, НИ ДРУГУЮ форму —
    напр. «Займе 40 годин» без предлога, где русское «Займет 40 часов» тоже
    даёт пусто), он лишь запрещает украинскому быть слепее русского.
    """
    pairs = [
        ("Зробимо за 3 години.", "Сделаем за 3 часа."),
        ("Зробимо через 2 години.", "Сделаем через 2 часа."),
        ("Роботу зробимо за годину.", "Работу сделаем за час."),
        ("Займе 40 годин.", "Займет 40 часов."),
    ]
    for uk, ru in pairs:
        assert _rules(uk) == _rules(ru), f"{uk!r} видится иначе, чем {ru!r}"


def test_invented_hours_reach_contains_unbacked_claim():
    """Класс ошибки: правило сработало, но булев фасад его не увидел.

    `contains_unbacked_claim` — единственная дверь, через которую сторож влияет
    на живой ответ (run.py). Проверяем последствие целиком, а не внутренности:
    срок в часах, которого нет в прайсе Ярины (8 не входит в «6–10»), обязан
    поднять флаг.
    """
    assert contains_unbacked_claim("Зробимо полірування за 8 годин.", YARINA) is True


