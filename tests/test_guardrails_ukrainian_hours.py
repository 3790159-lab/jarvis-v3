@pytest.mark.parametrize(
    "reply",
    [
        "Дякую за годинник — гарний подарунок.",
        "Ми відповідаємо за годинники у вітрині.",
        "Ми беремося за годування тварин.",
        "Ми відповідаємо за годування кота.",
    ],
)
def test_clock_and_feeding_words_after_za_are_not_deadlines(reply):
    """Класс ошибки: стем `годин\\w*`/`год\\w*` глушит живой ответ.

    Конструкция «за <слово>» — прямой вход в бесчисловую ветку срока. Если
    единицу внесли стемом, «за годинник» и «за годування» станут «обещанием
    срока, не подтверждённым базой»: ответ либо затрут редакцией
    («точний термін узгоджуємо індивідуально» вместо благодарности за
    подарок), либо подавят целиком. Лид, который ждёт, получает ТИШИНУ — а в
    логах это выглядит штатной работой предохранителя.

    Это та же грабля границы слова, из-за которой в проде стоят явные
    окончания у «год/рок/лет» и `\\b` у «ден».
    """
    assert _rules(reply) == set()


