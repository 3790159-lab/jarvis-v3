# -*- coding: utf-8 -*-
"""DEV-44: белый список бэкапа больше не держится человеческим взглядом.

ПОЧЕМУ ЭТОТ СТОРОЖ, ЕСЛИ ЕСТЬ `test_state_backup_connect_evidence.py`.
Тот пришпилил РОВНО две улики арки T7 — `connect/*.consent.md` и
`connect/*.bundle.txt`. Механики, которая заметит СЛЕДУЮЩУЮ улику того же
рода, там нет: заводится новый артефакт, автор помнит или не помнит дописать
глоб, и если не помнит — не краснеет ничего.

КЛАСС, а не случай. Улики этого рода объединяет свойство, которого нет в имени
файла: они живут ВНЕ git (`state/` в `.gitignore`) и существуют в ОДНОМ
экземпляре. Потеря обнаруживается не при потере, а через месяцы — когда
понадобится доказать согласие клиента или когда выяснится, что базлайн
регресса, с которым сверяли полгода, восстановить не из чего.

КАК УСТРОЕН СТОРОЖ. Реестр ниже — ЛИТЕРАЛЬНЫЙ список конкретных экземпляров,
а не выборка из `CRITICAL_PATTERNS`. Это принципиально: реестр, выведенный из
белого списка, согласен с ним по определению и промолчит ровно там, где тот
забыл (то же правило, что и для любых списков в этом репозитории).

ОБЕ СТОРОНЫ ОБЯЗАТЕЛЬНЫ. Белый список существует не чтобы «набрать файлов», а
чтобы в бэкап НИКОГДА не уехал секрет. Поэтому рядом с реестром улик стоит
реестр того, что уезжать не имеет права, и он проверяется так же строго:
широкий глоб вида `connect/*` прошёл бы первую половину и утащил бы
session-файл Telethon, то есть полный доступ к аккаунту клиента.

ЧТО ЛОВИТ ТРЕТИЙ ТЕСТ. Список глобов пришпилен литеральной копией. Любая
правка `CRITICAL_PATTERNS` — добавление, удаление, сужение — красит его, и
автор обязан пройти мимо реестра. Именно этого «обязан пройти мимо» и не
хватало: сторож не может знать, что новый файл на диске является уликой, но
может не дать изменить белый список молча.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from app.services import state_backup as sb

SLUG = "volska"

# ── РЕЕСТР УЛИК ──────────────────────────────────────────────────────────────
# Путь относительно `state/` + чем именно оборачивается потеря. Пути КОНКРЕТНЫЕ
# (без `*`): это экземпляры, а не глобы. Добавляя сюда запись, добавь и глоб в
# `CRITICAL_PATTERNS` — третий тест не даст сделать наоборот.
EVIDENCE: tuple[tuple[str, str], ...] = (
    (f"connect/{SLUG}.consent.md",
     "единственная запись о том, что доступ к ЛИЧНОЙ переписке аккаунта "
     "разрешён, кем и когда; без неё согласие недоказуемо"),
    (f"connect/{SLUG}.bundle.txt",
     "единственный след того, что бандл секретов пересняли после логина и "
     "какие сессии в него вошли; без него в бэкапе найдётся мёртвый auth"),
    ("users.json",
     "реестр людей, которых бот знает; восстановить неоткуда"),
    ("cost_tracking.json",
     "накопленный счёт по моделям; без него нельзя сказать, во что обошёлся "
     "месяц, и любой спор о цене становится словом против слова"),
    ("regress_baseline.json",
     "эталон регресса; потеряв его, теряем право говорить «стало хуже» — "
     "сравнивать не с чем"),
    ("dev_tasks/log.jsonl",
     "журнал задач: что запускалось, чем кончилось; единственный след"),
    ("personas/personas.json",
     "реестр персон; ключи и центроиды пересобирать дороже, чем хранить"),
)

# ── ЧТО УЕЗЖАТЬ НЕ ИМЕЕТ ПРАВА ───────────────────────────────────────────────
# Первые две записи — соседи улик по каталогу `connect/`, ради которых глобы
# и сделаны УЗКИМИ по хвосту имени. Остальные — секреты, лежащие в `state/`.
MUST_NOT_TRAVEL: tuple[tuple[str, str], ...] = (
    (f"connect/{SLUG}.session",
     "session-файл Telethon = полный доступ к аккаунту клиента"),
    (f"connect/{SLUG}.md",
     "человеческий журнал подключения; свидетельством не является"),
    ("api_keys.json", "ключи"),
    ("ig_accounts.json", "учётки Instagram"),
    ("google_oauth_token.json", "живой токен"),
    ("connect/secrets_bundle.zip", "бандл секретов целиком"),
)

# ── ПРИШПИЛЕННЫЙ БЕЛЫЙ СПИСОК ────────────────────────────────────────────────
# Литеральная копия. Не выводить из `sb.CRITICAL_PATTERNS` ни при каких
# обстоятельствах: выведенная копия равна оригиналу по определению и не
# краснеет никогда.
PINNED_PATTERNS: tuple[str, ...] = (
    "users.json",
    "cost_tracking.json",
    "daily_metrics.json",
    "regress_baseline.json",
    "personas/personas.json",
    "personas/expenses.jsonl",
    "personas/*/arcface_centroid.npy",
    "expenses/persona_video.jsonl",
    "jarvis_brain/*.json",
    "dev_tasks/*.json",
    "dev_tasks/log.jsonl",
    "dev_tasks/*/report.md",
    "connect/*.consent.md",
    "connect/*.bundle.txt",
)


def _state_tree(tmp_path: Path) -> Path:
    """`state/`, где улики и запрещённое лежат ВПЕРЕМЕШКУ, как на живом диске."""
    root = tmp_path / "state"
    for rel, _why in EVIDENCE + MUST_NOT_TRAVEL:
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(f"содержимое {rel}", encoding="utf-8")
    return root


@pytest.mark.parametrize("rel,why", EVIDENCE, ids=[e[0] for e in EVIDENCE])
def test_every_evidence_in_the_registry_actually_reaches_the_backup(tmp_path, rel, why):
    """Каждая запись реестра обязана быть покрыта хотя бы одним глобом."""
    root = _state_tree(tmp_path)
    picked = {p.relative_to(root).as_posix() for p in sb.discover_backup_files(root)}
    assert rel in picked, (
        f"улика `{rel}` НЕ уезжает в бэкап, хотя числится в реестре.\n"
        f"Чем оборачивается потеря: {why}.\n"
        f"Почини `CRITICAL_PATTERNS` в app/services/state_backup.py — или, если "
        f"улика перестала быть уликой, убери её из реестра ОСОЗНАННО."
    )


@pytest.mark.parametrize("rel,why", MUST_NOT_TRAVEL, ids=[e[0] for e in MUST_NOT_TRAVEL])
def test_nothing_from_the_forbidden_list_reaches_the_backup(tmp_path, rel, why):
    """Вторая половина важнее первой: белый список не имеет права утечь."""
    root = _state_tree(tmp_path)
    picked = {p.relative_to(root).as_posix() for p in sb.discover_backup_files(root)}
    assert rel not in picked, (
        f"`{rel}` УЕЗЖАЕТ в бэкап, а не имеет права: {why}.\n"
        f"Скорее всего кто-то расширил глоб до каталога (`connect/*`) вместо "
        f"узкого хвоста имени (`connect/*.consent.md`)."
    )


def test_the_allowlist_is_pinned_so_the_next_evidence_cannot_slip_in_unnoticed():
    """Любая правка белого списка обязана пройти мимо реестра улик.

    Сторож не может знать, что новый файл на диске — улика. Но может не дать
    изменить белый список молча: правка красит этот тест, и автор, поправляя
    копию, видит реестр выше.
    """
    assert sb.CRITICAL_PATTERNS == PINNED_PATTERNS, (
        "белый список бэкапа изменился.\n"
        "Это не ошибка сама по себе — но прежде чем поправить PINNED_PATTERNS, "
        "ответь на вопрос DEV-44: появилась ли улика, живущая ВНЕ git и в ОДНОМ "
        "экземпляре? Если да — допиши её в EVIDENCE выше. Если глоб расширили — "
        "проверь MUST_NOT_TRAVEL: не утащит ли он соседей по каталогу.\n"
        f"было:  {PINNED_PATTERNS}\n"
        f"стало: {sb.CRITICAL_PATTERNS}"
    )


def test_the_registry_is_a_list_of_instances_not_a_copy_of_the_globs():
    """Реестр обязан быть литеральным, иначе он согласен с кодом по определению.

    Тонкость, на которой этот тест сам себя поправил при написании: глоб без
    подстановки (`users.json`) СОВПАДАЕТ со своим экземпляром — это свойство
    глобов, а не признак копирования. Поэтому «ни одна запись не встречается в
    белом списке» проверять нельзя, такое правило красит честный реестр.
    Признак независимости другой: в реестре обязаны быть записи, которые ни
    одному глобу не равны и покрываются ТОЛЬКО через подстановку. Копия
    белого списка такого не даст никогда.
    """
    for rel, _why in EVIDENCE:
        assert "*" not in rel, (
            f"запись реестра `{rel}` — это ГЛОБ, а не экземпляр. Реестр, "
            f"повторяющий глобы, проверяет глобы сами на себя."
        )
    only_by_wildcard = [rel for rel, _ in EVIDENCE if rel not in sb.CRITICAL_PATTERNS]
    assert only_by_wildcard, (
        "каждая запись реестра дословно равна какому-то глобу — значит реестр "
        "переписан с белого списка и молчит ровно там, где тот забыл."
    )


def test_every_evidence_has_a_reason_that_names_what_becomes_unprovable():
    """Запись без причины через полгода не отличить от случайного файла."""
    for rel, why in EVIDENCE:
        assert len(why) >= 40, f"у `{rel}` причина слишком короткая, чтобы объяснить потерю"
