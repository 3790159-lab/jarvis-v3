# -*- coding: utf-8 -*-
"""DEV-35: дата в ценовом предложении — это СРОК, а не выдуманная цена.

Класс ошибки, доказанный замером на живом конфиге Ярины 17.08:

    «Так, акція діє до 30 вересня 2026 року.»                    -> []      ✅
    «Акція діє до 30 вересня 2026 року: при замовленні двоетапного
     полірування (8 000–13 000 грн)…»                            -> price   🔴

То есть **чем полнее бот пересказывал акцию, тем вернее его ответ глушился** —
дефект наказывал за правильное поведение. Корень: предложение вправе нести
несколько видов чисел разом, а год попадал в «слова-заполнители» между числом
и единицей времени и уезжал сверяться с ЦЕНОВЫМ множеством.

Сторожа стоят на ПОСЛЕДСТВИИ (`_findings`), а не на форме регэкспа: регэксп —
реализация. Половина файла — негативный контроль: правка обязана оставить
выдуманные цены и сроки пойманными, иначе она лечит подавление ценой слепоты.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from chatter.core.guardrails import _context_numbers, _findings

REPO_ROOT = Path(__file__).resolve().parent.parent

# База с акцией и прайсом — форма живого клиента: год в дате, цены в гривнах.
PROMO_KNOWLEDGE = (
    "Двоетапне полірування кузова — 8 000–13 000 грн.\n"
    "Керамічне покриття кузова — 8 000–15 000 грн.\n"
    "Антидощ для скла — 1 000–2 000 грн.\n"
    "Акція діє до 30 вересня 2026 року: при замовленні двоетапного полірування "
    "разом із керамічним покриттям антидощ у подарунок.\n"
)

# База БЕЗ дат и БЕЗ чисел: на ней любая цифра ответа необеспечена.
NEUTRAL = "Ми робимо детейлінг авто. Працюємо у Києві."


def rules(reply: str, knowledge: str = PROMO_KNOWLEDGE) -> set[str]:
    return {f.rule for f in _findings(reply, knowledge)}


# ══ ТО, ЧТО ЧИНИТСЯ ════════════════════════════════════════════════════════

def test_the_full_promo_sentence_is_not_a_price_finding():
    """Ловит: подавление ответа за ПОЛНЫЙ пересказ акции.

    Ровно эта реплика на живом конфиге давала `_Finding(number='2026',
    rule='price')`, и лид, спросивший про акцию, получал молчание.
    """
    reply = ("Акція діє до 30 вересня 2026 року: при замовленні двоетапного "
             "полірування (8 000–13 000 грн) разом із керамічним покриттям "
             "(8 000–15 000 грн) антидощ на лобове скло у подарунок.")
    assert rules(reply) == set(), sorted(rules(reply))


def test_the_short_promo_form_stays_clean_too():
    """Парная: короткая форма была чиста и ДО правки. Если она покраснеет,
    правка сломала то, что работало."""
    assert rules("Так, акція діє до 30 вересня 2026 року.") == set()


def test_a_year_and_a_price_in_one_sentence_do_not_fight():
    """Требование владельца: предложение вправе нести НЕСКОЛЬКО видов чисел,
    а не выбирать один. Цена сверяется с ценами, дата — со сроками."""
    assert rules("У 2026 році двоетапне полірування коштує 8 000–13 000 грн.") == set()


def test_a_day_at_a_ukrainian_month_is_a_date_not_a_price():
    """Ловит: день месяца, сверенный с прайсом.

    Украинские месяцы в `_TIME_UNIT` не значатся (там только русские), поэтому
    «30 вересня» в ценовом предложении проверялось как цена. Это тот же дефект,
    что с годом, только на соседнем числе.
    """
    assert rules("Акція діє до 30 вересня, ціна 8 000–13 000 грн.") == set()


# ══ НЕГАТИВНЫЙ КОНТРОЛЬ: выдуманное обязано ловиться ═══════════════════════

def test_an_invented_price_is_still_caught():
    """Главный риск правки — вылечить подавление ценой слепоты."""
    assert "price" in rules("Полірування коштує 9 999 грн.")


def test_an_invented_deadline_is_still_caught():
    assert "deadline" in rules("Зробимо за 12 годин.", NEUTRAL)


def test_an_invented_discount_is_still_caught():
    assert "price" in rules("Дам знижку 35%.")


def test_a_year_shaped_number_used_as_a_PRICE_is_still_caught():
    """Ловит: правило «год — не цена», которое запретило бы законную цену.

    «2026 грн» — это цена, а не дата: рядом валюта, а не слово года. Правка
    опознаёт дату ПО СОСЕДСТВУ, и это единственное, что отличает её от
    запрета, который сделал бы сторож слепым на целый диапазон сумм.
    """
    assert "price" in rules("Знижка 2026 грн на керамічне покриття.")


def test_a_price_that_looks_like_a_year_range_is_still_checked():
    """Тот же класс на диапазоне: «1 999–2 026 грн» — деньги, не годы."""
    assert "price" in rules("Ціна 1 999–2 026 грн за пакет.")


def test_a_date_does_not_make_the_whole_sentence_supported():
    """Ловит: дату, превращённую в индульгенцию.

    Если появление даты начнёт «обеспечивать» соседние числа, бот сможет
    назвать любую цену, приписав к ней «до 30 вересня 2026 року».
    """
    assert "price" in rules("Акція діє до 30 вересня 2026 року: полірування 4 444 грн.")


# ══ НЕЙТРАЛЬНОСТЬ ДЛЯ ОСТАЛЬНЫХ КЛИЕНТОВ ══════════════════════════════════

def test_the_knowledge_parser_is_untouched():
    """Ловит: правку, поехавшую в разбор БАЗЫ.

    Правка обязана менять только то, какие числа ОТВЕТА считаются срочными.
    Множества обеспеченных чисел базы — общий вход для всех четырёх живых
    клиентов, и сдвиг там поменял бы поведение везде разом.
    """
    price, deadline = _context_numbers(PROMO_KNOWLEDGE)
    assert {"8000", "13000", "15000", "1000", "2000"} <= price, sorted(price)
    assert "2026" in deadline, sorted(deadline)


@pytest.mark.parametrize("reply,expect", [
    ("SMM-ведення — 750–900 $.", set()),
    ("Упаковка — 300–400 $.", set()),
    ("Пакет коштує 7 777 $.", {"price"}),
])
def test_a_client_without_any_dates_behaves_exactly_as_before(reply, expect):
    """Ольга (агентство) дат в базе не держит вовсе. Её ответы обязаны вести
    себя ровно как до правки — это и есть проверка ширины."""
    knowledge = ("SMM-ведення — 750–900 $. Ціна за місяць.\n"
                 "Упаковка — 300–400 $.\n")
    got = {f.rule for f in _findings(reply, knowledge)}
    assert got & {"price", "deadline"} == expect, sorted(got)


# ══ ЗАМЕР НА ЖИВОМ ФАЙЛЕ (спека §6, шаг 3) ════════════════════════════════

def test_the_live_yarina_promo_line_is_clean():
    """Тот самый замер, с которого начался DEV-35 — на НАСТОЯЩЕМ файле клиента.

    Фикстуры выше описывают форму; здесь проверяется, что дефект ушёл именно
    там, где он жил. Файл клиента не в git — если его нет, тест честно
    пропускается, а не зеленеет молча.
    """
    know_path = REPO_ROOT / "chatter" / "clients" / "yarina" / "knowledge.md"
    if not know_path.is_file():
        pytest.skip(f"конфиг живого клиента недоступен: {know_path}")
    knowledge = know_path.read_text(encoding="utf-8")
    line = next((ln for ln in knowledge.splitlines() if "Акція діє до" in ln), None)
    assert line, "строка акции пропала из живого knowledge — замер потерял предмет"

    reply = (f"{line.strip()} при замовленні двоетапного полірування "
             "(8 000–13 000 грн) разом із керамічним покриттям "
             "(8 000–15 000 грн) антидощ на лобове скло у подарунок.")
    assert {f.rule for f in _findings(reply, knowledge)} == set()
