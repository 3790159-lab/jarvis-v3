def test_the_split_really_separates_declaration_from_verification():
    """Без него весь этот файл мог бы искать подстроки в ОДНОМ куске текста и
    снова стать слепым к семи мутациям: «объявлено» и «перечитано» — разные
    утверждения, и доказывать их обязаны разные куски скрипта."""
    declaration = _declaration_block()
    verification = _verification_block()
    assert LIVE_READ not in declaration, (
        f"блок объявления содержит `{LIVE_READ}` — разрез не состоялся, и "
        "«объявлено» доказывается тем же текстом, что «перечитано»")
    assert "New-ScheduledTaskPrincipal" not in verification, (
        "блок перечитывания содержит объявление принципала — значит задача "
        "создаётся ПОСЛЕ того, как её прочитали, либо разрез не там")
    assert declaration.strip() and verification.strip(), (
        f"один из блоков пуст: объявление {len(declaration)} символов, "
        f"перечитывание {len(verification)}")


_PLANTED_BLIND = '''\
$reg = Get-ScheduledTask -TaskName X -ErrorAction Stop
$problems = @()
if ($reg.State -ne 'Ready') { $problems += "LogonType=$($reg.Principal.LogonType), expected S4U" }
$trig = @($reg.Triggers)[0]
if ($trig.Enabled) { $problems += "trigger is $($trig.CimClass.CimClassName), expected MSFT_TaskWeeklyTrigger" }
'''


def test_the_message_text_is_not_mistaken_for_a_check():
    """Без него сторожа ниже были бы зелены по построению: образец НИЧЕГО не
    проверяет по делу, но говорит нужные слова в тексте ошибки — ровно так
    22.08 проехали семь мутаций подряд."""
    raw = _PLANTED_BLIND
    for token in ("S4U", "MSFT_TaskWeeklyTrigger", ".Principal.LogonType"):
        assert token in raw, f"образец не о том: в нём нет {token!r}"

    assertive = _assertive_text(raw)
    for token in ("S4U", "MSFT_TaskWeeklyTrigger", ".Principal.LogonType"):
        assert token not in assertive, (
            f"{token!r} попал в текст ПРОВЕРОК, хотя в образце он есть только "
            f"в сообщении об ошибке.\nЧто сочтено проверкой:\n{assertive}\n"
            "Сторож, читающий сообщение как проверку, слеп к мутации самой "
            "проверки: сломанное сравнение продолжает рассказывать о себе "
            "прежними словами")

    for token in (".State", ".Enabled", ".Triggers"):
        assert token in assertive, (
            f"{token!r} — это то, что образец РЕАЛЬНО читает и сравнивает, а "
            f"разбор его потерял.\nЧто сочтено проверкой:\n{assertive}\n"
            "Сторож, теряющий настоящие сравнения, покраснеет на исправном "
            "скрипте и заставит автора править не то")


