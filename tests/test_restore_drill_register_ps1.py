def test_registration_does_not_run_the_drill():
    """Проехало бы молча: регистрация сама сходила в живой R2. Живое чтение —
    отдельный осознанный шаг владельца (граница §4.4); в тексте `schtasks
    /Run` допустим ТОЛЬКО как печатаемая подсказка."""
    bad = []
    for ln in _code_lines():
        if not re.search(r"schtasks\s+/Run|Start-ScheduledTask\b", ln):
            continue
        if re.search(r"Write-(Host|Output|Information|Warning)", ln):
            continue  # подсказка в выводе — это не запуск
        bad.append(ln.strip())
    assert not bad, f"регистрация запускает дрил сама: {bad}"


