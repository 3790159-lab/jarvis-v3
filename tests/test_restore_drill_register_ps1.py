# -*- coding: utf-8 -*-
"""Контракт регистрации JarvisRestoreDrill (DEV-46 §4.3, §9.2, §9.4).

Сторож написан ОТ СПЕКИ и держит то, ЧТО будет зарегистрировано. Саму
регистрацию делает владелец руками отдельным шагом, поэтому здесь нет ни
`schtasks`, ни `Register-ScheduledTask`, ни `Get-ScheduledTask`: проверяется
ТЕКСТ скрипта, а не живой Планировщик. Прогон сторожа не имеет права
трогать машину.

Почему проверка по тексту вообще имеет смысл (образец —
tests/test_state_backup_register_ps1.py): деплой гардиана 25.07 показал, что
`Register-ScheduledTask` возвращает успех, а Планировщик молча оставляет
старое определение. Код возврата не доказывает НИЧЕГО; доказывает только
перечитанное живое определение и `throw` на расхождении. Значит скрипт обязан
содержать это перечитывание в своём тексте — и вот это здесь и сторожится.

Отдельная причина именно для дрила (§9.2, §9.4): задача живёт не на той
машине, где сторож, и её отсутствие видно пробе как `drill_never` —
состояние, у которого лечение противоположно `drill_failed`. Незаведённая
или неработоспособная задача приезжает в сторож как красная лампа при
исправном бэкапе, а такая лампа приучает не читать красное вовсе
([[jarvis-ask-bridge-auto-allow-suspect]]).

🔴 ПОЧЕМУ «ПОДСТРОКА ЕСТЬ В ФАЙЛЕ» ЗДЕСЬ НЕ СТОРОЖ. Мутационный гейт 22.08
показал 7 слепых мутаций из 19, и класс у всех один: **одна и та же подстрока
стоит в ДВУХ местах** — в объявлении задачи и в её же перечитывании, а внутри
перечитывания ещё и в тексте сообщения об ошибке:

    if ($reg.Principal.LogonType -ne 'S4U') { $problems += "... expected S4U" }

Сломай сравнение — сообщение оставит сторожа зелёным. Сломай объявление —
зелёным оставит сравнение. Поэтому здесь всё разбирается ПО МЕСТУ:

* `_declaration_block` — то, из чего задачу СОЗДАЮТ (до `Get-ScheduledTask`);
* `_assertive_text` — то, чем живую задачу ПРОВЕРЯЮТ: условия `if (...)` и
  присваивания, но НЕ накопление сообщений (`$problems += "..."`). Сообщение
  повторяет слово сравнения и является рассказом о проверке, а не проверкой;
* `_printed_text` — то, что владелец РЕАЛЬНО видит на экране. Порядок
  действий, оставшийся только в комментарии шапки, ему не поможет: комментарий
  читает тот, кто открыл файл, а не тот, кто запустил скрипт.

Списки требований ниже — ЛИТЕРАЛЬНЫЕ и правятся человеком. Выведенный из
скрипта список согласен с ним по определению и молчит ровно там, где скрипт
забыл ([[jarvis-literal-lists-not-introspection]]).
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
REGISTER = REPO_ROOT / "scripts" / "register_restore_drill.ps1"

# Строка, на которой скрипт переходит от СОЗДАНИЯ задачи к её ПЕРЕЧИТЫВАНИЮ.
LIVE_READ = "Get-ScheduledTask"

_IF_COND = re.compile(r"^\s*(?:els)?if\s*\((?P<cond>.+)\)\s*\{")
_MESSAGE_ADD = re.compile(r"^\s*\$\w+\s*\+=")
_ASSIGN = re.compile(r"^\s*\$[\w.]+\s*=")
_WRITE_HOST = re.compile(r"Write-(?:Host|Output|Information|Warning)\s+(?P<said>.*)$")


def _text() -> str:
    # Файла нет == КРАСНОЕ, а не пропуск: «не смогли проверить» и «проверили,
    # всё чисто» — разные вещи ([[jarvis-blocked-verdict-swallows-the-red]]).
    assert REGISTER.is_file(), (
        f"скрипта регистрации нет: {REGISTER} — сторожить нечего, "
        "а значит задача JarvisRestoreDrill не заведена ничем")
    return REGISTER.read_text(encoding="utf-8-sig", errors="replace")


def _code_lines(text: str | None = None) -> list[str]:
    """Строки БЕЗ комментариев: комментарий описывает механику, а не является
    ею; сторож на комментарий красится от переформулировки."""
    src = _text() if text is None else text
    return [ln for ln in src.splitlines() if not ln.lstrip().startswith("#")]


def _split(text: str | None = None) -> tuple[list[str], list[str]]:
    """Разрезать скрипт на блок ОБЪЯВЛЕНИЯ и блок ПЕРЕЧИТЫВАНИЯ.

    Разрез — по первому обращению к живой задаче. Всё до него создаёт задачу,
    всё после проверяет, что Планировщик создал именно её."""
    lines = _code_lines(text)
    for i, ln in enumerate(lines):
        if LIVE_READ in ln:
            return lines[:i], lines[i:]
    raise AssertionError(
        f"в {REGISTER} нет ни одного `{LIVE_READ}` — живая задача не "
        "перечитывается вовсе, и «Register-ScheduledTask вернул успех» "
        "остаётся единственным доказательством. 25.07 показал, чего оно стоит")


def _declaration_block(text: str | None = None) -> str:
    return "\n".join(_split(text)[0])


def _verification_block(text: str | None = None) -> str:
    return "\n".join(_split(text)[1])


def _assertive_text(text: str | None = None) -> str:
    """Проверки живой задачи БЕЗ рассказов о них.

    Берутся условия `if (...)` и присваивания; накопление сообщений
    (`$problems += "…"`) выбрасывается. Именно оно повторяет сравниваемое
    слово и делает сторожа на подстроку слепым: мутируешь сравнение —
    сообщение оставляет тебя зелёным."""
    parts: list[str] = []
    for ln in _split(text)[1]:
        cond = _IF_COND.match(ln)
        if cond:
            parts.append(cond.group("cond"))
            continue
        if _MESSAGE_ADD.match(ln):
            continue
        if _ASSIGN.match(ln):
            parts.append(ln.strip())
    return "\n".join(parts)


def _printed_text(text: str | None = None) -> str:
    """То, что владелец видит на экране, — и только оно."""
    said = [m.group("said") for m in
            (_WRITE_HOST.search(ln) for ln in _code_lines(text)) if m]
    return "\n".join(said)


def _resolved_vars(text: str) -> set[str]:
    """Переменные, в которые положен РАЗОБРАННЫЙ путь (`Resolve-Path`)."""
    return set(re.findall(r"\$(\w+)\s*=\s*\(?\s*Resolve-Path", text))


def _anchors(text: str, groups: dict) -> list:
    low = text.lower()
    return [name for name, words in groups.items()
            if any(w.lower() in low for w in words)]


