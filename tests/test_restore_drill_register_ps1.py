def test_script_encoding_contract():
    """Проехало бы молча (до первого запуска): не-ASCII без UTF-8 BOM — и
    PS 5.1 читает файл как windows-1251 и умирает в парсере. Проверяем
    БАЙТАМИ: догадка «тут вроде латиница» и есть способ это пропустить."""
    assert REGISTER.is_file(), f"скрипта регистрации нет: {REGISTER}"
