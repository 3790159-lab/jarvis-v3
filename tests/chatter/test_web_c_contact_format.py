def test_guardD4_myortvoe_obeshchanie_pro_sleduyushchuyu_arku_snyato():
    """Сторож Д4: обещание «трёхсегментный формат вводит СЛЕДУЮЩАЯ арка»
    снято, а не осталось висеть текстом.

    Сегодня оно записано в модуле трижды: в докстринге модуля («на формате
    ..., который вводит следующая арка»), в комментарии над `SEGMENTS_TODAY`
    и в самом тексте отказа `_parts` («Трёхсегментный формат вводит следующая
    арка — она же снимет этот запрет»). Следующая арка — эта.

    🔴 Мёртвое обещание в докстринге через полгода читается как ЖИВОЕ. Хуже
    того, текст отказа уходит владельцу и в лог: отказ, объясняющий поведение
    ссылкой на работу, которая уже сделана, — это ложный след при разборе
    инцидента.

    Константа `SEGMENTS_TODAY = 2` судится отдельно и по той же причине: пока
    в модуле живёт число «2», названное «сегодня», кто-то будет сверяться с
    ним, а не с форматом. КАК снимать — дело реализации; сторож требует
    только, чтобы двойка перестала быть правилом."""
    import ast
    from pathlib import Path

    path = Path(contact_ref.__file__)
    src = path.read_text(encoding="utf-8-sig")

    stale = re.findall(r"[^.\n]*следующ\w*\s+арк\w*[^.\n]*", src, re.I)
    assert not stale, (
        "в `%s` осталось обещание про следующую арку — %r. Эта арка и есть "
        "следующая: обещание либо выполнено (и текст снимается тем же "
        "коммитом), либо не выполнено — и тогда красное здесь честнее "
        "зелёного." % (path.name, stale))

    tree = ast.parse(src)
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id == "SEGMENTS_TODAY":
                val = node.value
                literal = val.value if isinstance(val, ast.Constant) else None
                raise AssertionError(
                    "в модуле жива константа `SEGMENTS_TODAY = %r`. Она — "
                    "предмет запрета, который эта арка снимает: пока число "
                    "«сегодня» лежит в коде, разбор будет сверяться с ним, а "
                    "не с форматом." % (literal,))
