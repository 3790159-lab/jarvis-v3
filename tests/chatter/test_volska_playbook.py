# --- дрил 2026-07-23 18:34: «я напишу вам завтра» ---------------------------
def test_never_promise_to_write_first():
    """Форензика дрила 1: раннер чисто событийный (только NewMessage(incoming)
    запускает ответ; фоновые циклы — heartbeat/autoresume/config-watch — лидам
    не пишут), follow-up арка НЕ смержена. Значит обещание Ольги «я напишу вам
    завтра» (18:34:12) физически невыполнимо: молчание = ігнор лида. Playbook
    обязан запрещать обещать инициативу от Ольги и давать переворот инициативы
    («напишіть, щойно будете готові»)."""
    low = PLAYBOOK.casefold()
    assert "не обіцяти написати перш" in low or "не обіцяти писати перш" in low, (
        "нет правила «не обіцяти написати першою»")
    # переворот инициативы: клиенту предлагаем написать самому
    assert "щойно будете готові" in low or "ініціатив" in low, (
        "нет шаблона переворота инициативы на клиента")


# --- клиент перебил своим вопросом: не переспрашивать механически ------------
def test_unanswered_question_is_not_mechanically_repeated():
    """Ольга задала уточнение, клиент на него не ответил — перебил своим
    вопросом. Механический переспрос («так яка все ж таки сфера?») звучит
    как бот, который не слушает: свой вопрос он держит в голове, а чужой —
    нет. Правило: двигаться по вопросу клиента, а нужное уточнение вплетать
    в следующий естественный шаг, а не требовать отдельно."""
    low = PLAYBOOK.casefold()
    assert "не перепитуй" in low, "нет запрета механически переспрашивать"
    assert "перебив" in low, "не описан сам случай (клиент перебил своим вопросом)"
    # уточнение не выбрасываем — вплетаем в следующий шаг
    assert "вплети" in low or "вплітай" in low, (
        "нет требования вплести уточнение в следующий естественный шаг")


def test_unanswered_question_rule_keeps_the_next_step_alive():
    """Переход к вопросу клиента не отменяет правило «без глухого кута»:
    уточнение возвращается в диалог, а не теряется навсегда."""
    # берём именно СЕКЦИЮ правила (от её заголовка до следующего "## "),
    # а не окно вокруг слова: слово встречается в тексте не один раз.
    low = PLAYBOOK.casefold()
    start = low.index("не перепитуй")
    section = low[start:].split("\n## ", 1)[0]
    assert "уточненн" in section, (
        "в секции правила не сказано, что делать с потерянным уточнением")
    assert "вплети" in section or "вплітай" in section
    assert "відповідь на його питання" in section or "відповідь на йог" in section, (
        "не сказано, что сперва отвечаем на вопрос клиента")
