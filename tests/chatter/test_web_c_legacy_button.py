"""Сторожа 17-20 спеки «ВЕБ, волна 2 / пара C» — СТАРАЯ КНОПКА.

Спека: `docs/superpowers/specs/2026-08-28-web-c-envelope-identity.md`,
§3.4, §4.4 п.7, §9 (сторожа 17-20).

ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ. `callback_data` кнопок, улетевших владельцу ДО миграции,
живёт в его чате месяцами и тапабельно всё это время. Замер §3.4: живых
карточек с флагом `esc_active` — 5 у demo и 2 у yarina. Без единственной
двери для старой формы семь живых кнопок владельца становятся НЕМЫМИ тапами:
`route_callback` на неизвестный тап отвечает «без мутаций», то есть отказом
БЕЗ следа для того, кто жмёт.

🔴 И РОВНО ПОЭТОМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ МЯГКИЙ РЕЖИМ ВНУТРИ `peer_of`
(§3.4): (а) `peer_of` остаётся строгим, и сторож 20 это пинит; (б) её можно
будет удалить ОДНИМ куском, когда старые кнопки истекут.

⚠️ ГДЕ ЖИВЁТ ФУНКЦИЯ, СПЕКА НЕ ГОВОРИТ. §3.4 называет её имя дословно
(`upgrade_legacy_callback_contact`) и место применения (`route_callback`), но
не модуль. Поэтому ниже — литеральный список ДОПУСТИМЫХ домов с причиной на
каждый, и требование, чтобы дом был РОВНО ОДИН: функция в двух модулях —
это два разных послабления, которые разъедутся молча.
"""
from __future__ import annotations

import importlib

import pytest

from chatter.core import contact_ref
from chatter.storage.db import Store

# Куда §3.4 могла её положить. Литерально, с причиной — угадывать за спеку
# нельзя, а искать по всему дереву значит принять любой ответ.
LEGACY_HOMES = {
    "chatter.core.contact_ref":
        "единственная точка правды об устройстве contact_id: послабление — "
        "это знание о СТАРОЙ форме, и оно того же предмета",
    "chatter.payments.callbacks":
        "реестр версий формата callback_data: «кнопка, улетевшая в Telegram, "
        "тапабельна через месяцы и legacy-форму придётся понимать всегда» — "
        "своими словами дома",
}

FN = "upgrade_legacy_callback_contact"

OLD = "12345:volska"
NEW = "telegram:12345:volska"


def _upgrade():
    """Функция апгрейда старой формы — или ГРОМКИЙ отказ с адресом §3.4."""
    found = []
    for mod_name in LEGACY_HOMES:
        try:
            mod = importlib.import_module(mod_name)
        except ImportError:
            continue
        fn = getattr(mod, FN, None)
        if fn is not None:
            found.append((mod_name, fn))
    assert found, (
        "функции `%s` нет ни в одном из допустимых домов (%s). §3.4 называет "
        "её ИМЯ дословно и требует ОТДЕЛЬНОЙ названной функции, а не мягкого "
        "режима внутри `peer_of`: (а) строгость разбора обязана остаться "
        "пинуемой, (б) послабление обязано удаляться одним куском, когда "
        "старые кнопки истекут — временность записана в самом имени."
        % (FN, ", ".join(LEGACY_HOMES)))
    assert len(found) == 1, (
        "`%s` объявлена в %d модулях (%s). Два послабления на одну вещь "
        "разъедутся молча, и удалять их придётся дважды — а забудут один."
        % (FN, len(found), ", ".join(m for m, _ in found)))
    return found[0][1]


# ═══ Сторож 17 ══════════════════════════════════════════════════════════════

@pytest.mark.parametrize("old, new", [
    (OLD, NEW),
    ("237616472:volska", "telegram:237616472:volska"),
    ("8849893367:yarina", "telegram:8849893367:yarina"),
    ("-1001234567890:demo", "telegram:-1001234567890:demo"),
])
def test_guard17_staraya_forma_podnimaetsya_do_tryohsegmentnoy(old, new):
    """Сторож 17: `upgrade_legacy_callback_contact("12345:volska")` даёт
    `"telegram:12345:volska"`.

    Безопасно это ровно потому, что до миграции ВСЕ существовавшие contact_id
    были телеграмными: 12 из 12 контактов в обеих базах, голова числовая у
    всех (§1.1). Отрицательная голова (группа) — тоже живая форма, и допуск
    ведущего `-` назван §3.4 отдельно."""
    got = _upgrade()(old)
    assert got == new, (
        "%s(%r) вернул %r, ждали %r. Промах здесь — это немой тап по живой "
        "кнопке владельца: действия не будет, и следа для того, кто жмёт, "
        "тоже." % (FN, old, got, new))


# ═══ Сторож 18 ══════════════════════════════════════════════════════════════

@pytest.mark.parametrize("bad, why", [
    ("web:abc:volska", "УЖЕ трёхсегментная — поднимать нечего"),
    ("telegram:12345:volska", "уже мигрированная — второй апгрейд её сломает"),
    ("abc:volska", "голова НЕЧИСЛОВАЯ: до миграции таких не существовало"),
    ("", "пусто"),
    ("volska", "один сегмент"),
    ("12345", "один сегмент, число"),
    (":volska", "пустая голова"),
    ("12345:", "пустой хвост"),
    ("12:34:56:volska", "четыре сегмента"),
])
def test_guard18_vsyo_prochee_eto_otkaz_a_ne_dogadka(bad, why):
    """Сторож 18: правило узкое — РОВНО два сегмента И числовая голова (с
    допуском ведущего `-`). Всё прочее — `None`, то есть отказ, а не догадка.

    Широкое правило здесь дороже узкого: апгрейд, применённый ко ВСЕМУ, что
    похоже на contact_id, превратит `web:abc:volska` в
    `telegram:web:abc:volska` — форму, которой нет ни в одной базе, и тап
    уйдёт в никуда уже по НАШЕЙ вине, а не по вине старой кнопки."""
    got = _upgrade()(bad)
    assert got is None, (
        "%s(%r) вернул %r вместо None (%s). §3.4: «Всё прочее — None, то есть "
        "отказ, а не догадка»." % (FN, bad, got, why))


# ═══ Сторож 19 ══════════════════════════════════════════════════════════════

def test_guard19_staraya_knopka_nahodit_MIGRIROVANNYY_kontakt(tmp_path):
    """Сторож 19: `route_callback` на `callback_data` СТАРОГО вида находит
    мигрированный контакт и совершает действие.

    Это ЕДИНСТВЕННОЕ место применения апгрейда (§3.4), и приёмка §4.4 п.7
    называет его отдельным шагом плана: «тап по карточке, отправленной ДО
    миграции, обязан сработать. Она — единственный носитель старой формы,
    переживший шаг 4».

    Меряем ИСХОД по базе: снята ли пауза с МИГРИРОВАННОГО контакта. Проверка
    «функция вернула какой-то текст» здесь ничего не значит — на неизвестный
    тап она тоже возвращает текст (`fb_unknown`), просто ничего не делает."""
    from chatter.notify.control_bot import route_callback

    with Store(tmp_path / "legacy.db") as store:
        store.get_or_create_contact(NEW)
        store.mute(NEW, source="command", until=None, now=1000.0)
        assert store.get_or_create_contact(NEW)["paused"], (
            "предпосылка стенда: контакт заглушён, иначе «пауза снята» "
            "проверять не на чем")

        route_callback("resume:" + OLD, store=store, now=2000.0, language="ru",
                       snooze_seconds=3600.0)

        row = store.get_or_create_contact(NEW)
        assert not row["paused"], (
            "тап по СТАРОЙ кнопке `resume:%s` не снял паузу с мигрированного "
            "контакта %r. Это и есть немой тап: владелец жмёт, ничего не "
            "происходит, и следа для него нет — `route_callback` на "
            "неизвестный тап отвечает «без мутаций»." % (OLD, NEW))


def test_guard19_musor_v_callback_data_ne_mutiruet_nichego(tmp_path):
    """Сторож 19, вторая половина: на мусоре не мутируется НИЧЕГО.

    Без неё апгрейд легко «починить» широким правилом, которое поднимает до
    трёх сегментов всё подряд: тогда мусорный тап начнёт находить чужой
    контакт и снимать паузу с него. Это хуже немого тапа: немой ничего не
    делает, а этот делает НЕ ТО."""
    from chatter.notify.control_bot import route_callback

    with Store(tmp_path / "garbage.db") as store:
        store.get_or_create_contact(NEW)
        store.mute(NEW, source="command", until=None, now=1000.0)
        for data in ("resume:", "resume:мусор", "resume:abc:volska",
                     "нетакого:12345:volska", ""):
            route_callback(data, store=store, now=2000.0, language="ru",
                           snooze_seconds=3600.0)
        assert store.get_or_create_contact(NEW)["paused"], (
            "мусорный тап снял паузу с %r: апгрейд поднимает до трёх сегментов "
            "то, чего поднимать нельзя, и тап стал попадать в ЧУЖОЙ контакт."
            % (NEW,))


# ═══ Сторож 20 ══════════════════════════════════════════════════════════════

@pytest.mark.parametrize("fname", ["peer_of", "slug_of", "channel_of"])
def test_guard20_poslablenie_NE_proteklo_v_strogiy_razbor(fname):
    """Сторож 20: `peer_of` на двухсегментной форме ПО-ПРЕЖНЕМУ бросает —
    сторож 11 не отменён апгрейдом.

    Самая дешёвая правка под сторожа 17-19 — сделать разбор терпимым к двум
    сегментам «раз уж мы всё равно умеем их понимать». Тогда послабление,
    заведённое ради СТАРЫХ КНОПОК, начнёт действовать на пути АДРЕСАЦИИ: код
    молча заработает на немигрированной базе, разъезд двух форм перестанет
    быть заметным, и один человек заживёт двумя контактами.

    Граница дома тут уже проведена и записана (`peer_label_of`): значение,
    которое АДРЕСУЕТ, — fail-closed; значение, которое ПОДПИСЫВАЕТ, —
    деградирует. Апгрейд старой кнопки живёт на третьей стороне: он не
    адресует и не подписывает, он ПЕРЕВОДИТ, и потому он отдельная функция."""
    fn = getattr(contact_ref, fname, None)
    assert fn is not None, (
        "в `contact_ref` нет `%s` — сторож 20 не может доказать, что "
        "послабление не протекло, а его зелёный цвет ничего не значит." % fname)
    with pytest.raises(ValueError):
        fn(OLD)


def test_guard20_apgreyd_i_strogiy_razbor_zhivut_v_RAZNYH_imenah():
    """Сторож 20, вторая половина: апгрейд — ОТДЕЛЬНОЕ имя, а не необязательный
    аргумент строгого разбора.

    `peer_of(x, legacy_ok=True)` выполнило бы сторожа 17-19 буквой и снесло бы
    их смыслом: удалить послабление «одним куском», когда кнопки истекут,
    стало бы нельзя — пришлось бы искать всех, кто передаёт флаг. §3.4 требует
    именно отдельную НАЗВАННУЮ функцию, и временность записана в её имени."""
    fn = _upgrade()
    assert getattr(fn, "__name__", "") == FN, (
        "функция апгрейда зовётся %r, а §3.4 называет её %r. Имя — часть "
        "договора: по нему её найдут в день, когда старые кнопки истекут."
        % (getattr(fn, "__name__", None), FN))
    for fname in ("peer_of", "slug_of", "channel_of", "telegram_peer_of"):
        target = getattr(contact_ref, fname, None)
        if target is None:
            continue
        import inspect

        params = list(inspect.signature(target).parameters)
        assert len(params) == 1, (
            "`contact_ref.%s` принимает %r: у строгого разбора появился второй "
            "аргумент. Послабление, спрятанное в флаг, нельзя будет удалить "
            "одним куском — придётся искать всех, кто его передаёт."
            % (fname, params))
